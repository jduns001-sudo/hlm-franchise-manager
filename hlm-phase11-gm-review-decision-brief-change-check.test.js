'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {assessGMReviewRiskBriefReadiness}=require('./hlm-phase11-gm-review-risk-brief-readiness');
const {checkGMReviewDecisionBriefChange:check}=require('./hlm-phase11-gm-review-decision-brief-change-check');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const riskDigest=assessGMReviewRiskBriefReadiness(items,digest,true,1000,[1100,1200],500).currentSha256;
const initial=check(items,digest,true,1000,[1100,1200],500,riskDigest);
assert.equal(initial.status,'unverified');assert.equal(initial.requiresFreshGMReview,true);
const same=check(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256);
assert.equal(same.status,'unchanged');assert.equal(same.readyForHumanReview,true);assert.equal(same.requiresFreshGMReview,false);
assert.equal(check(items,digest,true,1000,[1100,1501],500,riskDigest,initial.currentSha256).status,'changed');
assert.equal(check(items,digest,true,1000,[1100,1200],500,riskDigest,'0'.repeat(64)).status,'changed');
assert.equal(check(items,digest,true,1000,[1100,1200],500,riskDigest,'bad').status,'unverified');
assert.equal(check(items,'0'.repeat(64),true,1000,[1100,1200],500,riskDigest,initial.currentSha256).readyForHumanReview,false);
assert.equal(check([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256).readyForHumanReview,false);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(same[key],false);
assert.equal(same.requiresGMApproval,true);assert.ok(Object.isFrozen(same));
assert.deepEqual(check(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256),same);
console.log('GM review decision brief change check deterministic tests passed');
