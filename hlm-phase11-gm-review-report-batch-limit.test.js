'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {renderBoundedGMReview,MAX_ITEMS,MAX_EVIDENCE_CHARS}=require('./hlm-phase11-gm-review-report-batch-limit');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const valid=renderBoundedGMReview([{before:a.text,after:b.text}]);
assert.equal(valid.accepted,true);assert.ok(valid.evidenceChars>0);assert.ok(valid.evidenceChars<=MAX_EVIDENCE_CHARS);
assert.equal(renderBoundedGMReview([]).reason,'batch-size-limit');
assert.equal(renderBoundedGMReview(Array.from({length:MAX_ITEMS+1},()=>({before:a.text,after:b.text}))).reason,'batch-size-limit');
assert.equal(renderBoundedGMReview([{before:'x'.repeat(MAX_EVIDENCE_CHARS),after:'x'}]).reason,'evidence-size-limit');
assert.equal(renderBoundedGMReview([{before:1,after:b.text}]).reason,'invalid-batch-shape');
const malformed=renderBoundedGMReview([{before:'{',after:b.text}]);
assert.equal(malformed.accepted,false);assert.equal(malformed.page,null);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(valid[key],false);
assert.equal(valid.requiresGMApproval,true);assert.ok(Object.isFrozen(valid));
assert.deepEqual(renderBoundedGMReview([{before:a.text,after:b.text}]),valid);
console.log('Bounded GM review deterministic tests passed');
