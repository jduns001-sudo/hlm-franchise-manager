'use strict';
const assert=require('node:assert/strict');
const records=require('./cpu-audit-review-evidence-timeline-record');
const presentation=require('./cpu-audit-review-evidence-timeline-presentation');
const bundles=require('./cpu-audit-review-evidence-record-timeline-bundle');
const gates=require('./cpu-audit-review-evidence-record-timeline-gate');
const api=require('./cpu-audit-review-evidence-record-timeline-verification');
const summary={kind:'cpu-audit-public-review-evidence-timeline-summary',readOnly:true,count:2,reviewCount:0,reviewStateChanges:0,transitionCount:1};
const record=records.create({kind:'cpu-audit-public-review-evidence-timeline-bundle',readOnly:true,summary,text:presentation.describe(summary)});
const bundle=bundles.build([record,record]);
const gate=gates.assess(bundle);
const verified=api.verify(bundle,gate);
assert.equal(verified.consistent,true);
assert.equal(verified.requiresHumanReview,false);
assert.equal(verified.snapshotCount,2);
assert.ok(Object.isFrozen(verified));
assert.deepEqual(api.check(bundle),verified);
assert.throws(()=>api.verify(bundle,{...gate,requiresHumanReview:true}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,reasons:['forged']}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,snapshotCount:3}),TypeError);
assert.throws(()=>api.verify({...bundle,text:'forged'},gate),TypeError);
const empty=bundles.build([]);
assert.equal(api.check(empty).requiresHumanReview,true);
console.log('Aggregate review evidence record timeline verification tests passed');
