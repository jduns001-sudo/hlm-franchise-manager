'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const {create}=require('./hlm-phase11-isolated-single-game');
const {overview}=require('./hlm-phase11-isolated-season-dashboard');
const mem=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>mem.get(k)??null,setItem:(k,v)=>mem.set(k,v)};
const engine={createBrowserFranchiseSaveStore,applyScheduledGame,simulateNextDay,calculateStandings};
const teams=[{id:1,name:'GM'},{id:2,name:'CPU'}];
const games=Array.from({length:12},(_,i)=>({id:'game-'+i,date:'2026-10-'+String(i+19).padStart(2,'0'),homeTeamId:i%2?2:1,awayTeamId:i%2?1:2,status:'scheduled'}));
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams,games});
const m=create(engine,storage);m.stage(state,true);
assert.equal(overview(m.load(),engine).upcoming.length,8);
assert.equal(overview(m.load(),engine).scheduledCount,12);
for(let day=0;day<6;day++){
 const review=m.reviewNextDay();assert.equal(review.games,1);
 const before=mem.get(m.key);
 assert.throws(()=>m.advanceNextDay(1341,false),/approval/);assert.equal(mem.get(m.key),before);
 const result=m.advanceNextDay(1341,true);
 assert.equal(result.results.length,1);assert.equal(overview(result.state,engine).completedCount,day+1);
 assert.equal(overview(result.state,engine).scheduledCount,11-day);
 const recovered=create(engine,storage);
 assert.equal(overview(recovered.load(),engine).completedCount,day+1);
}
const stale=create(engine,storage);const active=create(engine,storage);active.advanceNextDay(1341,true);
assert.throws(()=>stale.advanceNextDay(1341,true),/changed/);
assert.equal(overview(active.load(),engine).completedCount,7);
assert.equal(mem.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
assert.equal(overview(null,engine),null);
assert.throws(()=>overview(state,engine,51),/limit/);
const tieState=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[...teams,{id:3,name:'Rival'}],games:[{id:'z-game',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'scheduled'},{id:'a-game',date:'2026-10-19',homeTeamId:1,awayTeamId:3,status:'scheduled'}]});
const tieMem=new Map([[m.key,JSON.stringify(tieState)]]);
const tieStorage={getItem:k=>tieMem.get(k)??null,setItem:(k,v)=>tieMem.set(k,v)};
const tieManager=create(engine,tieStorage);
assert.equal(tieManager.seasonPostgameContext().nextGameId,'a-game','same-date GM matchup ordering must use game ID as a deterministic tie-breaker');
const html=fs.readFileSync('hlm-phase11-isolated-single-game.html','utf8');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];assert.equal(scripts.length,1);
assert.doesNotThrow(()=>new Function(scripts[0][1]));
assert.match(html,/id="season-dashboard"/);
console.log('Isolated season dashboard: six chronological days, results, upcoming games, reload, stale conflict and production isolation passed');
