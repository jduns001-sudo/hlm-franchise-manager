'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createSequentialIsolatedCPUTradeCandidates}=require('./hlm-phase9-cpu-trade-sequence');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}]});
const before=JSON.stringify(state);
const trade=(from,to,id)=>({teamIds:[from,to],legs:[{fromTeamId:from,toTeamId:to,assets:[{type:'player',id:'p1',ownerTeamId:from}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:id});
const steps=[{teamId:'BUF',trade:trade('BUF','NYR','trade-1')},{teamId:'NYR',trade:trade('NYR','BOS','trade-2')}];
const result=createSequentialIsolatedCPUTradeCandidates(state,steps);
assert.equal(result.candidateState.universe.players[0].teamId,'BOS');
assert.deepEqual(result.candidateState.activity.transactions.map(t=>t.id),['trade-1','trade-2']);
assert.equal(result.steps.length,2);
assert.equal(result.candidateOnly,true);
assert.equal(result.persistencePerformed,false);
assert.equal(JSON.stringify(state),before);
assert.throws(()=>createSequentialIsolatedCPUTradeCandidates(state,[steps[0],{teamId:'NYR',trade:trade('NYR','BOS','trade-1')}]),e=>e.code==='CPU_TRADE_TRANSACTION_ID_DUPLICATE');
assert.throws(()=>createSequentialIsolatedCPUTradeCandidates(state,[steps[0],{teamId:'NYR',trade:trade('BUF','BOS','trade-2')}]),e=>e.code==='CPU_TRADE_OWNERSHIP_MISMATCH');
assert.throws(()=>createSequentialIsolatedCPUTradeCandidates(state,[steps[0],{teamId:'PIT',trade:trade('NYR','PIT','trade-2')}]),e=>e.code==='CPU_TRADE_HUMAN_TEAM_PROTECTED');
assert.throws(()=>createSequentialIsolatedCPUTradeCandidates(state,[]),e=>e.code==='CPU_TRADE_SEQUENCE_EMPTY');
assert.equal(JSON.stringify(state),before);
console.log('Phase 9 sequential isolated CPU trade candidate tests passed');
