'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createIsolatedSeasonStore:create}=require('./hlm-phase11-isolated-season-atomic-store');
const data=new Map();
let failKey=null;
const adapter={read:key=>data.has(key)?data.get(key):null,write:(key,value)=>{if(key===failKey){failKey=null;throw Error('Simulated storage interruption')}data.set(key,value)},remove:key=>data.delete(key)};
const store=create(adapter);
const state=createGameStateEnvelope({meta:{saveId:'isolation-test',controlledTeamId:1,currentDate:'2026-10-12'},teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],players:[],games:[]});
assert.equal(store.productionActivationEnabled,false);
assert.throws(()=>create(adapter,{key:'hlm_front_office_v8'}),/Isolated/);
assert.equal(store.load(),null);
store.save(state);
assert.equal(store.load().meta.currentDate,'2026-10-12');
assert.equal(data.has(store.key+'-journal'),false);
assert.throws(()=>store.advance(1),/confirmation/);
const day=store.advance(1,{confirmed:true});
assert.equal(day.saved,true);
assert.equal(store.load().meta.currentDate,'2026-10-13');
const current=JSON.stringify(store.load());
const stale=JSON.stringify(state);
assert.throws(()=>store.save(state,{expectedRaw:stale}),/Stale/);
assert.equal(JSON.stringify(store.load()),current);
const candidate=JSON.parse(current);candidate.meta.currentDate='2026-10-14';
failKey=store.key;
assert.throws(()=>store.save(candidate),/Simulated storage interruption/);
assert.equal(JSON.stringify(store.load()),current);
assert.equal(store.hasPendingRecovery(),false);
const old=adapter.read(store.key);
adapter.write(store.key+'-backup',old);
adapter.write(store.key+'-journal',JSON.stringify({pending:true}));
adapter.write(store.key,JSON.stringify(candidate));
assert.throws(()=>store.load(),/Recovery required/);
assert.throws(()=>store.advance(1,{confirmed:true}),/Recovery required/);
assert.equal(store.recover().recovered,true);
assert.equal(JSON.stringify(store.load()),current);
assert.equal(store.recover().recovered,false);
assert.equal([...data.keys()].some(k=>k.includes('hlm_front_office')),false);
console.log('Phase 11 isolated atomic season persistence, stale conflict, interruption rollback and recovery passed');
