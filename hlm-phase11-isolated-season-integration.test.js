'use strict';
const assert=require('node:assert/strict');
const {createStager}=require('./hlm-phase11-isolated-day-stage');
const {createController}=require('./hlm-phase11-isolated-season-advance');
const {review}=require('./hlm-phase11-recovery-season-review');
const {simulateGameScore}=require('./hlm-phase10-game-simulator');
const {exportCheckpoint,previewRestore}=require('./hlm-phase11-isolated-recovery');
const scheduled={id:'game1',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'scheduled'};
let state={meta:{controlledTeamId:1,currentDate:'2026-10-18'},universe:{teams:[{id:1,name:'Portland'},{id:2,name:'Seattle'}],players:[{id:11,teamId:1,name:'Player'}]},activity:{games:[scheduled]},privateNotes:'NEVER_EXPORT'};
let revision=0,writes=0;
const store={isolated:true,loadRevision(){return revision},saveIfRevision(next,expected){if(revision!==expected)return false;state=JSON.parse(JSON.stringify(next));revision++;writes++;return true}};
const bridge=createStager(()=>state,simulateGameScore);
const controller=createController(bridge,{review},store);
const preview=controller.preview([11]);assert.equal(preview.review.pending,1);
const staged=bridge.prepareIsolatedAdvance(123);assert.equal(staged.simulatedGames,1);assert.equal(writes,0);assert.equal(state.activity.games[0].status,'scheduled');
assert.throws(()=>controller.advance(false,123,[11],0),/approval/);assert.equal(writes,0);
const result=controller.advance(true,123,[11],0);assert.equal(result.review.completed,1);assert.equal(result.review.pending,0);assert.equal(result.revision,1);assert.equal(writes,1);
assert.throws(()=>controller.advance(true,123,[11],0),/Stale/);assert.equal(writes,1);
const recovered=previewRestore(exportCheckpoint(state));assert.equal(recovered.state.activity.games[0].status,'final');assert.equal(review(recovered.state,[11]).completed,1);assert(!JSON.stringify(recovered).includes('NEVER_EXPORT'));
console.log('Integrated isolated stage, approve, save, recover, standings regression passed');
