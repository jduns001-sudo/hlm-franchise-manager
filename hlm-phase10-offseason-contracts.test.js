'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {expireOffseasonContracts}=require('./hlm-phase10-offseason-contracts');
const state=createGameStateEnvelope({contracts:[{contractId:'a',teamId:1,status:'active'},{id:'b',teamId:2,status:'active'}]});
const before=JSON.stringify(state);
const {nextState,summary}=expireOffseasonContracts(state,['a']);
assert.equal(summary.expiredCount,1);
assert.equal(summary.unchangedCount,1);
assert.deepEqual(summary.expiredContractIds,['a']);
assert.equal(nextState.assets.contracts[0].status,'expired');
assert.equal(nextState.assets.contracts[1].status,'active');
assert.equal(JSON.stringify(state),before);
assert.throws(()=>expireOffseasonContracts(nextState,['a']),/already expired/);
assert.throws(()=>expireOffseasonContracts(state,['a','a']),/Duplicate/);
assert.throws(()=>expireOffseasonContracts(state,['missing']),/missing or ambiguous/);
assert.throws(()=>expireOffseasonContracts(state,null),/array/);
assert.equal(expireOffseasonContracts(state,[]).summary.expiredCount,0);
console.log('Phase 10 offseason contract tests passed');
