'use strict';
/* Mission 1588 extension: exercise the existing guarded save engine after source-backed handoff. */
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {calculateStandings}=require('./hlm-phase10-standings');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {create:managerCreate}=require('./hlm-phase11-isolated-single-game');
const {create:handoffCreate}=require('./hlm-phase11-m1588-next-season-game-continuity');
const data=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value)};
const engine={applyScheduledGame,calculateStandings,createBrowserFranchiseSaveStore};
const manager=managerCreate(engine,storage);
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2027-10-01'},teams:[{id:1,name:'GM Club'},{id:2,name:'Opponent'}],games:[{id:'next-season-gm-game',date:'2027-10-02',homeTeamId:1,awayTeamId:2,status:'scheduled'}]});
state.extensions.phase10CurrentSeasonId='2027-28';
state.history.seasons=[{seasonId:'2026-27',championTeamId:2}];
assert.throws(()=>manager.stage(state,false),/approval/);
manager.stage(state,true);
const gate=handoffCreate(()=>manager.peek());
const reviewed=gate.inspect();assert.equal(reviewed.available,true);
assert.equal(reviewed.gameId,'next-season-gm-game');
assert.equal(gate.decline().saved,false);
assert.equal(manager.peek().activity.games[0].status,'scheduled');
assert.equal(gate.inspect().available,true);
const accepted=gate.open();assert.equal(accepted.saved,false);assert.equal(accepted.target,'day-review');
assert.equal(manager.review(accepted.gameId).status,'scheduled');
const rival=managerCreate(engine,storage);
assert.throws(()=>manager.advance(accepted.gameId,1588,false),/approval/);
assert.equal(manager.peek().activity.games[0].status,'scheduled');
const saved=manager.advance(accepted.gameId,1588,true);
assert.equal(saved.result.status,'final');
assert.equal(saved.state.activity.games[0].status,'final');
assert.equal(saved.standings.find(x=>String(x.teamId)==='1').gp,1);
assert.deepEqual(saved.state.history.seasons,[{seasonId:'2026-27',championTeamId:2}]);
assert.equal(managerCreate(engine,storage).load().activity.games[0].status,'final');
assert.throws(()=>rival.advance(accepted.gameId,1588,true),/changed/);
assert.throws(()=>manager.advance(accepted.gameId,1588,true),/already played|unavailable/);
assert.equal(storage.getItem('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
console.log('Mission 1588 guarded next-season final, standings, GM approval, decline, stale tab, reload, history and production isolation PASS');
