'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const {startSeasonPlayoffs}=require('./hlm-phase10-season-playoffs');
const {simulateNextPlayoffGame}=require('./hlm-phase10-playoff-simulation');
const {create}=require('./hlm-phase11-isolated-single-game');
const engine={createBrowserFranchiseSaveStore,applyScheduledGame,simulateNextDay,calculateStandings,startSeasonPlayoffs,simulateNextPlayoffGame};
const map=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v)};
const teams=[1,2,3,4].map(id=>({id,name:'Team '+id}));
const pairs=[[1,2],[3,4],[1,3],[2,4],[1,4],[2,3]];
const games=pairs.map(([homeTeamId,awayTeamId],i)=>({id:'r'+i,date:'2026-10-'+(19+i),homeTeamId,awayTeamId,status:'scheduled'}));
const manager=create(engine,storage);
manager.stage(createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams,games}),true);
assert.throws(()=>manager.startPlayoffs(true),/unplayed/);
for(let i=0;i<6;i++)manager.advanceNextDay(1350,true);
assert.throws(()=>manager.startPlayoffs(false),/approval/);
const stale=create(engine,storage);
const started=manager.startPlayoffs(true);
assert.equal(started.bracket.status,'active');
assert.equal(started.seeds.length,4);
assert.throws(()=>manager.startPlayoffs(true),/already initialized/);
assert.throws(()=>stale.advancePlayoff(1350,true),/changed/);
assert.throws(()=>manager.advancePlayoff(1350,false),/approval/);
let count=0;
while(manager.load().extensions.phase10Playoffs.status==='active'){
 const before=manager.load().extensions.phase10Playoffs;
 const after=manager.advancePlayoff(1350+count,true);
 assert.notDeepEqual(after.bracket,before);
 assert.equal(create(engine,storage).load().extensions.phase10Playoffs.status,after.bracket.status);
 assert.equal(map.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
 if(++count>21)throw Error('Playoff progression did not terminate');
}
const final=manager.load();
assert.equal(final.activity.games.filter(g=>g.status==='final').length,6);
assert.equal(final.activity.games.filter(g=>g.status==='scheduled').length,0);
assert.equal(final.extensions.phase10Playoffs.status,'complete');
assert.ok(final.extensions.phase10Playoffs.championTeamId!=null);
assert.throws(()=>manager.advancePlayoff(1350,true),/No active playoff bracket/);
assert.equal(map.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
console.log('Human-approved regular-season to best-of-seven playoffs through champion, reload, stale writes and save isolation passed; playoff games: '+count);
