'use strict';
const assert=require('node:assert/strict');
const {previewRosterImport,stageRosterImport}=require('./hlm-phase11-roster-import');
const teams=[{id:11,name:'Northport Wolves'},{id:12,name:'Lakeside Falcons'}];
const players=teams.flatMap(t=>['C','LW','RW','D','D','G'].map((position,i)=>({id:t.id*100+i,teamId:t.id,name:t.name+' '+i,position,ovr:70+i})));
const source={format:'hlm-phase11-roster-import-v1',teams,players};
const text=JSON.stringify(source);
const before=JSON.stringify(source);
const preview=previewRosterImport(text);
assert.equal(preview.teamCount,2);assert.equal(preview.playerCount,12);assert.equal(preview.writes,0);
const staged=stageRosterImport(text);
assert.equal(staged.meta.saveId,'phase11-roster-import-preview');
assert.equal(staged.universe.players.length,12);
staged.universe.players[0].name='changed';
assert.equal(JSON.stringify(source),before,'Staging must not mutate input');
const broken=JSON.parse(text);broken.players[0].teamId=999;
assert.throws(()=>previewRosterImport(JSON.stringify(broken)),/Invalid player/);
const dup=JSON.parse(text);dup.players[1].id=dup.players[0].id;
assert.throws(()=>previewRosterImport(JSON.stringify(dup)),/Invalid player/);
const noGoalie=JSON.parse(text);noGoalie.players[5].position='C';
assert.throws(()=>previewRosterImport(JSON.stringify(noGoalie)),/goalie/);
assert.throws(()=>previewRosterImport('{bad'),/valid JSON/);
assert.throws(()=>previewRosterImport(JSON.stringify({...source,format:'unknown'})),/Unsupported/);
assert.throws(()=>stageRosterImport(text,{startDate:'not-a-date'}),/Invalid start date/);
console.log('Phase 11 roster import preview validation passed.');
