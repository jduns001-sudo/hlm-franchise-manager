'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {simulateGameScore}=require('./hlm-phase10-game-simulator');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {create}=require('./hlm-phase11-isolated-single-game');
const teams=[{id:1},{id:2}],games=[{id:'g1',homeTeamId:1,awayTeamId:2,date:'2026-10-19',status:'scheduled'}];
const skaters=[{id:12,teamId:1,position:'C',overall:95},{id:13,teamId:1,position:'LW',overall:95},{id:14,teamId:1,position:'D',overall:95}];
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams,games,players:[{id:11,teamId:1,position:'G',overall:80},...skaters,{id:21,teamId:2,position:'G',overall:80}]});
state.extensions.phase11GmGoaliePlan={playerId:11,teamId:1};
const seed=1372,legacy=applyScheduledGame(state,'g1',seed);
const before=JSON.stringify(state);
assert.deepEqual(legacy.result,simulateGameScore({gameId:'g1',homeTeamId:1,awayTeamId:2,seed}));
const experimental=applyScheduledGame(state,'g1',seed,{experimentalRosterAware:true});
assert.equal(experimental.result.experimentalRosterAware,true);
assert.equal(experimental.result.official,false);
assert.equal(experimental.result.homeGoals,legacy.result.homeGoals+1);
assert.equal(experimental.result.awayGoals,legacy.result.awayGoals);
assert.deepEqual(applyScheduledGame(state,'g1',seed,{experimentalRosterAware:true}).result,experimental.result);
assert.equal(JSON.stringify(state),before);
const day=simulateNextDay(state,seed,{experimentalRosterAware:true});
assert.deepEqual(day.results[0],experimental.result);
assert.deepEqual(day.standings,calculateStandings(day.nextState.universe.teams,day.nextState.activity.games));
assert.equal(day.nextState.activity.games[0].official,false);
const injured=JSON.parse(JSON.stringify(state));injured.activity.injuries=[{playerId:12,status:'out'}];
const injuredResult=applyScheduledGame(injured,'g1',seed,{experimentalRosterAware:true}).result;
assert.equal(injuredResult.homeGoals,legacy.result.homeGoals,'two healthy skaters cannot trigger roster modifier');
assert.equal(injuredResult.awayGoals,legacy.result.awayGoals);
assert.equal(injuredResult.experimentalRosterAware,true,'approved goalie-only experiment remains nonofficial');
const weak=JSON.parse(JSON.stringify(state));for(const p of weak.universe.players)if([12,13,14].includes(p.id))p.overall=50;
const weakResult=applyScheduledGame(weak,'g1',seed,{experimentalRosterAware:true}).result;
assert.equal(weakResult.homeGoals,Math.max(0,legacy.result.homeGoals-1));
const invalid=JSON.parse(JSON.stringify(state));invalid.extensions.phase11GmGoaliePlan=null;
assert.throws(()=>applyScheduledGame(invalid,'g1',seed,{experimentalRosterAware:true}),/approval/);
assert.throws(()=>simulateGameScore({gameId:'g1',homeTeamId:1,awayTeamId:2,seed,experimentalVerifiedSkaterAverage:95,experimentalVerifiedSkaterSide:'home'}),/Invalid experimental verified skater/);
const data=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};
const m=create({applyScheduledGame,calculateStandings,createBrowserFranchiseSaveStore},storage);
m.stage(state,true);
assert.throws(()=>m.approveExperimentalRosterAware(true,false),/approval/);
assert.equal(m.approveExperimentalRosterAware(true,true),true);
const saved=m.advance('g1',seed,true);
assert.deepEqual(saved.result,experimental.result);
assert.equal(data.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
const disabled=new Map(),storage2={getItem:k=>disabled.get(k)??null,setItem:(k,v)=>disabled.set(k,v)};
const m2=create({applyScheduledGame,calculateStandings,createBrowserFranchiseSaveStore},storage2);
m2.stage(state,true);assert.deepEqual(m2.advance('g1',seed,true).result,legacy.result);
console.log('Mission 1372: verified healthy rated skaters, deterministic day/game, default-off, GM approval, privacy and save isolation pass');
