'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const {startSeasonPlayoffs}=require('./hlm-phase10-season-playoffs');
const {simulateNextPlayoffGame}=require('./hlm-phase10-playoff-simulation');
const {finalizeChampionshipSeason}=require('./hlm-phase10-season-finalization');
const {completeOffseasonAndStartSeason}=require('./hlm-phase10-complete-offseason');
const {create}=require('./hlm-phase11-isolated-single-game');
const engine={createBrowserFranchiseSaveStore,applyScheduledGame,simulateNextDay,calculateStandings,startSeasonPlayoffs,simulateNextPlayoffGame,finalizeChampionshipSeason,completeOffseasonAndStartSeason};
const backing=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>backing.get(k)??null,setItem:(k,v)=>backing.set(k,v)};
const teams=[1,2,3,4].map(id=>({id,name:'Club '+id,leagueId:'premier'}));
const players=teams.flatMap(t=>Array.from({length:23},(_,i)=>({id:'player-'+t.id+'-'+i,teamId:t.id,name:'Player '+t.id+' '+i,position:i<2?'G':i<9?'D':'F',overall:65+i%20,age:20+i%15})));
const prospects=Array.from({length:8},(_,i)=>({id:'prospect-'+i,name:'Prospect '+i,overall:55+i,potential:'Elite'}));
const contracts=players.map((p,i)=>({contractId:'contract-'+i,playerId:p.id,teamId:p.teamId,aav:1000000+i*1000,years:2,status:'active'}));
const draftPicks=Array.from({length:8},(_,i)=>({pickId:'pick-'+i,currentOwnerId:i%4+1,status:'available'}));
const games=[[1,2],[3,4],[1,3],[2,4],[1,4],[2,3]].map(([homeTeamId,awayTeamId],i)=>({id:'2026-'+i,date:'2026-10-'+(19+i),homeTeamId,awayTeamId,status:'scheduled'}));
const initial=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18',saveId:'multi-year-fixture'},teams,players,prospects,contracts,draftPicks,games,finances:{currency:'USD',leagueCap:95000000,clubs:teams.map(t=>({teamId:t.id,balance:15000000}))}});
const manager=create(engine,storage);manager.stage(initial,true);
const initialFinances=JSON.stringify(initial.finances);
const originalIds=players.map(p=>p.id);
function finishSeason(id,seed){
 for(let day=0;day<8&&manager.load().activity.games.some(g=>g.status==='scheduled');day++)manager.advanceNextDay(seed+day,true);
 assert.ok(manager.load().activity.games.every(g=>g.status==='final'));
 manager.startPlayoffs(true,4,7);
 let count=0;
 while(manager.load().extensions.phase10Playoffs.status==='active'){
  manager.advancePlayoff(seed+count,true);
  if(++count>21)throw Error('Playoff bracket did not terminate');
 }
 const archived=manager.archiveSeason(id,true);
 assert.equal(archived.summary.seasonId,id);
 return archived.summary.championTeamId;
}
const firstChampion=finishSeason('2026-27',1353);
const old=backing.get(manager.key);
const options={contracts:{expiredContractIds:['contract-0'],signings:[{contractId:'replacement-0',playerId:'player-1-0',teamId:1,aav:2000000,years:3,season:'2027-28',capLimit:95000000}]},draftSelections:[{pickId:'pick-0',prospectId:'prospect-0',teamId:1}],nextSeason:{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01',cycles:2}};
const review=manager.reviewOffseason(options);
assert.equal(backing.get(manager.key),old);
assert.equal(review.playerCount,undefined);
assert.equal(review.summary.signings,1);
assert.throws(()=>manager.approveReviewedOffseason(false),/approval/);
assert.equal(backing.get(manager.key),old);
const stale=create(engine,storage);
manager.approveReviewedOffseason(true);
assert.throws(()=>stale.startNextSeason(options,true),/changed/);
let state=manager.load();
assert.equal(state.assets.contracts.find(c=>c.contractId==='contract-0').status,'expired');
assert.equal(state.assets.contracts.find(c=>c.contractId==='replacement-0').status,'active');
assert.equal(state.assets.draftPicks.find(p=>p.pickId==='pick-0').selectedProspectId,'prospect-0');
assert.equal(state.universe.prospects.find(p=>p.id==='prospect-0').draftedByTeamId,1);
assert.equal(JSON.stringify(state.finances),initialFinances);
assert.deepEqual(state.universe.players.map(p=>p.id),originalIds);
const secondChampion=finishSeason('2027-28',2353);
const before=backing.get(manager.key);
const secondOptions={contracts:{expiredContractIds:['contract-1'],signings:[]},draftSelections:[{pickId:'pick-1',prospectId:'prospect-1',teamId:2}],nextSeason:{completedSeasonId:'2027-28',nextSeasonId:'2028-29',startDate:'2028-10-01',cycles:2}};
assert.throws(()=>manager.reviewOffseason({...secondOptions,draftSelections:[{pickId:'pick-0',prospectId:'prospect-1',teamId:1}]}),/already used/);
assert.equal(backing.get(manager.key),before);
assert.throws(()=>manager.approveReviewedOffseason(true),/Review offseason/);
manager.reviewOffseason(secondOptions);manager.approveReviewedOffseason(true);
const recovered=create(engine,storage),snapshot=recovered.careerSnapshot(),saved=recovered.load();
assert.equal(snapshot.completedSeasons.length,2);
assert.deepEqual(snapshot.completedSeasons.map(s=>s.seasonId),['2026-27','2027-28']);
assert.deepEqual(snapshot.completedSeasons.map(s=>s.championTeamId),[firstChampion,secondChampion]);
assert.equal(snapshot.seasonId,'2028-29');
assert.equal(snapshot.controlledTeamId,1);
assert.equal(snapshot.playerCount,92);
assert.equal(snapshot.teamCount,4);
assert.equal(snapshot.prospectCount,8);
assert.equal(snapshot.contractCount,93);
assert.equal(snapshot.usedDraftPickCount,2);
assert.equal(snapshot.scheduledGames,12);
assert.deepEqual(saved.universe.players.map(p=>p.id),originalIds);
assert.equal(JSON.stringify(snapshot.finances),initialFinances);
assert.equal(backing.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
assert.throws(()=>recovered.startNextSeason(secondOptions,true),/already initialized|unfinished|already expired/);
assert.equal(recovered.careerSnapshot().completedSeasons.length,2);
console.log('Two champions, 92-player franchise, real contracts, draft continuity, finances, owner, reload, duplicate/stale protections and production isolation passed');
