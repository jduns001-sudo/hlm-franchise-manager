'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createFranchiseSaveStore}=require('./hlm-phase10-save-store');
const {finalizeChampionshipSeason}=require('./hlm-phase10-season-finalization');
const {rolloverSavedFranchise}=require('./hlm-phase10-rollover-persistence');
const map=new Map(),adapter={read:k=>map.get(k)??null,write:(k,v)=>map.set(k,v)};
const store=createFranchiseSaveStore(adapter,'save');
const state=createGameStateEnvelope({meta:{saveId:'save',currentDate:'2027-06-20',controlledTeamId:1},teams:[{id:1,name:'Wolves'},{id:2,name:'Falcons'}],players:[{id:10,name:'A'}],contracts:[{contractId:'old',playerId:10,teamId:1,status:'active',aav:2}],prospects:[{id:'p1'}],draftPicks:[{pickId:'pick1',currentOwnerId:1}],games:[{id:'g',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:3,awayGoals:1,overtime:false}]});
state.extensions.phase10Playoffs={status:'complete',championTeamId:1,rounds:[[]]};
store.save(finalizeChampionshipSeason(state,'2026-27').nextState);
const before=map.get('save');
const opts={contracts:{expiredContractIds:['old'],signings:[{playerId:10,teamId:1,contractId:'new',aav:3,years:2,season:'2027-28',capLimit:10}]},draftSelections:[{pickId:'pick1',prospectId:'p1',teamId:1}],nextSeason:{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'}};
assert.throws(()=>rolloverSavedFranchise(adapter,'save',{...opts,nextSeason:{...opts.nextSeason,startDate:'2027-01-01'}}),/after championship/);
assert.equal(map.get('save'),before);
const result=rolloverSavedFranchise(adapter,'save',opts);
assert.equal(result.summary.season.scheduledGames,2);
assert.deepEqual(store.load(),result.nextState);
assert.equal(store.load().history.seasons.length,1);
const committed=map.get('save');
assert.throws(()=>rolloverSavedFranchise(adapter,'save',opts),/already expired/);
assert.equal(map.get('save'),committed);
console.log('Phase 10 rollover persistence tests passed');
