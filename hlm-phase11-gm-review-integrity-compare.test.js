'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {compareGMReviewIntegrity}=require('./hlm-phase11-gm-review-integrity-compare');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const items=[{before:a.text,after:b.text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const same=compareGMReviewIntegrity(items,digest);
assert.equal(same.status,'unchanged');assert.equal(same.matches,true);
const changed=compareGMReviewIntegrity(items,'0'.repeat(64));assert.equal(changed.status,'changed');assert.equal(changed.matches,false);
for(const expected of ['',null,'0'.repeat(63),'G'.repeat(64)])assert.equal(compareGMReviewIntegrity(items,expected).status,'unavailable');
assert.equal(compareGMReviewIntegrity([{before:'{',after:b.text}],digest).status,'unavailable');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(same[key],false);
assert.equal(same.requiresGMApproval,true);assert.ok(Object.isFrozen(same));
assert.deepEqual(compareGMReviewIntegrity(items,digest),same);
console.log('GM review integrity comparison deterministic tests passed');
