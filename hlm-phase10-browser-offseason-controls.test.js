'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('phase10-demo.html','utf8');
const bundle=fs.readFileSync('hlm-phase10-browser.bundle.js','utf8');
assert.match(html,/id="offseason"/);
assert.match(html,/finalizeChampionshipSeason/);
assert.match(html,/completeOffseasonAndStartSeason/);
const sandbox={};sandbox.window=sandbox;
vm.runInNewContext(bundle,sandbox,{timeout:3000});
for(const key of ['finalizeChampionshipSeason','completeOffseasonAndStartSeason'])assert.equal(typeof sandbox.HLMPhase10[key],'function',key);
const api=sandbox.HLMPhase10;
const state=api.createGameStateEnvelope({meta:{saveId:'browser-test',currentDate:'2027-06-20',controlledTeamId:1},teams:[{id:1,name:'A'},{id:2,name:'B'}],games:[{id:'g',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:2,awayGoals:1,overtime:false}]});
state.extensions.phase10Playoffs={status:'complete',championTeamId:1,rounds:[[]]};
const archived=api.finalizeChampionshipSeason(state,'2026-27').nextState;
const result=api.completeOffseasonAndStartSeason(archived,{nextSeason:{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'}});
assert.equal(result.summary.season.scheduledGames,2);
assert.equal(result.nextState.extensions.phase10CurrentSeasonId,'2027-28');
console.log('Phase 10 browser offseason bundle smoke tests passed');
