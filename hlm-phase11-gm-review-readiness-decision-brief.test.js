'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {assessGMReviewRiskBriefReadiness}=require('./hlm-phase11-gm-review-risk-brief-readiness');
const {buildGMReviewReadinessDecisionBrief:brief}=require('./hlm-phase11-gm-review-readiness-decision-brief');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const first=brief(items,digest,true,1000,[1100,1200],500);
assert.equal(first.status,'blocked');assert.match(first.lines.join(' '),/integrity-unverified-or-changed/);
const fingerprint=assessGMReviewRiskBriefReadiness(items,digest,true,1000,[1100,1200],500).currentSha256;
const ready=brief(items,digest,true,1000,[1100,1200],500,fingerprint);
assert.equal(ready.status,'ready-for-human-review');assert.equal(ready.readyForHumanReview,true);
assert.match(ready.lines.join(' '),/human GM must decide/);
const staleFingerprint=assessGMReviewRiskBriefReadiness(items,digest,true,1000,[1100,1501],500).currentSha256;
assert.equal(brief(items,digest,true,1000,[1100,1501],500,staleFingerprint).status,'blocked');
assert.equal(brief(items,'0'.repeat(64),true,1000,[1100,1200],500,fingerprint).status,'blocked');
assert.equal(brief([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500,fingerprint).status,'blocked');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(ready[key],false);
assert.equal(ready.requiresGMApproval,true);assert.ok(Object.isFrozen(ready));assert.ok(Object.isFrozen(ready.lines));
assert.deepEqual(brief(items,digest,true,1000,[1100,1200],500,fingerprint),ready);
console.log('GM review readiness decision brief deterministic tests passed');
