'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {prepareApprovedCPUTradeBatch}=require('./hlm-phase9-cpu-trade-batch-preview');
const {commitPreviewedCPUTradeBatch}=require('./hlm-phase9-cpu-trade-approved-preview-commit');
const repository=createMemorySaveRepository();
repository.save('original',createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}]}));
const original=serializeGameState(repository.load('original').state);
const trade=(from,to,id)=>({teamIds:[from,to],legs:[{fromTeamId:from,toTeamId:to,assets:[{type:'player',id:'p1',ownerTeamId:from}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:id});
const steps=[{teamId:'BUF',trade:trade('BUF','NYR','t1')},{teamId:'NYR',trade:trade('NYR','BOS','t2')}];
const preview=prepareApprovedCPUTradeBatch({repository,sourceSlotId:'original',steps,expectedSourceFingerprint:original});
const run=(changes={})=>commitPreviewedCPUTradeBatch({repository,preview,steps,destinationSlotId:'candidate',confirmCommit:true,...changes});
assert.throws(()=>run({confirmCommit:false}),e=>e.code==='CPU_PREVIEW_COMMIT_CONFIRMATION_REQUIRED');
assert.throws(()=>run({steps:[steps[0]]}),e=>e.code==='CPU_PREVIEW_COMMIT_CHANGED');
assert.throws(()=>run({destinationSlotId:'original'}),e=>e.code==='CPU_COMMIT_SOURCE_PROTECTED');
assert.equal(repository.count(),1);
const result=run();
assert.equal(result.verified,true);
assert.equal(result.previewMatched,true);
assert.equal(result.activeFranchiseSlotReplaced,false);
assert.equal(result.productionCPUExecutionEnabled,false);
assert.equal(serializeGameState(repository.load('candidate').state),preview.candidateFingerprint);
assert.equal(serializeGameState(repository.load('original').state),original);
assert.throws(()=>run(),e=>e.code==='CPU_COMMIT_DESTINATION_OCCUPIED');
const dirty=createMemorySaveRepository();
dirty.save('dirty',createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}],transactions:[{id:'existing'},{id:'existing'}]}));
const dirtyFingerprint=serializeGameState(dirty.load('dirty').state);
const dirtyPreview=prepareApprovedCPUTradeBatch({repository:dirty,sourceSlotId:'dirty',steps,expectedSourceFingerprint:dirtyFingerprint});
assert.throws(()=>commitPreviewedCPUTradeBatch({repository:dirty,preview:dirtyPreview,steps,destinationSlotId:'new',confirmCommit:true}),e=>e.code==='CPU_PREVIEW_COMMIT_DUPLICATE_HISTORY');
assert.equal(dirty.has('new'),false);
console.log('Phase 9 approved CPU trade preview commit tests passed');
