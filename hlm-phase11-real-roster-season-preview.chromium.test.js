'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),http=require('node:http'),path=require('node:path');
const {chromium}=require('playwright');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {previewRosterCareer}=require('./hlm-phase11-real-roster-season-preview');
const server=http.createServer((req,res)=>{const name=decodeURIComponent((req.url||'/').split('?')[0].slice(1));if(!/^[\w.-]+$/.test(name))return res.writeHead(404).end();fs.readFile(path.join(__dirname,name),(e,b)=>{if(e)return res.writeHead(404).end();res.setHeader('Content-Type',name.endsWith('.js')?'text/javascript':'text/html');res.end(b)})});
(async()=>{await new Promise(ok=>server.listen(0,'127.0.0.1',ok));const browser=await chromium.launch();try{
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block'});
await page.goto('http://127.0.0.1:'+server.address().port+'/hlm-phase11-isolated-single-game.html');
const teams=[1,2,3,4].map(id=>({id,name:'Club '+id}));
const players=teams.flatMap(t=>Array.from({length:23},(_,i)=>({id:t.id*100+i,teamId:t.id,position:['C','LW','RW','D','D','G'][i%6],ovr:70+i%10})));
const contracts=players.map((p,i)=>({contractId:'c'+i,playerId:p.id,teamId:p.teamId,status:'Active'}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const games=[[1,2],[3,4],[1,3],[2,4],[1,4],[2,3]].map(([homeTeamId,awayTeamId],i)=>({id:'g'+i,date:'2026-10-'+(20+i),homeTeamId,awayTeamId,status:'scheduled'}));
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-19'},teams,players,contracts,injuries,games,finances:{teamSnapshots:Object.fromEntries(teams.map(t=>[t.id,{cash:5000000}]))}});
const preview=previewRosterCareer(state,{offseason:{contracts:{expiredContractIds:[],signings:[]},draftSelections:[]}});
assert.equal(preview.nextState.history.seasons.length,1);
assert.equal(preview.official,false);
await page.evaluate(()=>localStorage.setItem('hlm_front_office_v8','PRODUCTION_SENTINEL'));
await page.locator('#file').setInputFiles({name:'experimental-career.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(preview.nextState))});
await page.waitForFunction(()=>!document.querySelector('#import').disabled);
page.once('dialog',d=>d.accept());await page.locator('#import').click();
await page.waitForFunction(()=>document.querySelector('#career-continuity')?.textContent.includes('"playerCount": 92'));
await page.reload();
const snapshot=JSON.parse(await page.locator('#career-continuity').innerText());
assert.equal(snapshot.completedSeasons.length,1);
assert.equal(snapshot.playerCount,92);
assert.equal(snapshot.contractCount,92);
assert.equal(snapshot.seasonId,'2027-28');
assert.equal(await page.evaluate(()=>localStorage.getItem('hlm_front_office_v8')),'PRODUCTION_SENTINEL');
console.log('Mobile imported nonofficial roster-weighted career preview, champion history, reload and production isolation passed');
}finally{await browser.close();await new Promise(ok=>server.close(ok))}})().catch(e=>{console.error(e);process.exitCode=1});
