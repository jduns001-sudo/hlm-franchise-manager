'use strict';
const assert=require('node:assert/strict');
const {checkpoint}=require('./hlm-phase11-season-checkpoint');
const {createBridge,KEY}=require('./hlm-phase11-gameplay-bridge');
const {simulateGameScore}=require('./hlm-phase10-game-simulator');
const teams=[{id:1,name:'Portland'},{id:2,name:'Seattle'}];
const game={id:'g1',date:'2026-10-18',homeTeamId:1,awayTeamId:2,status:'scheduled'};
let state={meta:{controlledTeamId:1,currentDate:'2026-10-17'},universe:{teams,players:[]},activity:{games:[game]},privateNotes:'PRIVATE'};
let writes=0;
const storage={getItem:k=>k===KEY?JSON.stringify(state):null,setItem(){writes++;}};
const engine={createBrowserFranchiseSaveStore:()=>({load:()=>state}),calculateStandings:()=>[]};
const bridge=createBridge(engine,storage);
const first=checkpoint(bridge);
assert.equal(first.controlledGamesRemaining,1);assert.equal(first.record.wins,0);assert.equal(first.nextGame.venue,'home');assert.equal(writes,0);
const result=simulateGameScore({gameId:'g1',homeTeamId:1,awayTeamId:2,seed:1312});
state={...state,meta:{...state.meta,currentDate:'2026-10-18'},activity:{games:[{...game,status:'final',homeGoals:result.homeGoals,awayGoals:result.awayGoals}]}};
const second=checkpoint(bridge);
assert.equal(second.seasonComplete,true);assert.equal(second.controlledGamesCompleted,1);
assert.equal(second.goalsFor,result.homeGoals);assert.equal(second.goalsAgainst,result.awayGoals);
assert.equal(second.record.wins+second.record.losses+second.record.ties,1);
assert.equal(second.productionActivationAllowed,false);assert.equal(second.finalDecisionMaker,'human-gm');assert.equal(second.persistencePerformed,false);
assert.equal(JSON.stringify(second).includes('PRIVATE'),false);assert.equal(writes,0);
assert.deepEqual(second,checkpoint(bridge));
state.activity.games[0].homeGoals=-1;assert.throws(()=>checkpoint(bridge),/Invalid final score/);
state.activity.games[0].homeGoals=1;state.activity.games.push({...game,status:'scheduled'});assert.throws(()=>checkpoint(bridge),/duplicate game ID/);
console.log('Mission 1312 deterministic isolated season checkpoint regression passed');
