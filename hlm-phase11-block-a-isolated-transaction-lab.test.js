'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {join}=require('node:path');
const {teams,build}=require('./hlm-phase11-new-franchise');
const engine={...require('./hlm-game-state'),...require('./hlm-phase10-season-schedule')};
const {createIsolatedTransactionLab}=require('./hlm-phase11-block-a-isolated-transaction-lab');
test('isolated lab atomically moves canonical pick, records history and rejects replay and stale revision',()=>{
 const source=JSON.parse(readFileSync(join(__dirname,'hlm-universe.json'),'utf8'));
 const state=build(source,teams(source)[0].id,engine),lab=createIsolatedTransactionLab(state);
 const pick=state.assets.draftPicks.find(p=>p.status==='AVAILABLE');
 assert.ok(pick);
 const to=teams(source).find(t=>String(t.id)!==String(pick.currentOwnerId)).id;
 const request={experimentalEnabled:true,gmApproved:true,expectedRevision:'revision-1',decisionId:'lab-only-decision',changes:{players:[],contracts:[],picks:[{id:pick.pickId,from:pick.currentOwnerId,to}],prospects:[]}};
 const before=lab.snapshot();
 assert.equal(lab.simulate({...request,injectFailure:true}).committed,false);
 assert.deepEqual(lab.snapshot(),before);
 assert.equal(lab.simulate({...request,cancelled:true}).committed,false);
 assert.deepEqual(lab.snapshot(),before);
 const committed=lab.simulate(request);
 assert.equal(committed.committed,true);
 assert.equal(committed.productionSaved,false);
 assert.equal(committed.independentlyAuthenticated,false);
 const after=lab.snapshot();
 assert.equal(String(after.state.assets.draftPicks.find(p=>p.pickId===pick.pickId).currentOwnerId),String(to));
 assert.equal(after.state.activity.transactions.length,before.state.activity.transactions.length+1);
 assert.ok(after.consumedDecisionIds.includes('lab-only-decision'));
 assert.equal(lab.simulate(request).committed,false);
 assert.equal(lab.simulate({...request,expectedRevision:after.revision}).committed,false);
});
test('lab never invents missing contract and rejects default-off',()=>{
 const source=JSON.parse(readFileSync(join(__dirname,'hlm-universe.json'),'utf8'));
 const state=build(source,teams(source)[0].id,engine),lab=createIsolatedTransactionLab(state);
 const player=state.universe.players[0],other=teams(source).find(t=>String(t.id)!==String(player.teamId)).id;
 const request={experimentalEnabled:true,gmApproved:true,expectedRevision:'revision-1',decisionId:'lab-player',changes:{players:[{id:player.id,from:player.teamId,to:other}],contracts:[{playerId:player.id,from:player.teamId,to:other}],picks:[],prospects:[]}};
 const before=lab.snapshot();
 assert.equal(lab.simulate({...request,experimentalEnabled:false}).committed,false);
 assert.equal(lab.simulate(request).committed,false);
 assert.deepEqual(lab.snapshot(),before);
});
