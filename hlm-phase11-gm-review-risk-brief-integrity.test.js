'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {prepareGMReviewRiskBriefIntegrity:integrity}=require('./hlm-phase11-gm-review-risk-brief-integrity');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const report=integrity(items,digest,true,1000,[1100,1200,1501],500);
assert.match(report.sha256,/^[a-f0-9]{64}$/);assert.equal(report.reviewRequired,true);
assert.equal(integrity(items,digest,true,1000,[1100,1200,1501],500,report.sha256).matchesExpected,true);
assert.equal(integrity(items,digest,true,1000,[1100,1200,1501],500,'0'.repeat(64)).matchesExpected,false);
assert.equal(integrity(items,digest,true,1000,[1100,1200,1501],500,'bad').matchesExpected,null);
assert.notEqual(integrity(items,digest,true,1000,[1100,1200],500).sha256,report.sha256);
assert.equal(integrity(items,'0'.repeat(64),true,1000,[1100,1200],500).reviewRequired,true);
assert.equal(integrity([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500).reviewRequired,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(report[key],false);
assert.equal(report.requiresGMApproval,true);assert.ok(Object.isFrozen(report));
assert.deepEqual(integrity(items,digest,true,1000,[1100,1200,1501],500),report);
console.log('GM review risk brief integrity deterministic tests passed');
