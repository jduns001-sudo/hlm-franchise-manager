'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {create}=require('./hlm-phase11-m1579-unified-gm-next-action');
const {build}=require('./hlm-phase11-new-franchise');
const universe=require('./hlm-universe.json');
const engine={...require('./hlm-game-state'),...require('./hlm-phase10-season-schedule')};
let state=build(universe,5,engine),writes=0;
const reader=()=>JSON.parse(JSON.stringify(state)),baseline=JSON.stringify(state);
const gate=create(reader);
let p=gate.prepare('#day-review');assert.equal(p.available,true);
assert.equal(p.target,'day-review');assert.equal(p.saved,false);
let opened=gate.open();assert.equal(opened.target,'day-review');
assert.equal(opened.requiresExplicitGMApproval,true);assert.equal(opened.saved,false);
assert.throws(()=>gate.open(),/Refresh/);
assert.equal(JSON.stringify(state),baseline);
gate.prepare('#day-review');assert.equal(gate.cancel().saved,false);assert.throws(()=>gate.open(),/Refresh/);
gate.prepare('#day-review');state.meta.revision=(state.meta.revision||0)+1;
assert.throws(()=>gate.open(),/changed/);
assert.throws(()=>gate.open(),/Refresh/);
assert.equal(gate.prepare('#playoff-next').available,false,'never handoff to automatic playoff save');
assert.equal(gate.prepare('#season-id').available,false,'never handoff to archive save');
assert.equal(gate.prepare('#file').available,false,'cannot import through launcher');
assert.equal(writes,0);
assert.ok(fs.readFileSync('hlm-phase11-isolated-single-game.html','utf8').includes('id="gm-unified-action-open"'));
console.log('M1579 source-real saved season: existing review handoff, no approval/save, cancellation and stale revision guards passed');
