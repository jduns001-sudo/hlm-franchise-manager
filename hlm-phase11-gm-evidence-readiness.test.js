'use strict';
const assert=require('node:assert/strict');
const {assessGMEvidenceReadiness}=require('./hlm-phase11-gm-evidence-readiness');
const home=Array.from({length:4},(_,i)=>({shots:10,goals:i+1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const before=JSON.stringify([home,away]);
const r=assessGMEvidenceReadiness(home,away,[5,10,25],[5]);
assert.equal(r.productionActivationEnabled,false);
assert.equal(r.automaticallyApplied,false);
assert.equal(r.requiresGMApproval,true);
assert.equal(r.gameplayActionAuthorized,false);
assert.equal(r.evidenceReadyForDescription,false);
assert.equal(r.gmReviewComplete,false);
assert.deepEqual(r.missingEvidenceThresholds,[25]);
assert.deepEqual(r.pendingReviewThresholds,[25,10]);
assert.ok(Object.isFrozen(r.flags));
const fullyReviewed=assessGMEvidenceReadiness(home,away,[5,10,25],[5,10,25]);
assert.equal(fullyReviewed.gmReviewComplete,true);
assert.equal(fullyReviewed.gameplayActionAuthorized,false);
assert.deepEqual(assessGMEvidenceReadiness(home,away,[5,10,25],[5]),r);
assert.equal(JSON.stringify([home,away]),before);
console.log('GM evidence readiness deterministic tests passed');
