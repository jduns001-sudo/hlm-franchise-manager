'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {calculateStandings}=require('./hlm-phase10-standings');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {create,KEY}=require('./hlm-phase11-isolated-single-game');
const players=[{id:11,teamId:1,position:'G',overall:80},{id:12,teamId:1,position:'C',overall:95},{id:13,teamId:1,position:'LW',overall:95},{id:14,teamId:1,position:'D',overall:95},{id:15,teamId:1,position:'RW',overall:40},{id:21,teamId:2,position:'G',overall:80},{id:22,teamId:2,position:'C',overall:95},{id:23,teamId:2,position:'LW',overall:95},{id:24,teamId:2,position:'D',overall:95}];
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[{id:1},{id:2}],games:[{id:'g1',homeTeamId:1,awayTeamId:2,status:'scheduled',date:'2026-10-19'}],players});
state.extensions.phase11GmGoaliePlan={teamId:1,playerId:11};
const seed=1372,opts={experimentalRosterAware:true};
const baseline=applyScheduledGame(state,'g1',seed);
assert.throws(()=>applyScheduledGame(state,'g1',seed,opts),/Explicit GM-approved skater participation required/,'unapproved experimental scoring must be rejected');
const approved=JSON.parse(JSON.stringify(state));approved.extensions.phase11GmApprovedSkaters={teamId:1,playerIds:[12,13,14]};
const result=applyScheduledGame(approved,'g1',seed,opts);
assert.equal(result.result.homeGoals,baseline.result.homeGoals+1);
assert.equal(result.result.official,false);
assert.deepEqual(applyScheduledGame(approved,'g1',seed,opts).result,result.result);
assert.equal(applyScheduledGame(approved,'g1',seed).result.homeGoals,baseline.result.homeGoals);
assert.equal(applyScheduledGame(state,'g1',seed).result.homeGoals,baseline.result.homeGoals,'default-off scoring remains unchanged without skater approval');
const strongOpponent=JSON.parse(JSON.stringify(approved));
const weakOpponent=JSON.parse(JSON.stringify(approved));for(const p of weakOpponent.universe.players.filter(p=>p.teamId===2&&p.position!=='G'))p.overall=50;
const strongOpponentResult=applyScheduledGame(strongOpponent,'g1',seed,opts).result;
const weakOpponentResult=applyScheduledGame(weakOpponent,'g1',seed,opts).result;
assert.ok(strongOpponentResult.awayGoals>weakOpponentResult.awayGoals,'opposing CPU skater ratings must affect simulated goals');
assert.deepEqual(applyScheduledGame(strongOpponent,'g1',seed).result,applyScheduledGame(weakOpponent,'g1',seed).result,'opponent roster effects remain disabled unless experimental scoring is explicitly enabled');
assert.deepEqual(applyScheduledGame(strongOpponent,'g1',seed,opts).result,strongOpponentResult,'opponent roster effect remains deterministic');
const wrong=JSON.parse(JSON.stringify(approved));wrong.extensions.phase11GmApprovedSkaters.playerIds=[12,13,21];assert.throws(()=>applyScheduledGame(wrong,'g1',seed,opts),/eligible|injured/);
const injured=JSON.parse(JSON.stringify(approved));injured.activity.injuries=[{playerId:12,status:'out'}];assert.throws(()=>applyScheduledGame(injured,'g1',seed,opts),/eligible|injured/);
const duplicated=JSON.parse(JSON.stringify(approved));duplicated.extensions.phase11GmApprovedSkaters.playerIds=[12,12,14];assert.throws(()=>applyScheduledGame(duplicated,'g1',seed,opts),/Invalid/);
const map=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]),storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v)};
const engine={applyScheduledGame,calculateStandings,createBrowserFranchiseSaveStore};
const m=create(engine,storage);m.stage(state,true);
assert.throws(()=>m.approveSkaterParticipation([12,13,14],false),/approval/);
assert.throws(()=>m.approveSkaterParticipation([12,12,14],true),/distinct/);
assert.throws(()=>m.approveSkaterParticipation([12,13,21],true),/roster/);
assert.deepEqual(m.approveSkaterParticipation([12,13,14],true).playerIds,[12,13,14]);
m.approveExperimentalRosterAware(true,true);
const reloaded=create(engine,storage);reloaded.load();
assert.deepEqual(reloaded.advance('g1',seed,true).result,result.result);
assert.equal(map.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
assert.throws(()=>m.approveSkaterParticipation([12,13,14],true),/changed/);
assert.ok(map.get(KEY));
console.log('Mission 1373: explicit GM skater approval, deterministic score, invalid/injured rejection, legacy default-off, stale and production isolation pass');
