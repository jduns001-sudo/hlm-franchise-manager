'use strict';
const assert=require('node:assert/strict');
const {create}=require('./hlm-phase11-isolated-single-game');
const {review}=require('./hlm-phase11-game-day-skater-readiness');
const key='hlm-phase11-m1340-isolated-single-game-v1';
const store=new Map();
const storage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,String(v))};
const engine={reviewGameDaySkaters:review,applyScheduledGame(state,id){const next=JSON.parse(JSON.stringify(state));next.activity.games.find(g=>g.id===id).status='final';return {nextState:next,result:{gameId:id}}},calculateStandings(){return []},createBrowserFranchiseSaveStore(s,k){return {load(){const v=s.getItem(k);return v?JSON.parse(v):null},save(v){s.setItem(k,JSON.stringify(v))}}}};
const gm=create(engine,storage);
const state={meta:{controlledTeamId:5,currentDate:'2026-10-20'},universe:{teams:[{id:5},{id:3}],players:[{id:'signed',teamId:5,position:'C',overall:70},{id:'a',teamId:5,position:'LW',overall:80},{id:'b',teamId:5,position:'D',overall:75}]},activity:{games:[{id:'game1',date:'2026-10-20',status:'scheduled',homeTeamId:5,awayTeamId:3}],injuries:[],transactions:[{type:'drafted-prospect-signing',teamId:5,playerId:'signed'}]},assets:{contracts:[{teamId:5,playerId:'signed',status:'active'}]},extensions:{phase11GmApprovedSkaters:{teamId:5,playerIds:['signed','a','b']},phase11ExperimentalRosterAwareScores:false}};
gm.stage(state,true);
const before=storage.getItem(key);
assert.throws(()=>gm.advance('game1',17,true),/game-day skater approval required/);
const proposed=gm.reviewGameDaySkaters('game1');
assert.equal(storage.getItem(key),before,'review does not save');
assert.throws(()=>gm.approveReviewedGameDaySkaters(proposed,false),/approval required/);
assert.equal(storage.getItem(key),before,'decline does not save');
const approved=gm.approveReviewedGameDaySkaters(proposed,true);
assert.ok(approved.playerIds.includes('signed'));
assert.equal(gm.load().extensions.phase11ExperimentalRosterAwareScores,false);
assert.equal(gm.load().activity.transactions.length,1);
const played=gm.advance('game1',17,true);
assert.equal(played.state.activity.games[0].status,'final');
const post=gm.postgameSkaterReview('game1');
assert.deepEqual(post.approvedPlayerIds,['signed','a','b']);
assert.equal(post.officialResult,true);
assert.equal(post.actualParticipationVerified,false,'approved plan must never be described as observed ice time');
assert.equal(post.syntheticBoxScore,null);
const prior=storage.getItem(key);
assert.deepEqual(gm.postgameSkaterReview('game1').approvedPlayerIds,post.approvedPlayerIds);
assert.equal(storage.getItem(key),prior,'postgame review must be read-only');
assert.equal(gm.postgameSkaterReview('unknown'),null);
assert.equal(storage.getItem('hlm_front_office_v8'),null);
console.log('Mission 1401 reviewed skater participation and controlled simulation passed');
