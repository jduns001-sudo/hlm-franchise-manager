'use strict';
const assert=require('node:assert/strict');
const {append}=require('./hlm-phase11-isolated-box-scores');
const {buildUnifiedBoxScores}=require('./hlm-phase11-unified-box-scores');
const {review}=require('./hlm-phase11-gm-stat-review');
const players=[1,2].flatMap(teamId=>['C','LW','RW','D','G'].map((position,i)=>({id:teamId*100+i,teamId,position})));
const before={meta:{controlledTeamId:1},universe:{players},activity:{games:[{id:'g1',status:'scheduled',homeTeamId:1,awayTeamId:2}]},extensions:{phase10CurrentSeasonId:'2026-27'}};
const final={id:'g1',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:3,awayGoals:2};
const after={...before,activity:{games:[final]}};
const next=append(before,after,buildUnifiedBoxScores,17);
assert.equal(next.extensions.phase11ExperimentalBoxScores.length,1);
assert.equal(next.extensions.phase11ExperimentalBoxScores[0].official,false);
assert.equal(next.extensions.phase11ExperimentalBoxScores[0].experimental,true);
assert.equal(next.extensions.phase11ExperimentalBoxScores[0].home.players.reduce((n,p)=>n+p.goals,0),3);
assert.equal(review(next,{season:'2026-27',kind:'regular'}).games,1);
const inferred=append({...before,meta:{...before.meta,currentDate:'2026-10-18'},extensions:{}},{...after,extensions:{}},buildUnifiedBoxScores,17);
assert.equal(inferred.extensions.phase11ExperimentalBoxScores[0].season,'2026-27');
const winter=append({...before,meta:{...before.meta,currentDate:'2027-02-18'},extensions:{}},{...after,extensions:{}},buildUnifiedBoxScores,17);
assert.equal(winter.extensions.phase11ExperimentalBoxScores[0].season,'2026-27');
assert.equal(review(JSON.parse(JSON.stringify(next))).goalies.length,1);
assert.equal(append(after,next,buildUnifiedBoxScores,17).extensions.phase11ExperimentalBoxScores.length,1);
assert.deepEqual(before.activity.games[0].status,'scheduled');
assert.equal(append(before,{...after,universe:{players:[]}},buildUnifiedBoxScores,17).extensions.phase11ExperimentalBoxScores,undefined);
assert.throws(()=>append(before,{...after,activity:{games:[{...final,homeGoals:-1}]}},buildUnifiedBoxScores,17),/Invalid authoritative game goals/);
const playoffGame={gameId:'PO-R1-S1-G1',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:2,awayGoals:1,winnerTeamId:1};
const playoffBefore={...next,extensions:{...next.extensions,phase10Playoffs:{rounds:[[{games:[]}]]}}};
const playoffAfter={...playoffBefore,extensions:{...playoffBefore.extensions,phase10Playoffs:{rounds:[[{games:[playoffGame]}]]}}};
const withPlayoffs=append(playoffBefore,playoffAfter,buildUnifiedBoxScores,17);
assert.equal(review(withPlayoffs,{season:'2026-27',kind:'playoffs'}).games,1);
assert.equal(review(withPlayoffs,{season:'2026-27',kind:'regular'}).games,1);
assert.equal(withPlayoffs.extensions.phase11ExperimentalBoxScores.at(-1).playoff,true);
assert.equal(withPlayoffs.extensions.phase11ExperimentalBoxScores.at(-1).official,false);
assert.equal(append(playoffAfter,withPlayoffs,buildUnifiedBoxScores,17).extensions.phase11ExperimentalBoxScores.length,2);
const nextYearBefore={...before,extensions:{phase10CurrentSeasonId:'2027-28',phase11ExperimentalBoxScores:withPlayoffs.extensions.phase11ExperimentalBoxScores}};
const nextYearAfter={...nextYearBefore,activity:{games:[final]}};
const nextYear=append(nextYearBefore,nextYearAfter,buildUnifiedBoxScores,17);
assert.equal(review(nextYear,{season:'2027-28',kind:'regular'}).games,1);
assert.equal(review(nextYear,{season:'2026-27',kind:'playoffs'}).games,1);
// A completed championship is archived, then the Phase 10 offseason clears the bracket.
// Reused playoff game IDs must generate distinct synthetic reports in the next season.
const archived={...withPlayoffs,history:{seasons:[{seasonId:'2026-27',championTeamId:1,playoffRounds:[[{games:[playoffGame]}]]}]}};
const rollover={...archived,meta:{...archived.meta,currentDate:'2027-10-18'},activity:{games:[{id:'g1',status:'scheduled',homeTeamId:1,awayTeamId:2}]},extensions:{...archived.extensions,phase10CurrentSeasonId:'2027-28'}};
delete rollover.extensions.phase10Playoffs;
const nextPlayoffBefore={...rollover,extensions:{...rollover.extensions,phase10Playoffs:{rounds:[[{games:[]}]]}}};
const nextPlayoffAfter={...nextPlayoffBefore,extensions:{...nextPlayoffBefore.extensions,phase10Playoffs:{rounds:[[{games:[playoffGame]}]]}}};
const twoSeasons=append(nextPlayoffBefore,nextPlayoffAfter,buildUnifiedBoxScores,17);
assert.equal(twoSeasons.extensions.phase11ExperimentalBoxScores.length,3);
assert.equal(review(twoSeasons,{season:'2026-27',kind:'playoffs'}).games,1);
assert.equal(review(twoSeasons,{season:'2027-28',kind:'playoffs'}).games,1);
assert.equal(review(twoSeasons,{season:'2026-27',kind:'regular'}).games,1);
assert.equal(twoSeasons.extensions.phase11ExperimentalBoxScores.at(-1).official,false);
assert.equal(append(nextPlayoffAfter,twoSeasons,buildUnifiedBoxScores,17).extensions.phase11ExperimentalBoxScores.length,3);
assert.equal(rollover.history.seasons[0].seasonId,'2026-27');
assert.equal(withPlayoffs.extensions.phase11ExperimentalBoxScores.length,2);
const sameIdBefore={...before,activity:{games:[{id:'PO-R1-S1-G1',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:1,awayGoals:0}]},extensions:{phase10CurrentSeasonId:'2026-27',phase10Playoffs:{rounds:[[{games:[]}]]}}};
const sameIdAfter={...sameIdBefore,extensions:{...sameIdBefore.extensions,phase10Playoffs:{rounds:[[{games:[playoffGame]}]]}}};
const sameIdBox=append(sameIdBefore,sameIdAfter,buildUnifiedBoxScores,17);
assert.equal(review(sameIdBox,{season:'2026-27',kind:'playoffs'}).games,1);
assert.throws(()=>append(before,{...after,activity:{games:[final,{...final}]}},buildUnifiedBoxScores,17),/Duplicate authoritative season game ID/);
console.log('Mission 1360 synthetic final attribution, persistence, deduplication, legacy roster safety and read-only review passed');
