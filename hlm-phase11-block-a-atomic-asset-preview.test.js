'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {join}=require('node:path');
const {teams,build}=require('./hlm-phase11-new-franchise');
const engine={...require('./hlm-game-state'),...require('./hlm-phase10-season-schedule')};
const {previewAtomicAssetDelta}=require('./hlm-phase11-block-a-atomic-asset-preview');
test('canonical universe preview never invents linked contract or authorizes a trade',()=>{
 const source=JSON.parse(readFileSync(join(__dirname,'hlm-universe.json'),'utf8'));
 const team=teams(source).find(t=>t.abbr==='PIT'),state=build(source,team.id,engine);
 const player=state.universe.players.find(p=>String(p.teamId)===String(team.id));
 const other=teams(source).find(t=>String(t.id)!==String(team.id)).id;
 const pick=state.assets.draftPicks.find(p=>p.status==='AVAILABLE');
 assert.ok(player&&pick);
 const pickOther=teams(source).find(t=>String(t.id)!==String(pick.currentOwnerId)).id;
 const proposal={players:[{playerId:player.id,fromTeamId:team.id,toTeamId:other}],picks:[{pickId:pick.pickId,fromTeamId:pick.currentOwnerId,toTeamId:pickOther}],prospects:[]};
 const before=JSON.stringify(state);
 const result=previewAtomicAssetDelta(source,state,proposal,{receivingTeamId:'unverified'},'unverified',{decision:'accepted'},{gmApproved:true,experimentalEnabled:true});
 assert.equal(result.status,'preview-only-settlement-blocked');
 assert.ok(result.errors.some(e=>e.code==='player-contract-link-not-verified'));
 assert.equal(result.changes.players.length,0);
 assert.equal(result.changes.contracts.length,0);
 assert.equal(result.changes.picks.length,1);
 assert.equal(result.settlementAuthorized,false);
 assert.equal(result.saved,false);
 assert.equal(JSON.stringify(state),before);
});
test('duplicate pick and cancelled review remain blocked without writes',()=>{
 const source=JSON.parse(readFileSync(join(__dirname,'hlm-universe.json'),'utf8'));
 const state=build(source,teams(source)[0].id,engine);
 const pick=state.assets.draftPicks.find(p=>p.status==='AVAILABLE');
 assert.ok(pick);
 const to=teams(source).find(t=>String(t.id)!==String(pick.currentOwnerId)).id;
 const transfer={pickId:pick.pickId,fromTeamId:pick.currentOwnerId,toTeamId:to};
 const before=JSON.stringify(state);
 const result=previewAtomicAssetDelta(source,state,{players:[],picks:[transfer,transfer],prospects:[]},{},'x',null,{cancelled:true});
 assert.ok(result.errors.some(e=>e.code==='duplicate-transfer'));
 assert.ok(result.blockers.includes('gm-cancelled-or-declined'));
 assert.equal(result.saved,false);
 assert.equal(JSON.stringify(state),before);
});
