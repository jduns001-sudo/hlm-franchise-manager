'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {calculateStandings}=require('./hlm-phase10-standings');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {create,KEY}=require('./hlm-phase11-isolated-single-game');
const memory=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const engine={applyScheduledGame,calculateStandings,createBrowserFranchiseSaveStore};
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],games:[{id:'g1',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'scheduled'}]});
state.universe.players=[{id:11,teamId:1,position:'G',name:'GM Goalie'},{id:12,teamId:1,position:'C',name:'Skater'},{id:21,teamId:2,position:'G',name:'CPU Goalie'}];
const a=create(engine,storage);a.stage(state,true);
assert.throws(()=>a.reviewGoalieChoice(12),/controlled-team roster/);
assert.throws(()=>a.reviewGoalieChoice(21),/controlled-team roster/);
assert.equal(a.reviewGoalieChoice(11).playerName,'GM Goalie');
assert.throws(()=>a.approveGoalieChoice(11,false),/approval/);
const before=storage.getItem(KEY),stale=create(engine,storage);
a.approveGoalieChoice(11,true);
assert.notEqual(storage.getItem(KEY),before);
assert.equal(a.load().extensions.phase11GmGoaliePlan.playerId,11);
assert.throws(()=>stale.approveGoalieChoice(11,true),/changed/);
assert.equal(memory.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
const state2=a.load();state2.activity.injuries=[{playerId:11,status:'out'}];
const storage2={getItem:k=>k===KEY?null:null,setItem:(k,v)=>{if(k===KEY)memory.set('alternate',v)}};
const fresh=create(engine,storage2);fresh.stage(state2,true);
assert.throws(()=>fresh.reviewGoalieChoice(11),/unresolved injury/);
console.log('Mission 1368: goalie review, GM approval, stale-write, injury guard and production isolation passed');
