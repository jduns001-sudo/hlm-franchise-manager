'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {selectDraftProspect}=require('./hlm-phase10-draft-selection');
const {signDraftedProspect}=require('./hlm-phase11-drafted-prospect-signing');
const initial=createGameStateEnvelope({meta:{controlledTeamId:5},teams:[{id:5,name:'Pittsburgh'},{id:3,name:'New York'}],players:[{id:'existing',teamId:5,name:'Roster Player'}],prospects:[{id:'future',name:'Future Prospect',position:'C',overall:72}],draftPicks:[{pickId:'pick',currentOwnerId:5,status:'available'}],contracts:[{contractId:'existing-contract',playerId:'existing',teamId:5,aav:5,years:2,season:'2027-28',status:'active'}]});
const drafted=selectDraftProspect(initial,{pickId:'pick',prospectId:'future',teamId:5}).nextState;
assert.equal(drafted.universe.players.length,1,'draft rights alone never sign prospect');
const before=JSON.stringify(drafted);
const input={prospectId:'future',teamId:5,contractId:'rookie',aav:1,years:3,season:'2027-28',capLimit:10};
assert.throws(()=>signDraftedProspect(drafted,{...input,teamId:3}),/does not own/);
assert.throws(()=>signDraftedProspect(drafted,{...input,capLimit:5}),/salary cap/);
assert.throws(()=>signDraftedProspect(drafted,{...input,contractId:'existing-contract'}),/already exists/);
assert.equal(JSON.stringify(drafted),before,'rejected approvals cannot mutate save');
const {nextState,summary}=signDraftedProspect(drafted,input);
assert.equal(summary.projectedPayroll,6);
assert.equal(nextState.universe.players.length,2);
assert.equal(nextState.universe.players.find(p=>p.id==='future').teamId,5);
assert.equal(nextState.universe.players.find(p=>p.id==='future').position,'C');
assert.equal(nextState.assets.contracts.find(c=>c.contractId==='rookie').playerId,'future');
assert.equal(nextState.universe.prospects.find(p=>p.id==='future').signedContractId,'rookie');
assert.equal(JSON.stringify(drafted),before,'approved signing clones original');
assert.throws(()=>signDraftedProspect(nextState,input),/already signed/);
const reload=JSON.parse(JSON.stringify(nextState));
assert.equal(reload.universe.players.find(p=>p.id==='future').teamId,5);
assert.equal(reload.universe.prospects.find(p=>p.id==='future').signedContractId,'rookie');
assert.equal(reload.history.seasons.length,0,'history preserved');
console.log('Mission 1396 owned prospect signing, cap, duplicate, reload and atomicity passed');
