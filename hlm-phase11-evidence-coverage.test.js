'use strict';
const assert=require('node:assert/strict');
const {reportEvidenceCoverage}=require('./hlm-phase11-evidence-coverage');
const home=[{shots:10,goals:2,expectedGoals:2},{shots:10,goals:2,expectedGoals:2},{shots:10,goals:4,expectedGoals:2},{shots:10,goals:4,expectedGoals:2}];
const away=[{shots:10,goals:1,expectedGoals:2},{shots:10,goals:1,expectedGoals:2},{shots:10,goals:1,expectedGoals:2},{shots:10,goals:1,expectedGoals:2}];
const partial=reportEvidenceCoverage(home,away);
assert.equal(partial.coverage,'partial');assert.equal(partial.coverageFraction,.666667);
assert.deepEqual(partial.supportedThresholds,[5,10]);assert.deepEqual(partial.withheldThresholds,[25]);
assert.equal(partial.direction,null);assert.equal(partial.items[2].direction,null);
assert.ok(partial.cautionCodes.includes('window-sample-insufficient'));
assert.equal(partial.productionActivationEnabled,false);assert.equal(partial.automaticallyApplied,false);
assert.equal(partial.requiresGMApproval,true);assert.equal(Object.isFrozen(partial.items),true);
assert.deepEqual(partial,reportEvidenceCoverage(home,away));
const complete=reportEvidenceCoverage(home,away,[5,10]);
assert.equal(complete.coverage,'complete');assert.equal(complete.coverageFraction,1);
assert.equal(complete.direction,'increased');
const none=reportEvidenceCoverage(home,away,[50,100]);
assert.equal(none.coverage,'none');assert.equal(none.coverageFraction,0);
assert.deepEqual(none.withheldThresholds,[50,100]);assert.equal(none.direction,null);
assert.throws(()=>reportEvidenceCoverage(home,away,[5,5]),RangeError);
assert.throws(()=>reportEvidenceCoverage(null,away),TypeError);
console.log('Evidence coverage deterministic regressions passed');
