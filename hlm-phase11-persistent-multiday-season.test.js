'use strict';
const assert=require('node:assert/strict');
const {createPhase10FromFrontOffice}=require('./hlm-phase10-front-office-import');
const {createIsolatedSeasonStore}=require('./hlm-phase11-isolated-season-atomic-store');
const {createPersistentMultidaySeason}=require('./hlm-phase11-persistent-multiday-season');
const positions=['C','LW','RW','D','D','G'];
const players=[1,2].flatMap(teamId=>positions.map((position,i)=>({id:teamId*100+i,teamId,position,ovr:teamId===1?85:75})));
const legacy={teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],players,contracts:players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'})),injuries:players.map(p=>({playerId:p.id,status:'Recovered'}))};
const {nextState}=createPhase10FromFrontOffice(legacy,{controlledTeamId:1,currentDate:'2026-10-12',saveId:'multiday-test'});
nextState.activity.games=[{id:'G1',date:'2026-10-13',status:'scheduled',homeTeamId:1,awayTeamId:2},{id:'G2',date:'2026-10-14',status:'scheduled',homeTeamId:2,awayTeamId:1}];
nextState.activity.injuries=legacy.injuries;
const map=new Map(),adapter={read:k=>map.has(k)?map.get(k):null,write:(k,v)=>map.set(k,v),remove:k=>map.delete(k)};
const store=createIsolatedSeasonStore(adapter);store.save(nextState);
const engine=createPersistentMultidaySeason(adapter);
assert.throws(()=>engine.advanceDays(2),/confirmation/);
assert.throws(()=>engine.advanceDays(32,{confirmed:true}),/1 through 31/);
const result=engine.advanceDays(2,{confirmed:true,seed:11});
assert.equal(result.saved,true);
assert.equal(result.advancedDays,2);
assert.equal(result.days.length,2);
assert.equal(result.currentDate,'2026-10-14');
assert.equal(result.days.reduce((n,d)=>n+d.games.length,0),2);
assert.equal(engine.load().activity.games.filter(g=>g.status==='final').length,2);
assert.equal(engine.productionActivationEnabled,false);
assert.deepEqual([...map.keys()],[engine.key]);
const before=JSON.stringify(engine.load());
const blocked=engine.advanceDays(1,{confirmed:true,seed:12});
assert.equal(blocked.saved,true);
assert.equal(JSON.stringify(engine.load())===before,false);
const blockedMap=new Map(),blockedAdapter={read:k=>blockedMap.has(k)?blockedMap.get(k):null,write:(k,v)=>blockedMap.set(k,v),remove:k=>blockedMap.delete(k)};
const blockedStore=createIsolatedSeasonStore(blockedAdapter);
const invalid=JSON.parse(JSON.stringify(nextState));invalid.activity.games[1].awayTeamId=99;
blockedStore.save(invalid);
const blockedEngine=createPersistentMultidaySeason(blockedAdapter);
const original=blockedAdapter.read(blockedEngine.key);
const stopped=blockedEngine.advanceDays(2,{confirmed:true});
assert.equal(stopped.saved,false);
assert.equal(stopped.advancedDays,0);
assert.equal(blockedAdapter.read(blockedEngine.key),original);
console.log('Phase 11 persistent two-day owner/CPU games, standings, atomic commit and blocked-day rollback passed');
