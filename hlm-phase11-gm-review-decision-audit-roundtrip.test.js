'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {assessGMReviewRiskBriefReadiness}=require('./hlm-phase11-gm-review-risk-brief-readiness');
const {checkGMReviewDecisionBriefChange}=require('./hlm-phase11-gm-review-decision-brief-change-check');
const {verifyGMReviewDecisionAuditRoundtrip:verify}=require('./hlm-phase11-gm-review-decision-audit-roundtrip');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const risk=assessGMReviewRiskBriefReadiness(items,digest,true,1000,[1100,1200],500).currentSha256;
const prior=checkGMReviewDecisionBriefChange(items,digest,true,1000,[1100,1200],500,risk).currentSha256;
const ready=verify(items,digest,true,1000,[1100,1200],500,risk,prior,1300);
assert.equal(ready.status,'verified-read-only');assert.equal(ready.valid,true);
assert.equal(ready.auditStatus,'unchanged');assert.equal(ready.requiresFreshGMReview,false);
const changed=verify(items,digest,true,1000,[1100,1501],500,risk,prior,1600);
assert.equal(changed.status,'verified-read-only');assert.equal(changed.auditStatus,'changed');assert.equal(changed.requiresFreshGMReview,true);
const invalidTime=verify(items,digest,true,1000,[1100,1200],500,risk,prior,-1);
assert.equal(invalidTime.status,'verified-read-only');assert.equal(invalidTime.auditStatus,'invalid-audit-time');assert.equal(invalidTime.requiresFreshGMReview,true);
const invalidEvidence=verify([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500,risk,prior,1300);
assert.equal(invalidEvidence.requiresFreshGMReview,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(ready[key],false);
assert.equal(ready.requiresGMApproval,true);assert.ok(Object.isFrozen(ready));
assert.deepEqual(verify(items,digest,true,1000,[1100,1200],500,risk,prior,1300),ready);
console.log('GM review decision audit roundtrip deterministic tests passed');
