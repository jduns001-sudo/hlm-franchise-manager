'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('phase11-roster-import.html','utf8');
for(const id of ['file','json','preview','summary','teams','save','existing','status'])assert(html.includes('id="'+id+'"'));
const sandbox={window:{}};vm.runInNewContext(fs.readFileSync('hlm-phase11-roster-import.bundle.js','utf8'),sandbox,{timeout:10000});
const values=new Map([['hlm-phase10-demo-v1','KEEP_DEMO'],['hlm-phase10-roster-experimental-v1','KEEP_ROSTER'],['legacy-front-office','KEEP_FRONT']]);
const writes=[],storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>{writes.push(k);values.set(k,v)}};
const controller=sandbox.window.HLMRosterImport.createRosterImportController(storage);
const teams=[{teamId:1,teamName:'Wolves'},{teamId:2,teamName:'Bears'}];
const players=teams.flatMap(t=>['C','LW','RW','LD','RD','GK'].map((pos,i)=>({playerId:t.teamId*100+i,teamName:t.teamName,playerName:'Player '+t.teamId+' '+i,pos,overall:75})));
const input=JSON.stringify({teams,players});
const preview=controller.preview(input);
assert.equal(preview.teamCount,2);assert.equal(preview.playerCount,12);assert.equal(writes.length,0);
assert.throws(()=>controller.commit(false),/confirmation/);assert.equal(writes.length,0);
const state=controller.commit(true);
assert.equal(state.universe.players.length,12);assert.equal(writes.length,1);assert.equal(writes[0],controller.key);
assert.equal(values.get('hlm-phase10-demo-v1'),'KEEP_DEMO');assert.equal(values.get('hlm-phase10-roster-experimental-v1'),'KEEP_ROSTER');assert.equal(values.get('legacy-front-office'),'KEEP_FRONT');
assert.throws(()=>controller.commit(true),/Preview a roster/);
controller.preview(input);assert.throws(()=>controller.commit(true),/already exists/);
const second=sandbox.window.HLMRosterImport.createRosterImportController(storage);
assert.equal(second.load().universe.teams.length,2);
assert.equal(writes.length,1);
console.log('Phase 11 browser import smoke and save-isolation tests passed.');
