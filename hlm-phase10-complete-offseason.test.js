'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {finalizeChampionshipSeason}=require('./hlm-phase10-season-finalization');
const {completeOffseasonAndStartSeason}=require('./hlm-phase10-complete-offseason');
const state=createGameStateEnvelope({meta:{saveId:'season',currentDate:'2027-06-20',controlledTeamId:1},teams:[{id:1,name:'Wolves'},{id:2,name:'Falcons'}],players:[{id:10,name:'A'}],contracts:[{contractId:'c1',playerId:10,teamId:1,status:'active',aav:2}],prospects:[{id:'p1'}],draftPicks:[{pickId:'pick1',currentOwnerId:1}],games:[{id:'g1',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:3,awayGoals:1,overtime:false}]});
state.extensions.phase10Playoffs={status:'complete',championTeamId:1,rounds:[[]]};
const archived=finalizeChampionshipSeason(state,'2026-27').nextState;
const before=JSON.stringify(archived);
const options={contracts:{expiredContractIds:['c1'],signings:[{playerId:10,teamId:1,contractId:'c2',aav:3,years:2,season:'2027-28',capLimit:10}]},draftSelections:[{pickId:'pick1',prospectId:'p1',teamId:1}],nextSeason:{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'}};
const {nextState,summary}=completeOffseasonAndStartSeason(archived,options);
assert.equal(summary.draftSelections.length,1);
assert.equal(summary.season.scheduledGames,2);
assert.equal(nextState.assets.contracts[1].status,'active');
assert.equal(nextState.universe.prospects[0].draftedByTeamId,1);
assert.equal(nextState.history.seasons.length,1);
assert.equal(JSON.stringify(archived),before);
assert.throws(()=>completeOffseasonAndStartSeason(archived,{...options,nextSeason:{...options.nextSeason,startDate:'2027-01-01'}}),/after championship/);
assert.equal(JSON.stringify(archived),before);
console.log('Phase 10 complete offseason tests passed');
