'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {assessGMReviewRiskBriefReadiness:assess}=require('./hlm-phase11-gm-review-risk-brief-readiness');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const first=assess(items,digest,true,1000,[1100,1200],500);
assert.equal(first.status,'blocked');assert.equal(first.readyForHumanReview,false);
const ready=assess(items,digest,true,1000,[1100,1200],500,first.currentSha256);
assert.equal(ready.status,'ready-for-human-review');assert.equal(ready.readyForHumanReview,true);assert.deepEqual(ready.reasons,[]);
const stale=assess(items,digest,true,1000,[1100,1501],500);
const blocked=assess(items,digest,true,1000,[1100,1501],500,stale.currentSha256);
assert.equal(blocked.status,'blocked');assert.deepEqual(blocked.reasons,['fresh-evidence-acknowledgement-required']);
assert.equal(assess(items,digest,true,1000,[1100,1200],500,'0'.repeat(64)).status,'blocked');
assert.equal(assess(items,'0'.repeat(64),true,1000,[1100,1200],500).status,'blocked');
assert.equal(assess([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500).status,'blocked');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(ready[key],false);
assert.equal(ready.requiresGMApproval,true);assert.ok(Object.isFrozen(ready));assert.ok(Object.isFrozen(ready.reasons));
assert.deepEqual(assess(items,digest,true,1000,[1100,1200],500,first.currentSha256),ready);
console.log('GM review risk brief readiness deterministic tests passed');
