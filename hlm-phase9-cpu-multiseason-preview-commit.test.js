'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {previewCPUMultiSeasonSave,commitPreviewedCPUMultiSeasonSave}=require('./hlm-phase9-cpu-multiseason-preview-commit');
const repository=createMemorySaveRepository();
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT',currentDate:'2030-06-30'},teams:[{id:'PIT'},{id:'NYR'}]});
state.history.seasons.push({id:'2029-30',status:'completed',champion:'PIT'});
repository.save('original',state);
const before=serializeGameState(repository.load('original').state);
const transitions=[{fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01'},{fromSeasonId:'2030-31',toSeasonId:'2031-32',nextDate:'2031-07-01',completedSeason:{seasonId:'2030-31',championTeamId:'NYR'}}];
const preview=previewCPUMultiSeasonSave({repository,sourceSlotId:'original',transitions});
assert.equal(preview.transitionCount,2);
assert.equal(repository.count(),1);
const commit=(changes={})=>commitPreviewedCPUMultiSeasonSave({repository,preview,transitions,destinationSlotId:'reviewed',confirmCommit:true,...changes});
assert.throws(()=>commit({confirmCommit:false}),e=>e.code==='CPU_MULTI_SEASON_PREVIEW_APPROVAL_REQUIRED');
assert.throws(()=>commit({transitions:[{...transitions[0],nextDate:'2030-07-02'},transitions[1]]}),e=>e.code==='CPU_MULTI_SEASON_PREVIEW_STALE');
assert.equal(repository.count(),1);
const result=commit();
assert.equal(result.verified,true);
assert.equal(result.previewMatched,true);
assert.equal(result.productionCPUExecutionEnabled,false);
assert.equal(serializeGameState(repository.load('reviewed').state),preview.candidateFingerprint);
assert.equal(serializeGameState(repository.load('original').state),before);
assert.throws(()=>commit(),e=>e.code==='CPU_MULTI_SEASON_SAVE_DESTINATION_OCCUPIED');
console.log('Phase 9 multi-season preview and exact-match commit tests passed');
