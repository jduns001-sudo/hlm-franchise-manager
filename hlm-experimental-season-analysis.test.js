'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createExperimentalSchedule,runExperimentalSeasonBatch}=require('./hlm-experimental-season-batch');
const lab=require('./hlm-experimental-season-analysis');
const positions=['C','LW','RW','D','D','G'];
const players=[...positions.map((position,i)=>({id:10+i,teamId:1,position,ovr:80})),...positions.map((position,i)=>({id:20+i,teamId:2,position,ovr:70}))];
const contracts=players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const state=createGameStateEnvelope({teams:[{id:1,name:'Wolves'},{id:2,name:'Bears'}],players,contracts,injuries});
const before=JSON.stringify(state);
const batch=runExperimentalSeasonBatch(state,createExperimentalSchedule([1,2],2),12345);
assert.equal(lab.goalDifferentialTable(batch).length,2);
assert.equal(lab.homeAwaySplits(batch).reduce((n,r)=>n+r.home.games+r.away.games,0),4);
assert.equal(lab.headToHead(batch)[0].games,2);
assert.equal(lab.recentForm(batch).length,2);
assert.equal(lab.experimentalPlayoffSeeds(batch,2).length,2);
assert.equal(lab.seasonIntegrityAudit(batch).consistent,true);
const snapshot=lab.seasonSnapshot(batch);
assert.equal(snapshot.integrity.checkedGames,2);
assert.equal(snapshot.official,false);
assert.deepEqual(lab.seasonSnapshot(batch),snapshot);
assert.deepEqual(lab.runExperimentalSeasonAnalysis(state,[1,2],12345,2).snapshot,snapshot);
assert.equal(JSON.stringify(state),before);
const corrupted={...batch,standings:batch.standings.map((r,i)=>i?{...r}:{...r,points:r.points+1})};
assert.equal(lab.seasonIntegrityAudit(corrupted).consistent,false);
assert.throws(()=>lab.seasonSnapshot(corrupted),/INCONSISTENT/);
assert.throws(()=>lab.recentForm(batch,0),RangeError);
assert.throws(()=>lab.experimentalPlayoffSeeds(batch,3),RangeError);
const missing=createGameStateEnvelope({teams:state.universe.teams,players,contracts:contracts.filter(c=>c.playerId!==20),injuries});
const blocked=lab.runExperimentalSeasonAnalysis(missing,[1,2],12345,2);
assert.equal(blocked.researchReady,false);
assert.equal(blocked.snapshot,null);
assert(blocked.blockers.length>0);
assert.throws(()=>lab.seasonSnapshot({...batch,researchReady:false}),/NOT_READY/);
console.log('Batch 765-772 experimental season analysis tests passed.');
