'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {assessPhase9Readiness}=require('./hlm-phase9-integration-readiness');
const state=createGameStateEnvelope({teams:[{id:'PIT',name:'Pittsburgh'}],players:[{id:'p1',teamId:'PIT'}],contracts:[],draftPicks:[]});
const before=JSON.stringify(state);
const options={decision:{prioritization:{evaluation:{identification:{problems:[{id:'cap',category:'cap',severity:'high'}]},options:[{id:'trade',problemId:'cap',type:'trades'}]},priorities:[{id:'first',optionId:'trade',tier:'high',order:1}]},priorityId:'first',authorized:true,execute:true}};
const report=assessPhase9Readiness(state,'PIT',options);
assert.equal(report.checks.organizationAssessment,true);
assert.equal(report.checks.decisionRecommendation,true);
assert.equal(report.checks.humanApprovalBoundary,true);
assert.equal(report.checks.stateUnchanged,true);
assert.equal(report.checks.persistentCPUExecution,false);
assert.equal(report.checks.multiSeasonContinuity,false);
assert.deepEqual(report.blockers,['persistentCPUExecution','multiSeasonContinuity']);
assert.equal(report.readyForPhase10,false);
assert.equal(report.sourceStateMutated,false);
assert.equal(JSON.stringify(state),before);
assert.ok(Object.isFrozen(report)&&Object.isFrozen(report.checks)&&Object.isFrozen(report.blockers));
assert.throws(()=>assessPhase9Readiness({},'PIT'),TypeError);
assert.throws(()=>assessPhase9Readiness(state,'UNKNOWN'),/Team not found/);
console.log('Phase 9 integration readiness assessment tests passed');
