'use strict';
const assert=require('node:assert/strict');
const {mapExternalRoster,createVersionedImportStore}=require('./hlm-phase11-roster-mapping');
const teams=[{teamId:10,teamName:'Northport Wolves'},{teamId:20,teamName:'Lakeside Falcons'}];
const players=teams.flatMap((t,j)=>['C','LW','RW','LD','RD','GK'].map((pos,i)=>({playerId:(j+1)*100+i,teamName:t.teamName,playerName:'Player '+j+' '+i,pos,overall:70+i})));
const normalized=mapExternalRoster({teams,players});
const parsed=JSON.parse(normalized);
assert.equal(parsed.teams.length,2);assert.equal(parsed.players[5].position,'G');
assert.equal(parsed.players[3].position,'D');
const m=new Map([['hlm-phase10-roster-experimental-v1','KEEP_ROSTER'],['hlm-phase10-demo-v1','KEEP_DEMO'],['hlm-front-office-v1','KEEP_FRONT']]);
const writes=[];
const storage={getItem:k=>m.get(k)??null,setItem:(k,v)=>{writes.push(k);m.set(k,v)}};
const store=createVersionedImportStore(storage);
assert.equal(store.preview(normalized).writes,0);
assert.deepEqual(writes,[]);
assert.throws(()=>store.commit(normalized),/confirmation/);
assert.deepEqual(writes,[]);
const committed=store.commit(normalized,{confirm:true});
assert.equal(committed.meta.saveId,'phase11-roster-import-preview');
assert.deepEqual(writes,[store.key]);
assert.equal(store.load().universe.players.length,12);
assert.throws(()=>store.commit(normalized,{confirm:true}),/already exists/);
assert.equal(m.get('hlm-phase10-roster-experimental-v1'),'KEEP_ROSTER');
assert.equal(m.get('hlm-phase10-demo-v1'),'KEEP_DEMO');
assert.equal(m.get('hlm-front-office-v1'),'KEEP_FRONT');
const broken=JSON.parse(normalized);broken.players[0].teamId=999;
assert.throws(()=>store.preview(JSON.stringify(broken)),/Invalid player/);
const badSource={teams,players:players.map(p=>({...p}))};badSource.players[0].overall=0;
assert.throws(()=>mapExternalRoster(badSource),/Invalid player/);
console.log('Phase 11 mapping and isolated versioned commit tests passed.');
