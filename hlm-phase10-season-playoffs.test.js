'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {startSeasonPlayoffs}=require('./hlm-phase10-season-playoffs');
const teams=[1,2,3,4].map(id=>({id,name:'Team '+id}));
const games=[{id:'g1',date:'2026-10-13',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:3,awayGoals:1,overtime:false},{id:'g2',date:'2026-10-13',status:'final',homeTeamId:3,awayTeamId:4,homeGoals:2,awayGoals:1,overtime:false}];
const state=createGameStateEnvelope({meta:{saveId:'demo',currentDate:'2026-10-14',controlledTeamId:1},teams,games});
const before=JSON.stringify(state);
const result=startSeasonPlayoffs(state,4);
assert.equal(result.seeds.length,4);
assert.equal(result.bracket.rounds[0].length,2);
assert.equal(result.nextState.extensions.phase10Playoffs.status,'active');
assert.equal(JSON.stringify(state),before);
assert.throws(()=>startSeasonPlayoffs(result.nextState,4),/already initialized/);
const pending=JSON.parse(before);
pending.activity.games.push({id:'g3',date:'2026-10-15',status:'scheduled',homeTeamId:1,awayTeamId:3});
assert.throws(()=>startSeasonPlayoffs(pending,4),/unplayed/);
assert.throws(()=>startSeasonPlayoffs(createGameStateEnvelope({teams,games:[]}),4),/without regular-season/);
console.log('Phase 10 season playoff transition tests passed');
