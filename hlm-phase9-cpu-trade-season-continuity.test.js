'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {previewCPUTradeSeasonContinuity}=require('./hlm-phase9-cpu-trade-season-continuity');
const repo=createMemorySaveRepository();
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT',currentDate:'2030-10-11'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}]});
state.history.seasons.push({id:'2029-30',champion:'BOS'},{id:'2030-31',status:'active'});
repo.save('franchise',state);
const fingerprint=serializeGameState(repo.load('franchise').state);
const trade=(from,to,id)=>({teamIds:[from,to],legs:[{fromTeamId:from,toTeamId:to,assets:[{type:'player',id:'p1',ownerTeamId:from}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:id});
const steps=[{teamId:'BUF',trade:trade('BUF','NYR','t1')},{teamId:'NYR',trade:trade('NYR','BOS','t2')}];
const run=(changes={})=>previewCPUTradeSeasonContinuity({repository:repo,sourceSlotId:'franchise',expectedSourceFingerprint:fingerprint,seasonId:'2030-31',steps,...changes});
const preview=run();
assert.equal(preview.historicalSeasonsPreserved,true);
assert.equal(preview.currentDatePreserved,true);
assert.equal(preview.controlledTeamPreserved,true);
assert.deepEqual(preview.transactionIds,['t1','t2']);
assert.equal(preview.multiSeasonCPUExecutionEnabled,false);
assert.equal(repo.count(),1);
assert.equal(serializeGameState(repo.load('franchise').state),fingerprint);
assert.throws(()=>run({seasonId:'2031-32'}),e=>e.code==='CPU_SEASON_NOT_UNIQUE');
assert.throws(()=>run({expectedSourceFingerprint:'stale'}),e=>e.code==='CPU_SEASON_SOURCE_STALE');
console.log('Phase 9 CPU trade season continuity preview tests passed');
