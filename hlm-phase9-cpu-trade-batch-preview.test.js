'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {prepareApprovedCPUTradeBatch}=require('./hlm-phase9-cpu-trade-batch-preview');
const {commitApprovedCPUTradeSequence}=require('./hlm-phase9-cpu-trade-source-slot-commit');
const repo=createMemorySaveRepository();
repo.save('franchise',createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}]}));
const sourceFingerprint=serializeGameState(repo.load('franchise').state);
const trade=(from,to,id)=>({teamIds:[from,to],legs:[{fromTeamId:from,toTeamId:to,assets:[{type:'player',id:'p1',ownerTeamId:from}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:id});
const steps=[{teamId:'BUF',trade:trade('BUF','NYR','t1')},{teamId:'NYR',trade:trade('NYR','BOS','t2')}];
const preview=prepareApprovedCPUTradeBatch({repository:repo,sourceSlotId:'franchise',steps,expectedSourceFingerprint:sourceFingerprint});
assert.equal(preview.readyForExplicitCommit,true);
assert.equal(preview.committed,false);
assert.equal(preview.stepCount,2);
assert.deepEqual(preview.transactionIds,['t1','t2']);
assert.equal(repo.count(),1);
assert.throws(()=>prepareApprovedCPUTradeBatch({repository:repo,sourceSlotId:'franchise',steps,expectedSourceFingerprint:'stale'}),e=>e.code==='CPU_BATCH_SOURCE_STALE');
assert.throws(()=>prepareApprovedCPUTradeBatch({repository:repo,sourceSlotId:'franchise',steps:[{teamId:'PIT',trade:trade('PIT','NYR','x')}],expectedSourceFingerprint:sourceFingerprint}),e=>e.code==='CPU_TRADE_HUMAN_TEAM_PROTECTED');
const committed=commitApprovedCPUTradeSequence({repository:repo,sourceSlotId:'franchise',destinationSlotId:'approved',steps,expectedSourceFingerprint:preview.sourceFingerprint,confirmCommit:true});
assert.equal(committed.verified,true);
assert.equal(serializeGameState(repo.load('approved').state),preview.candidateFingerprint);
assert.equal(serializeGameState(repo.load('franchise').state),sourceFingerprint);
console.log('Phase 9 CPU trade batch preview and explicit commit integration tests passed');
