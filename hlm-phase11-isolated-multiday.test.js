'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const {create}=require('./hlm-phase11-isolated-single-game');
const memory=new Map([['hlm_front_office_v8','DO_NOT_TOUCH']]);
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const engine={createBrowserFranchiseSaveStore,applyScheduledGame,simulateNextDay,calculateStandings};
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],games:[{id:'g1',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'scheduled'},{id:'g2',date:'2026-10-20',homeTeamId:2,awayTeamId:1,status:'scheduled'}]});
const a=create(engine,storage);a.stage(state,true);const stale=create(engine,storage);
assert.equal(a.reviewNextDay().toDate,'2026-10-19');
assert.throws(()=>a.advanceNextDay(1341,false),/approval/);
const first=a.advanceNextDay(1341,true);assert.equal(first.results.length,1);assert.equal(first.state.meta.currentDate,'2026-10-19');assert.equal(first.standings[0].gp,1);
assert.throws(()=>stale.advanceNextDay(1341,true),/changed/);
const recovered=create(engine,storage);assert.equal(recovered.load().activity.games.filter(g=>g.status==='final').length,1);
assert.equal(recovered.reviewNextDay().toDate,'2026-10-20');
const second=recovered.advanceNextDay(1341,true);assert.equal(second.results.length,1);assert.equal(second.state.activity.games.filter(g=>g.status==='final').length,2);
assert.equal(second.standings[0].gp,2);
assert.throws(()=>recovered.advanceNextDay(1341,true),/No scheduled games remain/);
assert.equal(create(engine,storage).load().meta.currentDate,'2026-10-20');
assert.equal(storage.getItem('hlm_front_office_v8'),'DO_NOT_TOUCH');
const html=fs.readFileSync('hlm-phase11-isolated-single-game.html','utf8');
assert.match(html,/id="day-review"/);assert.match(html,/id="day-approve"/);assert.match(html,/navigator\.locks\.request/);
assert.match(html,/reviewedDay\.fromDate/);
console.log('Mission 1341: two chronological days, GM approval, standings, reload, duplicate and stale-tab protections passed');
