'use strict';
const assert=require('node:assert/strict');
const evidence=require('./cpu-audit-review-evidence-record-timeline-evidence');
const presentation=require('./cpu-audit-review-evidence-record-timeline-presentation');
const bundles=require('./cpu-audit-review-evidence-record-history-bundle');
const gates=require('./cpu-audit-review-evidence-record-history-gate');
const api=require('./cpu-audit-review-evidence-record-history-verification');
const summary={kind:'cpu-audit-public-review-evidence-record-timeline-summary',readOnly:true,count:2,reviewCount:0,reviewStateChanges:0,transitionCount:1};
const record=evidence.create({kind:'cpu-audit-public-review-evidence-record-timeline-bundle',readOnly:true,summary,text:presentation.describe(summary)});
const bundle=bundles.build([record,record]),gate=gates.assess(bundle);
const verified=api.verify(bundle,gate);
assert.equal(verified.verified,true);
assert.equal(verified.requiresHumanReview,false);
assert.equal(verified.snapshotCount,2);
assert.ok(Object.isFrozen(verified));
assert.throws(()=>api.verify(bundle,{...gate,requiresHumanReview:true}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,snapshotCount:1}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,reasons:['forged']}),TypeError);
assert.throws(()=>api.verify({...bundle,text:'forged'},gate),TypeError);
console.log('Aggregate review evidence record history gate verification tests passed');
