'use strict';
const assert=require('node:assert/strict');
const {compareVolumeBalance}=require('./hlm-phase11-shot-volume-balance');
const home=[{shots:15,goals:3,expectedGoals:2},{shots:15,goals:3,expectedGoals:2}];
const away=[{shots:5,goals:1,expectedGoals:1},{shots:5,goals:1,expectedGoals:1}];
const r=compareVolumeBalance(home,away);
assert.equal(r.comparable,true);assert.equal(r.homeShotShare,.75);
assert.equal(r.shotVolumeImbalance,.5);assert.equal(r.volumeCaution,'unequal-shot-volume');
assert.equal(r.normalizedGoals.homePerTenShots,2);assert.equal(r.normalizedGoals.awayPerTenShots,2);
assert.equal(r.normalizedGoals.homeExpectedPerTenShots,1.333333);
assert.deepEqual(r,compareVolumeBalance(home,away));
assert.equal(r.productionActivationEnabled,false);assert.equal(r.automaticallyApplied,false);
assert.equal(r.requiresGMApproval,true);assert.equal(Object.isFrozen(r),true);
const limited=compareVolumeBalance(home,[{shots:1,goals:0,expectedGoals:0}]);
assert.equal(limited.comparable,false);assert.equal(limited.normalizedGoals,null);
assert.equal(limited.homeShotShare,null);assert.equal(limited.volumeCaution,'insufficient-evidence');
const invalid=compareVolumeBalance([...home,{shots:1,goals:2,expectedGoals:0}],away);
assert.equal(invalid.comparable,false);assert.equal(invalid.base.home.invalidPeriods,1);
assert.throws(()=>compareVolumeBalance(null,away),TypeError);
console.log('Shot volume balance deterministic regressions passed');
