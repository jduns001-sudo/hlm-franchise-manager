'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch();
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block'});
  const page=await context.newPage();
  for(const file of ['hlm-phase11-isolated-single-game.html','hlm-phase10-browser.bundle.js','hlm-phase11-isolated-single-game.js']){
   await page.route('**/'+file+'*',route=>route.fulfill({status:200,contentType:file.endsWith('.html')?'text/html':'application/javascript',body:fs.readFileSync(file,'utf8')}));
  }
  await page.goto('https://jduns001-sudo.github.io/hlm-franchise-manager/hlm-phase11-isolated-single-game.html?mission1396='+Date.now(),{waitUntil:'domcontentloaded',timeout:60000});
  await page.evaluate(()=>localStorage.setItem('hlm_front_office_v8','MISSION1396_PRODUCTION_SENTINEL'));
  await page.waitForFunction(()=>document.querySelector('#new-team')?.options.length===32&&!document.querySelector('#new-franchise')?.disabled,{timeout:60000});
  await page.locator('#new-team').selectOption('5');
  page.once('dialog',d=>d.accept());
  await page.locator('#new-franchise').click();
  await page.waitForFunction(()=>document.querySelector('#gm-roster')?.textContent.includes('Players:'),{timeout:60000});
  const key='hlm-phase11-m1340-isolated-single-game-v1';
  await page.evaluate(key=>{const state=JSON.parse(localStorage.getItem(key));state.universe.prospects.push({id:'mission1396-prospect',name:'Unsigned Prospect',position:'C',overall:70,});state.assets.draftPicks.push({pickId:'mission1396-pick',currentOwnerId:5,status:'available'});localStorage.setItem(key,JSON.stringify(state))},key);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelector('#gm-draft-pick')?.options.length===1&&document.querySelector('#gm-draft-prospect')?.options.length===1,{timeout:60000});
  await page.locator('#gm-draft-review').click();
  assert.match(await page.locator('#gm-draft-status').innerText(),/Human GM approval required/);
  page.once('dialog',d=>d.dismiss());
  await page.locator('#gm-draft-approve').click();
  assert.equal(JSON.parse(await page.evaluate(key=>localStorage.getItem(key),key)).assets.draftPicks.find(p=>p.pickId==='mission1396-pick').status,'available','cancel leaves pick available');
  page.once('dialog',d=>d.accept());
  await page.locator('#gm-draft-approve').click();
  await page.waitForFunction(()=>document.querySelector('#gm-draft-status')?.textContent.includes('rights saved'),{timeout:60000});
  assert.equal(JSON.parse(await page.evaluate(key=>localStorage.getItem(key),key)).universe.players.some(p=>p.id==='mission1396-prospect'),false,'draft does not sign');
  await page.waitForFunction(()=>document.querySelector('#prospect-sign-select')?.options.length===1,{timeout:60000});
  assert.match(await page.locator('#gm-roster').innerText(),/Draft rights: 1/);
  const before=await page.evaluate(key=>localStorage.getItem(key),key);
  await page.locator('#prospect-sign-review').click();
  assert.match(await page.locator('#prospect-sign-status').innerText(),/Human GM approval required/);
  page.once('dialog',d=>d.dismiss());
  await page.locator('#prospect-sign-approve').click();
  assert.equal(await page.evaluate(key=>localStorage.getItem(key),key),before,'cancel never saves');
  page.once('dialog',d=>d.accept());
  await page.locator('#prospect-sign-approve').click();
  await page.waitForFunction(()=>document.querySelector('#prospect-sign-status')?.textContent.includes('signed and saved'),{timeout:60000});
  const after=JSON.parse(await page.evaluate(key=>localStorage.getItem(key),key));
  assert.equal(after.universe.players.find(p=>p.id==='mission1396-prospect').teamId,5);
  assert.equal(after.assets.contracts.find(c=>c.contractId==='rookie-contract-1').playerId,'mission1396-prospect');
  assert.equal(after.activity.transactions.filter(t=>t.type==='drafted-prospect-signing').length,1,'one signed transaction');
  assert.equal(after.activity.transactions.find(t=>t.type==='drafted-prospect-signing').contractId,'rookie-contract-1');
  assert.match(await page.locator('#gm-signing-history').innerText(),/rookie-contract-1/);
  assert.equal(await page.locator('#gm-signed-skater').inputValue(),'mission1396-prospect','signed prospect offered to GM');
  const beforePlan=await page.evaluate(key=>localStorage.getItem(key),key);
  await page.locator('#gm-signed-skater-add').click();
  assert.equal(await page.locator('#gm-skater-choice option:checked').filter({hasText:'Unsigned Prospect'}).count(),1,'prospect added to proposed selection');
  assert.equal(await page.evaluate(key=>localStorage.getItem(key),key),beforePlan,'adding proposal never saves');
  await page.evaluate(()=>{
    const select=document.querySelector('#gm-skater-choice');
    const state=JSON.parse(localStorage.getItem('hlm-phase11-m1340-isolated-single-game-v1'));
    const injured=new Set((state.activity.injuries||[]).filter(i=>i.active!==false&&i.status!=='resolved'&&i.status!=='recovered').map(i=>String(i.playerId)));
    const other=[...select.options].filter(o=>o.value!=='mission1396-prospect'&&!injured.has(o.value)).slice(0,2);
    if(other.length!==2)throw Error('Two healthy roster skaters required');
    for(const o of other)o.selected=true;
    select.dispatchEvent(new Event('change',{bubbles:true}));
  });
  await page.locator('#gm-skater-review').click();
  assert.match(await page.locator('#gm-skater-status').innerText(),/Review only, nothing saved/);
  page.once('dialog',d=>d.dismiss());
  await page.locator('#gm-skater-approve').click();
  assert.equal(await page.evaluate(key=>localStorage.getItem(key),key),beforePlan,'cancelled lineup approval never saves');
  page.once('dialog',d=>d.accept());
  await page.locator('#gm-skater-approve').click();
  await page.waitForFunction(()=>document.querySelector('#gm-skater-status')?.textContent.includes('GM approved'),{timeout:60000});
  const approvedPlan=JSON.parse(await page.evaluate(key=>localStorage.getItem(key),key));
  assert.ok(approvedPlan.extensions.phase11GmApprovedSkaters.playerIds.includes('mission1396-prospect'),'prospect approved for skater plan');
  assert.equal(approvedPlan.extensions.phase11ExperimentalRosterAwareScores,false,'score experiment remains off');
  assert.equal(after.extensions.phase11ExperimentalRosterAwareScores,false);
  assert.equal(await page.evaluate(()=>localStorage.getItem('hlm_front_office_v8')),'MISSION1396_PRODUCTION_SENTINEL');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelector('#gm-roster')?.textContent.includes('Unsigned Prospect'),{timeout:60000});
  assert.equal(await page.locator('#prospect-sign-review').isDisabled(),true,'cannot sign twice');
  assert.ok(JSON.parse(await page.evaluate(key=>localStorage.getItem(key),key)).extensions.phase11GmApprovedSkaters.playerIds.includes('mission1396-prospect'),'GM skater plan survives reload');
  assert.match(await page.locator('#gm-signing-history').innerText(),/rookie-contract-1/);
  assert.equal(JSON.parse(await page.evaluate(key=>localStorage.getItem(key),key)).activity.transactions.filter(t=>t.type==='drafted-prospect-signing').length,1);
  assert.equal(await page.evaluate(()=>localStorage.getItem('hlm_front_office_v8')),'MISSION1396_PRODUCTION_SENTINEL');
  console.log('Mission 1396 mobile GM review, cancel, approve, roster, reload and isolation passed');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
