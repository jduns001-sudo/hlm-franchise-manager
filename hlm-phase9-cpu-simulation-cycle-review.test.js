'use strict';
const assert=require('node:assert/strict');
const {createMasterCalendar}=require('./hlm-master-calendar');
const {createSeasonPhaseTimeline}=require('./hlm-season-phase-timeline');
const {createCalendarEventIndex}=require('./hlm-calendar-event');
const {createSimulationStopRules}=require('./hlm-simulation-stop-rules');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {createSimulationCommand,planSimulationCommand}=require('./hlm-simulation-command');
const {authorizeSimulationCommand,executeSimulationCommandCalendar,verifySimulationCommandCalendar}=require('./hlm-simulation-command-execution');
const {createSimulationGameStateCandidate,verifySimulationGameStateCandidate,authorizeSimulationGameStateActivation,activateSimulationGameState,verifySimulationGameStateActivation}=require('./hlm-simulation-gamestate-integration');
const {reviewCPUOrganizationsAfterSimulation}=require('./hlm-phase9-cpu-simulation-cycle-review');
const calendar=createMasterCalendar({currentDate:'2027-04-17'});
const timeline=createSeasonPhaseTimeline({windows:[{phaseId:'regular-season',startDate:'2027-04-01',endDate:'2027-04-30'}]});
const eventIndex=createCalendarEventIndex({events:[{id:'news',type:'news',date:'2027-04-18'}]});
const stopRules=createSimulationStopRules({});
const state=createGameStateEnvelope({meta:{currentDate:'2027-04-17',controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]});
const before=serializeGameState(state);
const plan=planSimulationCommand({calendar,timeline,eventIndex,stopRules,command:createSimulationCommand({command:'day'})});
const authorization=authorizeSimulationCommand({plan,approved:true});
const execution=executeSimulationCommandCalendar({calendar,plan,authorization});
const verified=verifySimulationCommandCalendar({execution});
const candidate=createSimulationGameStateCandidate({state,verification:verified});
const candidateVerification=verifySimulationGameStateCandidate({sourceState:state,candidate});
const activationAuthorization=authorizeSimulationGameStateActivation({verification:candidateVerification,approved:true});
const activation=activateSimulationGameState({verification:candidateVerification,authorization:activationAuthorization});
const simulationVerification=verifySimulationGameStateActivation({activation});
const report=reviewCPUOrganizationsAfterSimulation({sourceState:state,simulationVerification});
assert.equal(report.teamCount,2);
assert.deepEqual(report.leagueReview.items.map(x=>x.teamId),['BUF','NYR']);
assert.equal(report.toDate,'2027-04-18');
assert.equal(report.cpuActionsExecuted,false);
assert.equal(report.persistencePerformed,false);
assert.equal(report.sourcePreserved,true);
assert.equal(serializeGameState(state),before);
assert.equal(serializeGameState(activation.state),report.candidateFingerprint);
assert.throws(()=>reviewCPUOrganizationsAfterSimulation({sourceState:state,simulationVerification:{...simulationVerification,verified:false}}),e=>e.code==='CPU_SIMULATION_REVIEW_UNVERIFIED');
assert.throws(()=>reviewCPUOrganizationsAfterSimulation({sourceState:createGameStateEnvelope({}),simulationVerification}),e=>e.code==='CPU_SIMULATION_REVIEW_SOURCE_MISMATCH');
assert.throws(()=>reviewCPUOrganizationsAfterSimulation({sourceState:state,simulationVerification,decisionOptionsByTeam:{PIT:{}}}),e=>e.code==='CPU_LEAGUE_REVIEW_TEAM_OPTIONS_INVALID');
console.log('Phase 9 leaguewide CPU review after simulation integration tests passed');
