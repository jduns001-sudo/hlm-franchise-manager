'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {FORMAT}=require('./hlm-phase11-indexeddb-backup');
const {LEGACY_DB,validateFranchise,verifyCompatibilityRoundtrip,rejectLegacyEnvelope}=require('./hlm-phase11-legacy-schema-preservation');
const app=fs.readFileSync('app.html','utf8');
for(const pattern of [/const DBNAME='hlm_front_office_v8'/,/const OLDDB='hlm_front_office_v5'/,/const STORE='state'/,/function compactState\(\)/,/indexedDB\.open\(DBNAME,1\)/,/objectStore\(STORE\)\.get\('db'\)/,/objectStore\(STORE\)\.put\(state,'db'\)/])assert.match(app,pattern,'Production save architecture drift');
assert.match(app,/schema\s*:\s*7/,'Expected compact schema 7 not found');
const sample={schema:7,settings:{controlledTeamId:42},roster:[{id:101,teamId:42,position:'C'}],contracts:[{playerId:101,capHit:1250000}],draftPicks:[{year:2027,round:1,ownerId:42}],prospects:[{id:202,potential:'Elite'}],history:[{season:2026,record:'42-30-10'}],customPlayers:[{id:202,name:'Future Star'}],otherCustomData:{untouched:true}};
const snapshot={format:FORMAT,database:'hlm_front_office_v8',store:'state',record:'db',existed:true,state:sample};
const before=JSON.stringify(snapshot);
assert.deepEqual(verifyCompatibilityRoundtrip(snapshot),snapshot);
assert.equal(JSON.stringify(snapshot),before);
assert.equal(verifyCompatibilityRoundtrip(snapshot).state.settings.controlledTeamId,42);
assert.deepEqual(verifyCompatibilityRoundtrip(snapshot).state.otherCustomData,{untouched:true});
for(const schema of [0,5,6,8,999,'7',undefined])assert.throws(()=>validateFranchise({...snapshot,state:{...sample,schema}}),/schema/);
assert.throws(()=>validateFranchise({...snapshot,state:{...sample,settings:{}}}),/controlled team/);
assert.throws(()=>validateFranchise({...snapshot,state:{...sample,contracts:'bad'}}),/contracts/);
assert.throws(()=>rejectLegacyEnvelope({...snapshot,database:LEGACY_DB}),/Legacy v5/);
assert.throws(()=>validateFranchise({...snapshot,format:'unsupported'}),/envelope/);
console.log('Phase 11 app save architecture, representative schema-7 fixtures, franchise equality, legacy rejection passed');
