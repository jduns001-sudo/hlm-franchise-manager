'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {create}=require('./hlm-phase11-isolated-single-game');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const mem=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>mem.get(k)??null,setItem:(k,v)=>mem.set(k,v)};
const engine={applyScheduledGame,simulateNextDay,calculateStandings,createBrowserFranchiseSaveStore};
const gm=create(engine,storage);
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[{id:1,name:'Owner'},{id:2,name:'CPU'},{id:3,name:'Rival'}],games:[{id:'g1',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'scheduled'},{id:'g2',date:'2026-10-19',homeTeamId:2,awayTeamId:3,status:'scheduled'},{id:'g3',date:'2026-10-20',homeTeamId:3,awayTeamId:1,status:'scheduled'}]});
gm.stage(state,true);
const preview=gm.reviewNextDay();
assert.equal(preview.games,2);
assert.equal(preview.toDate,'2026-10-19');
assert.deepEqual(Array.from(preview.scheduledGameIds),['g1','g2']);
assert.deepEqual(Array.from(preview.matchups,g=>[g.gameId,g.homeTeamId,g.awayTeamId,g.controlledTeamInvolved]),[['g1',1,2,true],['g2',2,3,false]]);
assert.ok(Object.isFrozen(preview.matchups)&&Object.isFrozen(preview.matchups[0]));
assert.equal(preview.matchups[0].readiness.rosterPlayers,0);
assert.equal(preview.matchups[0].readiness.experimentalEnabled,false);
assert.equal(preview.matchups[0].readiness.unresolvedInjuries,0);
assert.equal(preview.matchups[1].readiness,null);
assert.ok(Object.isFrozen(preview.matchups[0].readiness));
assert.equal(gm.peek().activity.games.filter(g=>g.status==='scheduled').length,3,'Review cannot simulate or save');
assert.throws(()=>gm.advanceNextDay(1377,false),/approval/);
const stale=create(engine,storage);
const day=gm.advanceNextDay(1377,true);
assert.equal(day.results.length,2);
assert.equal(gm.reviewNextDay().games,1);
assert.throws(()=>stale.advanceNextDay(1377,true),/changed/);
assert.equal(storage.getItem('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
const html=fs.readFileSync('hlm-phase11-isolated-single-game.html','utf8');
assert.match(html,/Scheduled matchups \(not predictions\)/);
assert.match(html,/JSON\.stringify\(current\.matchups\)!==JSON\.stringify\(reviewedDay\.matchups\)/);
const mem2=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const store2={getItem:k=>mem2.get(k)??null,setItem:(k,v)=>mem2.set(k,v)};
const gm2=create(engine,store2);
const detailed=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],players:[{id:11,teamId:1,name:'Goalie',position:'G',overall:90},{id:12,teamId:1,name:'Center',position:'C',overall:91},{id:13,teamId:1,name:'Wing',position:'LW',overall:91},{id:14,teamId:1,name:'Defense',position:'D',overall:91}],games:[{id:'owner',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'scheduled'}],injuries:[{playerId:11,status:'active',type:'ankle'}]});
detailed.extensions={...detailed.extensions,phase11GmGoaliePlan:{teamId:1,playerId:11},phase11GmApprovedSkaters:{teamId:1,playerIds:[12,13,14]},phase11ExperimentalRosterAwareScores:false};
gm2.stage(detailed,true);
const ownerReview=gm2.reviewNextDay();
assert.equal(ownerReview.matchups[0].readiness.rosterPlayers,4);
assert.equal(ownerReview.matchups[0].readiness.unresolvedInjuries,1);
assert.equal(ownerReview.matchups[0].readiness.approvedGoalieId,11);
assert.equal(ownerReview.matchups[0].readiness.goalieNeedsReview,true);
assert.equal(ownerReview.matchups[0].readiness.approvedSkaters,3);
assert.equal(ownerReview.matchups[0].readiness.skatersNeedReview,false);
assert.throws(()=>gm2.advanceNextDay(1378,true),/injury|goalie/i,'Injured approved goalie remains blocked');
assert.equal(mem2.getItem('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
console.log('Mission 1378: real matchup manifest, controlled team, no mutation, GM approval, stale tab, production isolation pass');
