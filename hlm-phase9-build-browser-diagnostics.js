'use strict';
// Mission 556: dependency-free CommonJS browser bundle generator.
// Run: node hlm-phase9-build-browser-diagnostics.js
const fs=require('node:fs'),path=require('node:path');
const root=__dirname;
const entry='hlm-phase9-front-office-diagnostics-export-session.js';
const modules=new Map();
function collect(filename){
 if(modules.has(filename))return;
 const source=fs.readFileSync(path.join(root,filename),'utf8');
 modules.set(filename,source);
 for(const match of source.matchAll(/require\(['"]([^'"]+)['"]\)/g)){
  const dependency=match[1];
  if(!dependency.startsWith('./'))throw new Error('Unsupported browser dependency: '+dependency+' in '+filename);
  const child=path.posix.normalize(path.posix.join(path.posix.dirname(filename),dependency+'.js'));
  if(child.startsWith('../'))throw new Error('Dependency escapes repository: '+child);
  collect(child);
 }
}
collect(entry);
const rows=[...modules].map(([filename,source])=>JSON.stringify(filename)+':function(module,exports,require){\n'+source+'\n}').join(',\n');
const output='/* Generated by hlm-phase9-build-browser-diagnostics.js */\n(function(global){\n'+
 'var modules={\n'+rows+'\n};var cache={};\n'+
 'function load(name){if(cache[name])return cache[name].exports;if(!modules[name])throw Error("Missing module: "+name);var module={exports:{}};cache[name]=module;var base=name.split("/");base.pop();function localRequire(request){if(request.slice(0,2)!=="./")throw Error("Unsupported require: "+request);var parts=base.concat(request.slice(2).split("/"));var normalized=[];parts.forEach(function(part){if(part==="..")normalized.pop();else if(part!==".")normalized.push(part);});return load(normalized.join("/")+".js");}modules[name](module,module.exports,localRequire);return module.exports;}\n'+
 'global.HLMPhase9Diagnostics=load('+JSON.stringify(entry)+');\n'+
 '})(typeof window!=="undefined"?window:globalThis);\n';
fs.writeFileSync(path.join(root,'hlm-phase9-diagnostics-browser.bundle.js'),output);
console.log('Built browser diagnostics bundle with '+modules.size+' modules');
