'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {assessGMReviewRiskBriefReadiness}=require('./hlm-phase11-gm-review-risk-brief-readiness');
const {checkGMReviewDecisionBriefChange}=require('./hlm-phase11-gm-review-decision-brief-change-check');
const {exportGMReviewDecisionAudit}=require('./hlm-phase11-gm-review-decision-audit-export');
const {MAX_AUDIT_CHARS,validateGMReviewDecisionAuditImport:validate}=require('./hlm-phase11-gm-review-decision-audit-import-validation');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const risk=assessGMReviewRiskBriefReadiness(items,digest,true,1000,[1100,1200],500).currentSha256;
const previous=checkGMReviewDecisionBriefChange(items,digest,true,1000,[1100,1200],500,risk).currentSha256;
const exported=exportGMReviewDecisionAudit(items,digest,true,1000,[1100,1200],500,risk,previous,1300);
const result=validate(exported.text);
assert.equal(result.valid,true);assert.equal(result.reason,'validated-read-only');assert.deepEqual(result.record,exported.record);
assert.equal(validate('not-json').valid,false);assert.equal(validate('x'.repeat(MAX_AUDIT_CHARS+1)).reason,'invalid-size');
assert.equal(validate(JSON.stringify({...exported.record,gameplayActionAuthorized:true})).valid,false);
assert.equal(validate(JSON.stringify({...exported.record,requiresGMApproval:false})).valid,false);
assert.equal(validate(JSON.stringify({...exported.record,sha256:'xyz'})).valid,false);
assert.equal(validate(JSON.stringify({...exported.record,unknown:true})).reason,'invalid-schema');
assert.equal(validate(JSON.stringify({...exported.record,status:'changed',requiresFreshGMReview:false})).valid,false);
assert.equal(validate(JSON.stringify({...exported.record,checkedAtMs:-1})).valid,false);
assert.equal(validate(JSON.stringify({...exported.record,checkedAtMs:null})).valid,false);
const invalidTime=exportGMReviewDecisionAudit(items,digest,true,1000,[1100,1200],500,risk,previous,-1);
assert.equal(validate(invalidTime.text).valid,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(result[key],false);
assert.equal(result.requiresGMApproval,true);assert.ok(Object.isFrozen(result));assert.ok(Object.isFrozen(result.record));
assert.deepEqual(validate(exported.text),result);
console.log('GM review decision audit import validation deterministic tests passed');
