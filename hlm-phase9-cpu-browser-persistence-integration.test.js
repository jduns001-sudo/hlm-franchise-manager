'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserSaveAdapter}=require('./hlm-browser-save-adapter');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {prepareApprovedCPUTradeBatch}=require('./hlm-phase9-cpu-trade-batch-preview');
const {executeApprovedCPUTradeBatch}=require('./hlm-phase9-cpu-approved-trade-persistent-executor');
const {previewCPUMultiSeasonSave}=require('./hlm-phase9-cpu-multiseason-preview-commit');
const {executeReviewedCPUMultiSeason}=require('./hlm-phase9-cpu-persistent-multiseason-execution');
const items=new Map();
const storage={getItem:key=>items.has(key)?items.get(key):null,setItem:(key,value)=>items.set(key,value),removeItem:key=>items.delete(key)};
const repo=createBrowserSaveAdapter(storage);
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT',currentDate:'2030-06-30'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]});
state.history.seasons.push({id:'2029-30',status:'completed',champion:'PIT'});
repo.save('human',state);
const before=serializeGameState(repo.load('human').state);
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'browser-cpu-1'};
const steps=[{teamId:'BUF',trade}];
const preview=prepareApprovedCPUTradeBatch({repository:repo,sourceSlotId:'human',steps,expectedSourceFingerprint:before});
const committed=executeApprovedCPUTradeBatch({repository:repo,sourceSlotId:'human',destinationSlotId:'trade-review',steps,reviewedPreview:preview,confirmExecution:true});
assert.equal(committed.verified,true);
assert.equal(repo.load('trade-review').state.universe.players[0].teamId,'NYR');
assert.equal(serializeGameState(repo.load('human').state),before);
const transitions=[{fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01'}];
const seasonPreview=previewCPUMultiSeasonSave({repository:repo,sourceSlotId:'trade-review',transitions});
const season=executeReviewedCPUMultiSeason({repository:repo,reviewedPreview:seasonPreview,transitions,destinationSlotId:'next-season',confirmExecution:true});
assert.equal(season.verified,true);
assert.equal(repo.load('next-season').state.meta.currentDate,'2030-07-01');
assert.equal(repo.load('next-season').state.universe.players[0].teamId,'NYR');
assert.equal(serializeGameState(repo.load('human').state),before);
assert.equal(repo.list().length,3);
assert.throws(()=>executeApprovedCPUTradeBatch({repository:repo,sourceSlotId:'human',destinationSlotId:'trade-review',steps,reviewedPreview:preview,confirmExecution:true}),e=>e.code==='CPU_COMMIT_DESTINATION_OCCUPIED');
console.log('Phase 9 browser-backed persistent CPU trade and season continuity integration tests passed');
