'use strict';
const assert=require('node:assert/strict');
const {build}=require('./hlm-phase11-gm-human-evidence-review-ledger');
const packet={kind:'experimental-gm-human-session-handoff-packets',packets:[{checks:[{taskId:'t1',sessionNumber:1,gateId:'g1',sourceRequirement:'independent citation',remainingGap:'source absent',uncertainty:'high'}]}]};
assert.throws(()=>build(packet,[],false),/approval/);
assert.throws(()=>build({},[],true),/Valid handoff/);
assert.throws(()=>build(packet,[{taskId:'unknown',comment:'x'}],true),/unknown/);
assert.throws(()=>build(packet,[{taskId:'t1',comment:'a'},{taskId:'t1',comment:'b'}],true),/Duplicate/);
const result=build(packet,[{taskId:'t1',comment:'request source'}],true);
assert.equal(result.notedCount,1);
assert.equal(result.verifiedCount,0);
assert.equal(result.entries[0].sourceVerification,'not-performed');
assert.equal(result.entries[0].eligibility,'unknown');
assert.equal(result.productionActivationAllowed,false);
assert.equal(result.persistencePerformed,false);
assert.equal(result.automaticTransactionsAllowed,false);
assert.equal(result.finalDecisionMaker,'human-gm');
assert.deepEqual(build(packet,[{taskId:'t1',comment:'request source'}],true),result);
console.log('Mission 1274 deterministic Node regressions passed');