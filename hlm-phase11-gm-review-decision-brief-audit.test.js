'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {assessGMReviewRiskBriefReadiness}=require('./hlm-phase11-gm-review-risk-brief-readiness');
const {checkGMReviewDecisionBriefChange}=require('./hlm-phase11-gm-review-decision-brief-change-check');
const {auditGMReviewDecisionBrief:audit}=require('./hlm-phase11-gm-review-decision-brief-audit');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const riskDigest=assessGMReviewRiskBriefReadiness(items,digest,true,1000,[1100,1200],500).currentSha256;
const initial=checkGMReviewDecisionBriefChange(items,digest,true,1000,[1100,1200],500,riskDigest);
const current=audit(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256,1300);
assert.equal(current.status,'unchanged');assert.equal(current.checkedAtMs,1300);
assert.equal(current.requiresFreshGMReview,false);
assert.match(current.lines.join(' '),/Human GM approval still required/);
const changed=audit(items,digest,true,1000,[1100,1501],500,riskDigest,initial.currentSha256,1600);
assert.equal(changed.status,'changed');assert.equal(changed.requiresFreshGMReview,true);
const invalid=audit(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256,-1);
assert.equal(invalid.status,'invalid-audit-time');assert.equal(invalid.checkedAtMs,null);assert.equal(invalid.requiresFreshGMReview,true);
assert.equal(audit(items,digest,true,1000,[1100,1200],500,riskDigest,'bad',1300).status,'unverified');
assert.equal(audit(items,'0'.repeat(64),true,1000,[1100,1200],500,riskDigest,initial.currentSha256,1300).requiresFreshGMReview,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.equal(current.requiresGMApproval,true);assert.ok(Object.isFrozen(current));assert.ok(Object.isFrozen(current.lines));
assert.deepEqual(audit(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256,1300),current);
console.log('GM review decision brief audit deterministic tests passed');
