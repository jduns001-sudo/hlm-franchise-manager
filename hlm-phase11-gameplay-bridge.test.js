'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBridge,KEY}=require('./hlm-phase11-gameplay-bridge');
const sandbox={};sandbox.window=sandbox;vm.runInNewContext(fs.readFileSync('hlm-phase10-browser.bundle.js','utf8'),sandbox);
const engine=sandbox.HLMPhase10;
const map=new Map([['hlm_front_office_v8','PRODUCTION-UNTOUCHED']]);
const storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v)};
const bridge=createBridge(engine,storage);
const state=createGameStateEnvelope({meta:{saveId:'m1207',controlledTeamId:1,currentDate:'2026-10-12'},teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],games:[{id:'G1',date:'2026-10-13',status:'scheduled',homeTeamId:1,awayTeamId:2},{id:'G2',date:'2026-10-14',status:'scheduled',homeTeamId:2,awayTeamId:1}]});
const initial=JSON.stringify(state);
assert.equal(bridge.summary(state).team,'Owner');
assert.equal(map.size,1);
assert.throws(()=>bridge.importIsolated(state,false),/confirmation/);
assert.throws(()=>bridge.advance(false,10),/confirmation/);
bridge.importIsolated(state,true);
const first=bridge.advance(true,20261013);
assert.equal(first.toDate,'2026-10-13');
assert.equal(first.results.length,1);
assert.equal(bridge.load().activity.games.filter(g=>g.status==='final').length,1);
assert.equal(bridge.load().meta.currentDate,'2026-10-13');
assert.equal(first.summary.standings.reduce((sum,r)=>sum+r.gp,0),2);
assert.equal(JSON.stringify(state),initial);
assert.equal(map.get('hlm_front_office_v8'),'PRODUCTION-UNTOUCHED');
assert.equal(map.size,2);
const second=bridge.advance(true,20261014);
assert.equal(second.results.length,1);
assert.equal(bridge.load().activity.games.filter(g=>g.status==='final').length,2);
assert.throws(()=>bridge.advance(true,20261015),/No scheduled games/);
const invalid=JSON.parse(initial);invalid.activity.games.push({...invalid.activity.games[0]});
assert.throws(()=>bridge.importIsolated(invalid,true),/Duplicate/);
assert.equal(map.get('hlm_front_office_v8'),'PRODUCTION-UNTOUCHED');
assert.equal(bridge.key,KEY);
console.log('Mission 1207 deterministic isolated gameplay, standings, reload and production isolation passed');
