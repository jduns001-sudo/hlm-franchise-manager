'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {checkGMReviewDigestConsistency}=require('./hlm-phase11-gm-review-digest-consistency');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const changed=checkGMReviewDigestConsistency(a.text,b.text);
assert.deepEqual({valid:changed.valid,consistent:changed.consistent,totalChanges:changed.totalChanges},{valid:true,consistent:true,totalChanges:3});
assert.equal(checkGMReviewDigestConsistency(a.text,a.text).consistent,true);
assert.equal(checkGMReviewDigestConsistency('{',b.text).valid,false);
assert.equal(changed.saveWriteAllowed,false);
assert.equal(changed.gameplayActionAuthorized,false);
assert.equal(changed.productionActivationEnabled,false);
assert.equal(changed.requiresGMApproval,true);
assert.ok(Object.isFrozen(changed));
assert.deepEqual(checkGMReviewDigestConsistency(a.text,b.text),changed);
console.log('GM review digest consistency deterministic tests passed');
