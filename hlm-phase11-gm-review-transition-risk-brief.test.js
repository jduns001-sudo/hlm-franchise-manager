'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {buildGMReviewTransitionRiskBrief:brief}=require('./hlm-phase11-gm-review-transition-risk-brief');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const current=brief(items,digest,true,1000,[1100,1200],500);
assert.equal(current.status,'current');assert.equal(current.reviewRequired,false);assert.match(current.headline,/GM approval still required/);
const expired=brief(items,digest,true,1000,[1100,1200,1501],500);
assert.equal(expired.status,'review-required');assert.equal(expired.reviewRequired,true);assert.match(expired.lines[2],/2/);
const unavailable=brief(items,digest,true,1000,[1200,1100],500);
assert.equal(unavailable.status,'unavailable');assert.equal(unavailable.reviewRequired,true);
assert.equal(brief(items,'0'.repeat(64),true,1000,[1100,1200],500).reviewRequired,true);
assert.equal(brief([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500).reviewRequired,true);
assert.equal(brief(items,digest,false,1000,[1100,1200],500).reviewRequired,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.equal(current.requiresGMApproval,true);assert.ok(Object.isFrozen(current));assert.ok(Object.isFrozen(current.lines));
assert.deepEqual(brief(items,digest,true,1000,[1100,1200],500),current);
console.log('GM review transition risk brief deterministic tests passed');
