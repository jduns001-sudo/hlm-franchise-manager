'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {finalizeChampionshipSeason}=require('./hlm-phase10-season-finalization');
const {beginNextSeason}=require('./hlm-phase10-next-season');
const state=createGameStateEnvelope({meta:{saveId:'transition',currentDate:'2027-06-20',controlledTeamId:1},teams:[{id:1,name:'Wolves'},{id:2,name:'Falcons'}],games:[{id:'old',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:3,awayGoals:1,overtime:false}],contracts:[{id:'c1'}]});
state.extensions.phase10Playoffs={status:'complete',championTeamId:1,rounds:[[]]};
const {nextState:archived}=finalizeChampionshipSeason(state,'2026-27');
const input=JSON.stringify(archived);
const options={completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'};
const {nextState,summary}=beginNextSeason(archived,options);
assert.equal(summary.scheduledGames,2);
assert.equal(nextState.activity.games.length,2);
assert.ok(nextState.activity.games.every(g=>g.status==='scheduled'));
assert.equal(nextState.history.seasons.length,1);
assert.equal(nextState.assets.contracts.length,1);
assert.equal(nextState.meta.controlledTeamId,1);
assert.equal(nextState.meta.currentDate,'2027-10-01');
assert.equal(nextState.extensions.phase10CurrentSeasonId,'2027-28');
assert.equal(nextState.extensions.phase10Playoffs,undefined);
assert.equal(JSON.stringify(archived),input);
assert.throws(()=>beginNextSeason(nextState,options),/already initialized|unfinished/);
assert.throws(()=>beginNextSeason(state,options),/must be archived/);
assert.throws(()=>beginNextSeason(archived,{...options,startDate:'2027-06-20'}),/after championship/);
assert.throws(()=>beginNextSeason(archived,{...options,nextSeasonId:'2026-27'}),/Distinct/);
console.log('Phase 10 next season transition tests passed');
