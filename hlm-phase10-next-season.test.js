'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {beginNextSeason}=require('./hlm-phase10-next-season');
const teams=[1,2,3,4].map(id=>({id,name:'Team '+id}));
const games=[{id:'g1',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:3,awayGoals:1,overtime:false}];
const state=createGameStateEnvelope({meta:{saveId:'demo',currentDate:'2027-06-20',controlledTeamId:1},teams,games});
state.extensions.phase10Playoffs={status:'complete',championTeamId:1,rounds:[[{highSeed:{seed:1,teamId:1},lowSeed:{seed:4,teamId:4},status:'complete',winnerTeamId:1,games:[]}]]};
const original=JSON.stringify(state);
const {nextState,scheduledGames}=beginNextSeason(state,{completedSeasonId:'2026-27',nextSeasonStartDate:'2027-10-01'});
assert.equal(scheduledGames,12);
assert.equal(nextState.history.seasons.length,1);
assert.equal(nextState.history.seasons[0].regularSeasonResults.length,1);
assert.equal(nextState.activity.games.every(g=>g.status==='scheduled'),true);
assert.equal(nextState.extensions.phase10Playoffs,undefined);
assert.equal(nextState.meta.currentDate,'2027-10-01');
assert.equal(JSON.stringify(state),original);
assert.throws(()=>beginNextSeason(state,{completedSeasonId:'2026-27',nextSeasonStartDate:'2027-06-19'}),/after the current date/);
assert.throws(()=>beginNextSeason(state,{completedSeasonId:'2026-27',nextSeasonStartDate:'bad'}),/date/i);
console.log('Phase 10 next season tests passed');
