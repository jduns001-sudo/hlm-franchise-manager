'use strict';
const assert=require('node:assert/strict');
const {inspect,select,IMPORT_KEY,SELECT_KEY}=require('./hlm-phase11-franchise-selection');
const data=new Map([['legacy-front-office','KEEP'],['hlm-phase10-demo-v1','KEEP10']]);
const writes=[];
const storage={getItem:k=>data.has(k)?data.get(k):null,setItem:(k,v)=>{writes.push(k);data.set(k,v)}};
assert.equal(inspect(storage).available,false);
assert.throws(()=>select(storage,'imported',{confirm:true}),/No imported/);
assert.throws(()=>select(storage,'existing'),/confirmation/);
data.set(IMPORT_KEY,JSON.stringify({universe:{teams:[{id:1}],players:[{id:1}]}}));
assert.deepEqual(inspect(storage),{available:true,selected:false,teams:1,players:1});
assert.equal(select(storage,'imported',{confirm:true}),'imported');
assert.equal(inspect(storage).selected,true);
assert.equal(select(storage,'existing',{confirm:true}),'existing');
assert.deepEqual(writes,[SELECT_KEY,SELECT_KEY]);
assert.equal(data.get('legacy-front-office'),'KEEP');
assert.equal(data.get('hlm-phase10-demo-v1'),'KEEP10');
assert.throws(()=>select(storage,'unexpected',{confirm:true}),/Unknown/);
console.log('Phase 11 explicit selection and legacy-save isolation passed');
