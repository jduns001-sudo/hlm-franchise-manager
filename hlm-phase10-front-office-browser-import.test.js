'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('phase10-demo.html','utf8');
const sandbox={};sandbox.window=sandbox;
vm.runInNewContext(fs.readFileSync('hlm-phase10-browser.bundle.js','utf8'),sandbox,{timeout:5000});
const api=sandbox.HLMPhase10;
assert.match(html,/id="find-front-office"/);
assert.match(html,/id="import-team"/);
assert.match(html,/id="import-front-office"/);
assert.match(html,/hlm_tracker_v3/);
assert.match(html,/store\.save\(imported\.nextState\)/);
assert.equal(typeof api.createPhase10FromFrontOffice,'function');
assert.equal(typeof api.generateRoundRobinSchedule,'function');
const original={teams:[{id:1,name:'A'},{id:2,name:'B'}],players:[{id:10,name:'P',teamId:1}]};
const before=JSON.stringify(original);
const {nextState}=api.createPhase10FromFrontOffice(original,{controlledTeamId:1,currentDate:'2026-10-12'});
nextState.activity.games=api.generateRoundRobinSchedule(nextState.universe.teams,'2026-10-12',2);
assert.equal(nextState.activity.games.length,2);
assert.equal(nextState.universe.players.length,1);
assert.equal(JSON.stringify(original),before);
console.log('Phase 10 Front Office browser import smoke tests passed');
