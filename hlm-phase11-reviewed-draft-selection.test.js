'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {selectDraftProspect}=require('./hlm-phase10-draft-selection');
const {create}=require('./hlm-phase11-isolated-single-game');
const memory=new Map();
const storage={getItem:k=>memory.has(k)?memory.get(k):null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k)};
const engine={selectDraftProspect,applyScheduledGame(){},calculateStandings(){},createBrowserFranchiseSaveStore(s,k){return {load(){const raw=s.getItem(k);return raw?JSON.parse(raw):null},save(state){s.setItem(k,JSON.stringify(state))}}}};
const gm=create(engine,storage);
const state=createGameStateEnvelope({meta:{controlledTeamId:5},teams:[{id:5,name:'Pittsburgh'},{id:3,name:'New York'}],players:[{id:'roster',teamId:5,name:'Roster Player'}],prospects:[{id:'prospect',name:'Draft Prospect',position:'C'}],draftPicks:[{pickId:'first',currentOwnerId:5,status:'available'}]});
gm.stage(state,true);
const options={pickId:'first',prospectId:'prospect',teamId:5};
assert.throws(()=>gm.reviewDraftSelection({...options,teamId:3}),/controlled team/);
assert.throws(()=>gm.approveReviewedDraftSelection(true),/Review draft selection/);
const before=storage.getItem(gm.key);
assert.equal(gm.reviewDraftSelection(options).prospectName,'Draft Prospect');
assert.equal(storage.getItem(gm.key),before,'review never saves');
assert.throws(()=>gm.approveReviewedDraftSelection(false),/Human GM/);
assert.equal(storage.getItem(gm.key),before,'cancel never saves');
gm.approveReviewedDraftSelection(true);
let saved=gm.load();
assert.equal(saved.universe.prospects[0].draftedByTeamId,5);
assert.equal(saved.universe.prospects[0].draftPickId,'first');
assert.equal(saved.assets.draftPicks[0].status,'used');
assert.equal(saved.universe.players.length,1,'draft rights do not sign player');
assert.equal(saved.assets.contracts.length,0,'draft rights do not create contract');
assert.throws(()=>gm.reviewDraftSelection(options),/already used/);
const second=createGameStateEnvelope({meta:{controlledTeamId:5},teams:[{id:5},{id:3}],prospects:[{id:'another',name:'Another'}],draftPicks:[{pickId:'second',currentOwnerId:5,status:'available'}]});
storage.setItem(gm.key,JSON.stringify(second));gm.load();
gm.reviewDraftSelection({pickId:'second',prospectId:'another',teamId:5});
storage.setItem(gm.key,JSON.stringify({...second,extensions:{concurrentChange:true}}));
assert.throws(()=>gm.approveReviewedDraftSelection(true),/changed/);
assert.equal(JSON.parse(storage.getItem(gm.key)).extensions.concurrentChange,true,'stale write never overwrites');
assert.equal(storage.getItem('hlm_front_office_v8'),null,'production untouched');
console.log('Mission 1398 GM draft review, cancel, ownership, rights-only, duplicate and stale-save protections passed');
