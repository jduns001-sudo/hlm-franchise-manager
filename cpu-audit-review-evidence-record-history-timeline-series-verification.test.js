'use strict';
const assert=require('node:assert/strict');
const evidence=require('./cpu-audit-review-evidence-record-history-timeline-evidence');
const presentation=require('./cpu-audit-review-evidence-record-history-timeline-presentation');
const bundles=require('./cpu-audit-review-evidence-record-history-timeline-series-bundle');
const gates=require('./cpu-audit-review-evidence-record-history-timeline-series-gate');
const api=require('./cpu-audit-review-evidence-record-history-timeline-series-verification');
const summary={kind:'cpu-audit-public-review-evidence-record-history-timeline-summary',readOnly:true,count:2,reviewCount:0,reviewStateChanges:0,transitionCount:1};
const record=evidence.create({kind:'cpu-audit-public-review-evidence-record-history-timeline-bundle',readOnly:true,summary,text:presentation.describe(summary)});
const bundle=bundles.build([record]);
const gate=gates.assess(bundle);
const result=api.verify(bundle,gate);
assert.equal(result.verified,true);
assert.equal(result.requiresHumanReview,false);
assert.equal(result.snapshotCount,1);
assert.ok(Object.isFrozen(result));
assert.throws(()=>api.verify(bundle,{...gate,requiresHumanReview:true}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,snapshotCount:2}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,reasons:['forged']}),TypeError);
assert.throws(()=>api.verify({...bundle,text:'tampered'},gate),TypeError);
const empty=bundles.build([]);
assert.equal(api.verify(empty,gates.assess(empty)).requiresHumanReview,true);
console.log('Aggregate review evidence record history timeline series verification tests passed');
