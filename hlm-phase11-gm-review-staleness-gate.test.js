'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {checkGMReviewStaleness}=require('./hlm-phase11-gm-review-staleness-gate');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const items=[{before:a.text,after:b.text}];const digest=prepareGMReviewIntegrity(items).sha256;
const current=checkGMReviewStaleness(items,digest);
assert.equal(current.status,'unchanged');assert.equal(current.reviewCurrent,true);
assert.equal(current.requiresFreshGMReview,false);assert.equal(current.requiresGMApproval,true);
const stale=checkGMReviewStaleness(items,'0'.repeat(64));
assert.equal(stale.status,'changed');assert.equal(stale.reviewCurrent,false);assert.equal(stale.requiresFreshGMReview,true);
for(const input of [[],null,[{before:'{',after:b.text}]])assert.equal(checkGMReviewStaleness(input,digest).status,'unavailable');
assert.equal(checkGMReviewStaleness(items,'invalid').requiresFreshGMReview,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.ok(Object.isFrozen(current));assert.deepEqual(checkGMReviewStaleness(items,digest),current);
console.log('GM review staleness gate deterministic tests passed');
