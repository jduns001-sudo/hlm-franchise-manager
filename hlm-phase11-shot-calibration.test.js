'use strict';
const assert=require('node:assert/strict');
const {calibrateShotEvents}=require('./hlm-phase11-shot-calibration');
const lineup=Array.from({length:10},(_,i)=>({id:'P'+i,position:i<6?'F':'D',ovr:80}));
const snapshot=JSON.stringify(lineup);
const a=calibrateShotEvents(lineup,{samples:500});
assert.deepEqual(calibrateShotEvents(lineup,{samples:500}),a);
assert(a.projectedShotsPer60>20&&a.projectedShotsPer60<40,'plausible baseline');
assert(a.forwardShotShare>0.6&&a.forwardShotShare<0.9,'position weighted');
assert(Math.abs(a.forwardShotShare+a.defenseShotShare-1)<1e-10);
assert.equal(a.playerShots.reduce((sum,p)=>sum+p.meanShotsPerPeriod,0),a.meanShotsPerPeriod);
assert.equal(a.productionActivationEnabled,false);
assert.equal(a.automaticallyApplied,false);
assert.equal(a.requiresGMApproval,true);
assert.equal(JSON.stringify(lineup),snapshot);
assert.notDeepEqual(calibrateShotEvents(lineup,{samples:500,seedStart:500}),a);
const short=calibrateShotEvents(lineup,{samples:200,periodSeconds:60,shiftSeconds:15});
assert(short.meanShotsPerPeriod<a.meanShotsPerPeriod);
const boosted=lineup.map(p=>({...p,ovr:p.id==='P0'?120:60}));
const strong=calibrateShotEvents(boosted,{samples:500});
const weak=calibrateShotEvents(boosted.map(p=>({...p,ovr:p.id==='P0'?30:p.ovr})),{samples:500});
assert(strong.playerShots[0].meanShotsPerPeriod>weak.playerShots[0].meanShotsPerPeriod,'OVR sensitivity');
for(const options of [{samples:0},{samples:2001},{seedStart:-1},{seedStart:Number.MAX_SAFE_INTEGER}])assert.throws(()=>calibrateShotEvents(lineup,options),TypeError);
console.log('Mission 1124 seeded calibration, position, OVR, short period and safety passed',a.projectedShotsPer60);
