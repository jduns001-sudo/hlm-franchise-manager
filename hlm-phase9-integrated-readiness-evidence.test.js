'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {assessIntegratedPhase9Readiness}=require('./hlm-phase9-integrated-readiness-evidence');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]});
const before=serializeGameState(state);
const report=assessIntegratedPhase9Readiness(state,'BUF');
assert.equal(report.leaguewideCPUCount,2);
assert.equal(report.checks.leaguewideReview,true);
assert.equal(report.checks.isolatedReviewedCPUTradeIntegration,true);
assert.equal(report.checks.automaticGameProcessing,false);
assert.equal(report.checks.automaticCPUDecisionExecution,false);
assert.equal(report.checks.liveFrontOfficeIntegration,false);
assert.equal(report.readyForPhase10,false);
assert.equal(report.productionCPUExecutionEnabled,false);
assert.ok(report.blockers.includes('multiSeasonProductionContinuity'));
assert.equal(serializeGameState(state),before);
assert.ok(Object.isFrozen(report)&&Object.isFrozen(report.checks)&&Object.isFrozen(report.blockers));
assert.throws(()=>assessIntegratedPhase9Readiness(state,'BUF',{decisionOptionsByTeam:{PIT:{}}}),e=>e.code==='CPU_LEAGUE_REVIEW_TEAM_OPTIONS_INVALID');
console.log('Phase 9 integrated readiness evidence audit tests passed');
