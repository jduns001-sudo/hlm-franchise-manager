'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('phase10-demo.html','utf8');
const bundle=fs.readFileSync('hlm-phase10-browser.bundle.js','utf8');
assert.match(html,/hlm-phase10-browser\.bundle\.js/);
assert.match(html,/Advance One Day/);
const sandbox={};sandbox.window=sandbox;
vm.runInNewContext(bundle,sandbox,{timeout:3000});
const api=sandbox.HLMPhase10;
for(const name of ['createBrowserFranchiseSaveStore','calculateStandings','addCalendarDays','createGameStateEnvelope'])assert.equal(typeof api[name],'function',name);
const state=api.createGameStateEnvelope({meta:{saveId:'demo',currentDate:'2026-10-12',controlledTeamId:1},teams:[{id:1,name:'A'},{id:2,name:'B'}],games:[{id:'g',date:'2026-10-13',status:'scheduled',homeTeamId:1,awayTeamId:2}]});
const saved=new Map();
const store=api.createBrowserFranchiseSaveStore({getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v)});
store.save(state);
const result=store.advanceAndSave(3);
assert.equal(result.results.length,1);
assert.equal(store.load().meta.currentDate,'2026-10-13');
console.log('Phase 10 browser prototype smoke tests passed');
