'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {assessGMReviewRiskBriefReadiness}=require('./hlm-phase11-gm-review-risk-brief-readiness');
const {checkGMReviewDecisionBriefChange}=require('./hlm-phase11-gm-review-decision-brief-change-check');
const {exportGMReviewDecisionAudit:exportAudit}=require('./hlm-phase11-gm-review-decision-audit-export');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const riskDigest=assessGMReviewRiskBriefReadiness(items,digest,true,1000,[1100,1200],500).currentSha256;
const initial=checkGMReviewDecisionBriefChange(items,digest,true,1000,[1100,1200],500,riskDigest);
const report=exportAudit(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256,1300);
assert.equal(report.status,'unchanged');assert.equal(report.record.schemaVersion,1);
assert.deepEqual(JSON.parse(report.text),report.record);assert.equal(report.record.checkedAtMs,1300);
assert.equal(report.record.requiresGMApproval,true);assert.equal(report.record.gameplayActionAuthorized,false);
const changed=exportAudit(items,digest,true,1000,[1100,1501],500,riskDigest,initial.currentSha256,1600);
assert.equal(changed.status,'changed');assert.equal(changed.record.requiresFreshGMReview,true);
assert.equal(exportAudit(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256,-1).status,'invalid-audit-time');
assert.equal(exportAudit(items,digest,true,1000,[1100,1200],500,riskDigest,'bad',1300).status,'unverified');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(report[key],false);
assert.ok(Object.isFrozen(report));assert.ok(Object.isFrozen(report.record));
assert.deepEqual(exportAudit(items,digest,true,1000,[1100,1200],500,riskDigest,initial.currentSha256,1300),report);
console.log('GM review decision audit export deterministic tests passed');
