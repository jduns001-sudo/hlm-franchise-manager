'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {createCPUSeasonTransitionCandidate}=require('./hlm-phase9-cpu-season-transition-candidate');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT',currentDate:'2030-06-30'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]});
state.history.seasons.push({id:'2029-30',status:'completed',champion:'PIT'});
const original=serializeGameState(state);
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'season-t1'};
const run=(changes={})=>createCPUSeasonTransitionCandidate(state,{fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01',steps:[{teamId:'BUF',trade}],...changes});
const result=run();
assert.equal(result.candidateOnly,true);
assert.equal(result.persistencePerformed,false);
assert.equal(result.candidateState.history.seasons.length,2);
assert.equal(result.candidateState.history.seasons[0].champion,'PIT');
assert.equal(result.candidateState.history.seasons[1].previousSeasonId,'2029-30');
assert.equal(result.candidateState.meta.currentDate,'2030-07-01');
assert.equal(result.candidateState.meta.controlledTeamId,'PIT');
assert.equal(result.candidateState.universe.players[0].teamId,'NYR');
assert.equal(result.candidateState.activity.transactions[0].id,'season-t1');
assert.equal(serializeGameState(state),original);
assert.throws(()=>run({nextDate:'2030-06-29'}),e=>e.code==='CPU_SEASON_TRANSITION_DATE_ORDER');
assert.throws(()=>run({nextDate:'2030-02-30'}),e=>e.code==='CPU_SEASON_TRANSITION_INVALID_DATE');
assert.throws(()=>run({toSeasonId:'2029-30'}),e=>e.code==='CPU_SEASON_TRANSITION_SAME_SEASON');
assert.throws(()=>run({fromSeasonId:'2028-29'}),e=>e.code==='CPU_SEASON_TRANSITION_SOURCE_SEASON');
assert.throws(()=>run({steps:[{teamId:'PIT',trade}]}),e=>e.code==='CPU_TRADE_HUMAN_TEAM_PROTECTED');
const incomplete=JSON.parse(JSON.stringify(state));incomplete.history.seasons[0].status='active';
assert.throws(()=>createCPUSeasonTransitionCandidate(incomplete,{fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01'}),e=>e.code==='CPU_SEASON_TRANSITION_NOT_COMPLETED');
const overlapping=JSON.parse(JSON.stringify(state));
overlapping.history.seasons.push({id:'2028-29',status:'active'});
const overlapFingerprint=serializeGameState(overlapping);
assert.throws(()=>createCPUSeasonTransitionCandidate(overlapping,{fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01'}),e=>e.code==='CPU_SEASON_TRANSITION_ACTIVE_SEASON');
assert.equal(serializeGameState(overlapping),overlapFingerprint);
console.log('Phase 9 CPU season transition candidate tests passed');
