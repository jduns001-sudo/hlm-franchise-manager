'use strict';
const assert=require('node:assert/strict');
const {IMPORT_KEY}=require('./hlm-phase11-franchise-selection');
const {BACKUP_KEY,ACTIVE_KEY,preflight,activate,rollback}=require('./hlm-phase11-activation-bridge');
const values=new Map([['front-office-save','KEEP'],['hlm-phase10-demo-v1','KEEP10']]),writes=[];
const storage={getItem:k=>values.has(k)?values.get(k):null,setItem:(k,v)=>{writes.push(k);values.set(k,v)}};
assert.throws(()=>preflight(storage),/missing/);
assert.throws(()=>activate(storage,{authorize:true}),/missing/);
values.set(IMPORT_KEY,JSON.stringify({universe:{teams:[{}],players:[{}]}}));
assert.equal(preflight(storage).ready,true);
assert.throws(()=>activate(storage),/authorization/);
assert.equal(values.has(BACKUP_KEY),false);
assert.equal(activate(storage,{authorize:true}).active,'imported');
assert.equal(values.get(ACTIVE_KEY),'imported');
assert.throws(()=>activate(storage,{authorize:true}),/Backup already exists/);
assert.throws(()=>rollback(storage),/authorization/);
assert.equal(rollback(storage,{authorize:true}).active,'existing');
assert.equal(values.get('front-office-save'),'KEEP');
assert.equal(values.get('hlm-phase10-demo-v1'),'KEEP10');
assert(writes.every(k=>[BACKUP_KEY,ACTIVE_KEY].includes(k)));
const failure=new Map([[IMPORT_KEY,values.get(IMPORT_KEY)]]);
const failing={getItem:k=>failure.get(k)??null,setItem:(k,v)=>{if(k===ACTIVE_KEY)throw Error('Storage full');failure.set(k,v)}};
assert.throws(()=>activate(failing,{authorize:true}),/Storage full/);
assert.equal(failure.get(ACTIVE_KEY),undefined);
console.log('Phase 11 activation preflight, authorization, backup and rollback contract passed');
