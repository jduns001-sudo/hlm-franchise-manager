'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {buildGMReviewExpiryStatusReport:report}=require('./hlm-phase11-gm-review-expiry-status-report');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const current=report(items,digest,true,1000,1100,500);
assert.equal(current.status,'current');assert.match(current.lines[0],/human GM approval still required/);assert.match(current.lines[1],/400 ms/);
assert.equal(report(items,digest,true,1000,1500,500).status,'current');
assert.equal(report(items,digest,true,1000,1501,500).status,'expired');
assert.equal(report(items,digest,true,1001,1000,500).status,'future-acknowledgement');
assert.equal(report(items,digest,true,-1,1000,500).status,'invalid-clock');
assert.equal(report(items,digest,false,1000,1000,500).status,'blocked');
assert.equal(report(items,'0'.repeat(64),true,1000,1000,500).status,'blocked');
assert.equal(report([{before:'{',after:items[0].after}],digest,true,1000,1000,500).status,'blocked');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.equal(current.requiresGMApproval,true);assert.ok(Object.isFrozen(current));assert.ok(Object.isFrozen(current.lines));
assert.deepEqual(report(items,digest,true,1000,1100,500),current);
console.log('GM review expiry status report deterministic tests passed');
