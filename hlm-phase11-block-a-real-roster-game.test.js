'use strict';
const assert=require('node:assert/strict');
const universe=require('./hlm-universe.json');
const {build,teams}=require('./hlm-phase11-new-franchise');
const gameState=require('./hlm-game-state');
const schedule=require('./hlm-phase10-season-schedule');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {startSeasonPlayoffs}=require('./hlm-phase10-season-playoffs');
const {simulateNextPlayoffGame}=require('./hlm-phase10-playoff-simulation');
const {finalizeChampionshipSeason}=require('./hlm-phase10-season-finalization');
const {completeOffseasonAndStartSeason}=require('./hlm-phase10-complete-offseason');
const {calculateStandings}=require('./hlm-phase10-standings');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {create}=require('./hlm-phase11-isolated-single-game');
const engine={...gameState,...schedule,applyScheduledGame,simulateNextDay,calculateStandings,createBrowserFranchiseSaveStore,startSeasonPlayoffs,simulateNextPlayoffGame,finalizeChampionshipSeason,completeOffseasonAndStartSeason};
const owner=teams(universe).find(t=>t.abbr==='PIT');assert.ok(owner);
const state=build(universe,owner.id,engine);
const memory=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const gm=create(engine,storage);gm.stage(state,true);
const goalie=state.universe.players.find(p=>String(p.teamId)===String(owner.id)&&String(p.position).toUpperCase()==='G'&&Number(p.overall)>0);
assert.ok(goalie,'source-backed real goalie required');
const before=storage.getItem(gm.key);
assert.throws(()=>gm.approveGoalieChoice(goalie.id,false),/approval/);
assert.equal(storage.getItem(gm.key),before);
gm.approveGoalieChoice(goalie.id,true);
assert.throws(()=>gm.approveExperimentalRosterAware(true,false),/approval/);
assert.equal(gm.approveExperimentalRosterAware(true,true),true);
const reloaded=create(engine,storage);
const game=reloaded.load().activity.games.find(g=>g.status==='scheduled'&&(String(g.homeTeamId)===String(owner.id)||String(g.awayTeamId)===String(owner.id)));
assert.ok(game,'real controlled-team game required');
const ready=reloaded.load();assert.equal(ready.extensions.phase11ExperimentalRosterAwareScores,true);
const prior=storage.getItem(reloaded.key);
assert.throws(()=>reloaded.advance(game.id,1370,false),/approval/);
assert.equal(storage.getItem(reloaded.key),prior,'declined simulation never saves');
const stale=create(engine,storage);
const result=reloaded.advance(game.id,1370,true);
assert.throws(()=>stale.advance(game.id,1370,true),/changed|reload/,'stale second tab must not overwrite the accepted result');
assert.equal(result.result.experimentalRosterAware,true);
assert.equal(result.result.official,false);
assert.equal(result.state.activity.games.find(g=>String(g.id)===String(game.id)).status,'final');
const standings=calculateStandings(result.state.universe.teams,result.state.activity.games);
const home=standings.find(s=>String(s.teamId)===String(game.homeTeamId));
const away=standings.find(s=>String(s.teamId)===String(game.awayTeamId));
assert.equal(home.gp,1,'home team gets one played game');
assert.equal(away.gp,1,'away team gets one played game');
assert.equal(home.gf, result.state.activity.games.find(g=>String(g.id)===String(game.id)).homeGoals);
assert.equal(away.gf, result.state.activity.games.find(g=>String(g.id)===String(game.id)).awayGoals);
const restored=create(engine,storage).load();
assert.equal(restored.extensions.phase11ExperimentalRosterAwareScores,true);
assert.equal(restored.activity.games.find(g=>String(g.id)===String(game.id)).status,'final');
assert.equal(restored.extensions.phase11GmGoaliePlan.playerId,goalie.id);
assert.equal(memory.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
console.log('Block A: real-universe GM-approved experimental game, nonofficial provenance, goalie source identity, reload, decline no-save, production isolation');
