'use strict';
const assert = require('node:assert/strict');
const { createGameStateEnvelope } = require('./hlm-game-state');
const { createExperimentalValidationGates: gates } = require('./hlm-phase10-experimental-validation-gates');
const positions=['C','LW','RW','D','D','G'];
const players=[...positions.map((position,i)=>({id:10+i,teamId:1,position,ovr:80})),...positions.map((position,i)=>({id:20+i,teamId:2,position,ovr:70}))];
const contracts=players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const state=createGameStateEnvelope({teams:[{id:1,name:'Wolves'},{id:2,name:'Bears'}],players,contracts,injuries});
const before=JSON.stringify(state);
const result=gates(state,1,2);
assert.equal(result.researchGatePassed,true);
assert.equal(result.reportValid,true);
assert.equal(result.evidenceComplete,true);
assert.deepEqual(result.blockers,[]);
assert.deepEqual(gates(state,1,2),result);
for(const flag of ['eligibilityCertified','simulationAuthorized','scoreCalculated','gameResultCreated','standingsUpdated','sourceStateMutated','persistencePerformed']) assert.equal(result[flag],false);
assert.equal(JSON.stringify(state),before);
const missing=createGameStateEnvelope({teams:state.universe.teams,players,contracts:contracts.filter(c=>c.playerId!==20),injuries});
const blocked=gates(missing,1,2);
assert.equal(blocked.researchGatePassed,false);
assert.equal(blocked.reportValid,false);
assert(blocked.blockers.includes('INCOMPLETE_RESEARCH_EVIDENCE'));
console.log('Mission 747 experimental validation gates tests passed.');
