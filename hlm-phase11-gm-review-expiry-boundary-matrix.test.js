'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {evaluateGMReviewExpiryBoundaries:check,MAX_AGE_MS}=require('./hlm-phase11-gm-review-expiry-boundary-matrix');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const start=1000,ttl=500;
const current=check(items,digest,true,start,start,ttl);
assert.equal(current.status,'current');assert.equal(current.elapsedMs,0);assert.equal(current.remainingMs,ttl);
const boundary=check(items,digest,true,start,start+ttl,ttl);
assert.equal(boundary.status,'current');assert.equal(boundary.atExpiryBoundary,true);assert.equal(boundary.remainingMs,0);
const expired=check(items,digest,true,start,start+ttl+1,ttl);
assert.equal(expired.status,'expired');assert.equal(expired.remainingMs,null);assert.equal(expired.requiresFreshAcknowledgement,true);
assert.equal(check(items,digest,true,start+1,start,ttl).status,'future-acknowledgement');
assert.equal(check(items,digest,true,-1,start,ttl).status,'invalid-clock');
assert.equal(check(items,digest,true,start,start,MAX_AGE_MS+1).status,'invalid-clock');
assert.equal(check(items,digest,false,start,start,ttl).status,'blocked');
assert.equal(check(items,'0'.repeat(64),true,start,start,ttl).status,'blocked');
assert.equal(check([{before:'{',after:items[0].after}],digest,true,start,start,ttl).status,'blocked');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.equal(current.requiresGMApproval,true);assert.ok(Object.isFrozen(current));
assert.deepEqual(check(items,digest,true,start,start,ttl),current);
console.log('GM review expiry boundary matrix deterministic tests passed');
