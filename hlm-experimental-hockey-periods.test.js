'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const p=require('./hlm-experimental-hockey-periods');
const positions=['C','LW','RW','D','D','G'];
const players=[...positions.map((position,i)=>({id:10+i,teamId:1,position,ovr:80})),...positions.map((position,i)=>({id:20+i,teamId:2,position,ovr:70}))];
const contracts=players.map(q=>({playerId:q.id,teamId:q.teamId,status:'Active'}));
const injuries=players.map(q=>({playerId:q.id,status:'Recovered'}));
const state=createGameStateEnvelope({teams:[{id:1,name:'Wolves'},{id:2,name:'Bears'}],players,contracts,injuries});
const before=JSON.stringify(state);
const game=p.simulateExperimentalHockeyGame(state,1,2,12345);
assert.equal(game.researchReady,true);
assert.equal(p.validatePeriodScore(game).valid,true);
assert.equal(p.periodBoxScore(game).official,false);
assert.deepEqual(p.simulateExperimentalHockeyGame(state,1,2,12345),game);
const tie={homeTeamId:1,awayTeamId:2,seed:17,researchReady:true,blockers:[],hypotheticalScore:{home:2,away:2},official:false};
const ot=p.resolveExperimentalRegulation(tie,true);
assert.equal(ot.periods.length,4);
assert.equal(ot.periods[3].kind,'playoff-overtime');
assert.equal(ot.resolution.shootout,false);
assert.equal(p.validatePeriodScore(ot).valid,true);
assert.equal(p.periodBoxScore(ot).totals.home+p.periodBoxScore(ot).totals.away,5);
const regular=p.resolveExperimentalRegulation(tie,false);
assert.equal(regular.periods[3].kind,'regular-season-overtime');
assert.equal(regular.resolution.shootout,false);
assert.deepEqual(p.regulationPeriods({home:4,away:2},123),p.regulationPeriods({home:4,away:2},123));
assert.equal(p.splitGoals(5,p.nextRandom(1)).reduce((a,b)=>a+b,0),5);
assert.throws(()=>p.splitGoals(-1,p.nextRandom(1)),RangeError);
const series=p.simulateExperimentalHockeySeries(state,1,2,12345,7);
assert.equal(series.researchReady,true);
assert(series.games.length>=4&&series.games.length<=7);
assert.equal(series.wins[String(series.winnerTeamId)],4);
assert(series.games.every(g=>p.validatePeriodScore(g).valid&&g.resolution.shootout===false));
assert.equal(JSON.stringify(state),before);
const missing=createGameStateEnvelope({teams:state.universe.teams,players,contracts:contracts.filter(c=>c.playerId!==20),injuries});
const blocked=p.simulateExperimentalHockeyGame(missing,1,2,12345,true);
assert.equal(blocked.researchReady,false);
assert.equal(blocked.periods,null);
assert.equal(blocked.resolution,null);
assert.equal(p.simulateExperimentalHockeySeries(missing,1,2,12345,7).winnerTeamId,null);
assert.throws(()=>p.simulateExperimentalHockeyGame(state,1,2,-1),RangeError);
assert.throws(()=>p.simulateExperimentalHockeySeries(state,1,2,123,6),RangeError);
const corrupt={...game,periods:[...game.periods,{period:9,home:5,away:0,kind:'regulation'}]};
assert.equal(p.validatePeriodScore(corrupt).valid,false);
console.log('Batch 781-788 hockey period and overtime tests passed.');
