'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {buildSecureGMReviewPage}=require('./hlm-phase11-gm-review-report-security');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const page=buildSecureGMReviewPage([{before:a.text,after:b.text}]);
assert.match(page.html,/GM review batch: 1 comparison/);
assert.match(page.headers['Content-Security-Policy'],/default-src 'none'/);
assert.match(page.headers['Content-Security-Policy'],/form-action 'none'/);
assert.equal(page.headers['X-Content-Type-Options'],'nosniff');
assert.equal(page.readOnly,true);assert.equal(page.requiresGMApproval,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(page[key],false);
assert.ok(Object.isFrozen(page));assert.ok(Object.isFrozen(page.headers));
assert.match(buildSecureGMReviewPage([{before:'{',after:b.text}]).html,/invalid evidence or batch/);
assert.deepEqual(buildSecureGMReviewPage([{before:a.text,after:b.text}]),page);
console.log('Secure GM report deterministic tests passed');
