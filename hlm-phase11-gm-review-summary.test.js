'use strict';
const assert=require('node:assert/strict');
const {summarizeGMReview}=require('./hlm-phase11-gm-review-summary');
const home=Array.from({length:4},(_,i)=>({shots:10,goals:i+1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const snapshot=JSON.stringify([home,away]);
const result=summarizeGMReview(home,away,[5,10,25],[5]);
assert.equal(result.totalThresholds,3);
assert.equal(result.reviewedThresholds,1);
assert.equal(result.pendingReviews,2);
assert.equal(result.withheldThresholds,1);
assert.equal(result.entries.find(e=>e.minimumShots===25).direction,null);
assert.equal(result.productionActivationEnabled,false);
assert.equal(result.automaticallyApplied,false);
assert.equal(result.requiresGMApproval,true);
assert.deepEqual(result.authorizedActions,[]);
assert.ok(Object.isFrozen(result.entries));
assert.deepEqual(summarizeGMReview(home,away,[5,10,25],[5]),result);
assert.equal(JSON.stringify([home,away]),snapshot);
console.log('GM review summary deterministic tests passed');
