'use strict';
const assert=require('node:assert/strict');
const {createSeasonPreviewWorkbench:create}=require('./hlm-phase11-isolated-season-workbench');
assert.throws(()=>create(),/opt-in/);
const workbench=create({enabled:true});
assert.equal(workbench.inspect(),null);
assert.throws(()=>workbench.save(),/cannot save/);
const positions=['C','LW','RW','D','D','G'];
const players=[1,2].flatMap(teamId=>positions.map((position,i)=>({id:teamId*100+i,teamId,position,ovr:teamId===1?85:75})));
const legacy={teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],players,contracts:players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'})),injuries:players.map(p=>({playerId:p.id,status:'Recovered'}))};
const options={controlledTeamId:1,currentDate:'2026-10-12',games:[{id:'G1',date:'2026-10-13',status:'scheduled',homeTeamId:1,awayTeamId:2},{id:'G2',date:'2026-10-14',status:'scheduled',homeTeamId:2,awayTeamId:1}],days:2,seed:11};
const source=JSON.stringify(legacy);
const summary=workbench.preview(legacy,options);
assert.equal(summary.advancedDays,2);
assert.equal(summary.days.length,2);
assert.equal(summary.persistencePerformed,false);
assert.equal(summary.official,false);
assert.equal(workbench.inspect().nextState.meta.currentDate,'2026-10-14');
summary.days[0].results.length=0;
assert.equal(workbench.inspect().days[0].results.length,1);
assert.equal(JSON.stringify(legacy),source);
assert.throws(()=>workbench.save(),/cannot save/);
workbench.clear();assert.equal(workbench.inspect(),null);
const invalid=workbench.preview(legacy,{...options,games:[{...options.games[0],awayTeamId:999}]});
assert.equal(invalid.advancedDays,0);
assert.equal(workbench.inspect().nextState,null);
console.log('Phase 11 read-only season workbench, preview, copy isolation and blocked saves passed');
