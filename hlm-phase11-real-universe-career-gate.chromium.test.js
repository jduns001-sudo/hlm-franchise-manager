'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),http=require('node:http'),path=require('node:path');
const {chromium}=require('playwright');
const {assessRealUniverseCareer}=require('./hlm-phase11-real-universe-career-gate');
const server=http.createServer((req,res)=>{const name=decodeURIComponent((req.url||'/').split('?')[0].slice(1));if(!/^[\w.-]+$/.test(name))return res.writeHead(404).end();fs.readFile(path.join(__dirname,name),(e,b)=>{if(e)return res.writeHead(404).end();res.setHeader('Content-Type',name.endsWith('.js')?'text/javascript':'text/html');res.end(b)})});
(async()=>{await new Promise(ok=>server.listen(0,'127.0.0.1',ok));const browser=await chromium.launch();try{
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block'});
 const url='http://127.0.0.1:'+server.address().port;
 await page.goto(url+'/hlm-phase11-isolated-single-game.html');
 const teams=[1,2,3,4].map(id=>({id,name:'Club '+id}));
 const players=teams.flatMap(t=>Array.from({length:23},(_,i)=>({id:'p'+t.id+'-'+i,teamId:t.id,name:'Player '+i,position:i%6===0?'G':'C',ovr:75,metadata:{source:'front-office'}})));
 const contracts=players.map((p,i)=>({contractId:'c'+i,playerId:p.id,teamId:p.teamId,status:'active',aav:1000000}));
 const finances={teamSnapshots:Object.fromEntries(teams.map(t=>[t.id,{cash:5000000}]))};
 const legacy={teams,players,contracts,prospects:[{id:'pros1'}],draftPicks:[{pickId:'pick1',currentOwnerId:1,status:'available'}],finances};
 const games=[{id:'g1',date:'2026-10-20',homeTeamId:1,awayTeamId:2,status:'scheduled'}];
 const gate=assessRealUniverseCareer(legacy,{controlledTeamId:1,currentDate:'2026-10-19',games});
 assert.equal(gate.ready,true,JSON.stringify(gate.readiness.issues));
 await page.evaluate(()=>localStorage.setItem('hlm_front_office_v8','PRODUCTION_SENTINEL'));
 await page.locator('#file').setInputFiles({name:'real-franchise.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(gate.candidate))});
 await page.waitForFunction(()=>!document.querySelector('#import').disabled);
 page.once('dialog',d=>d.accept());await page.locator('#import').click();
 await page.waitForFunction(()=>document.querySelector('#career-continuity')?.textContent.includes('"playerCount": 92'));
 await page.reload();
 const snapshot=JSON.parse(await page.locator('#career-continuity').innerText());
 assert.equal(snapshot.playerCount,92);
 assert.equal(snapshot.contractCount,92);
 assert.equal(snapshot.controlledTeamId,1);
 assert.deepEqual(snapshot.finances,finances);
 assert.equal(await page.evaluate(()=>localStorage.getItem('hlm_front_office_v8')),'PRODUCTION_SENTINEL');
 assert.equal(await page.locator('#offseason-review').isDisabled(),true);
 console.log('Real Front Office import adapter to mobile isolated franchise, roster/contract/finance reload and production isolation passed');
}finally{await browser.close();await new Promise(ok=>server.close(ok))}})().catch(e=>{console.error(e);process.exitCode=1});
