'use strict';
const assert=require('node:assert/strict');
const {history,teamHistory,dashboard}=require('./hlm-player-performance-multiseason');
const g=(goals,assists)=>({shots:3,goals,assists});
const a=[{season:2027,games:[g(1,0),g(0,1),g(0,0)]},{season:2028,games:[g(1,1),g(1,0),g(0,1)]},{season:2029,games:[g(0,0),g(0,0),g(1,0)]}];
const before=JSON.stringify(a),h=history(a,{window:2});
assert.deepEqual(h.seasons.map(x=>x.season),[2027,2028,2029]);
assert.equal(h.rolling[1].games,6);
assert.equal(h.rolling[1].pointsPerGame,6/6);
assert.equal(h.rolling[2].games,6);
assert.deepEqual(h,history(a,{window:2}));
assert.equal(JSON.stringify(a),before);
assert.equal(dashboard(a,a).pointsPerGameDelta,0);
assert.equal(dashboard([],a).comparison,'insufficient-sample');
assert.throws(()=>history([a[0],a[0]]),/duplicate/);
assert.throws(()=>history(a,{window:0}),/invalid/);
const t=[{season:2027,players:[{id:'p',games:[{gameId:'g1',shots:4,goals:1,assists:1}]},{id:'q',games:[{gameId:'g1',shots:2,goals:0,assists:1}]}]}];
assert.deepEqual(teamHistory(t).seasons[0].summary.totals,{shots:6,goals:1,assists:2});
console.log('Mission 1148 multi-season historical analytics passed');
