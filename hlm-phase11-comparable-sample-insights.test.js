'use strict';
const assert=require('node:assert/strict');
const {compareSamples}=require('./hlm-phase11-comparable-sample-insights');
const home=[{shots:8,goals:2,expectedGoals:1},{shots:8,goals:2,expectedGoals:1}];
const away=[{shots:5,goals:1,expectedGoals:1},{shots:5,goals:0,expectedGoals:1}];
const a=compareSamples(home,away);
assert.equal(a.comparable,true);assert.equal(a.differential.observedFinishingRate,.15);
assert.equal(a.differential.expectedFinishingRate,-.075);
assert.equal(a.differential.shots,6);
assert.deepEqual(a,compareSamples(home,away));
assert.equal(a.productionActivationEnabled,false);assert.equal(a.automaticallyApplied,false);
assert.equal(a.requiresGMApproval,true);assert.equal(Object.isFrozen(a),true);
const limited=compareSamples(home,[{shots:1,goals:0,expectedGoals:0}]);
assert.equal(limited.comparable,false);assert.equal(limited.differential,null);
assert.deepEqual(limited.reasons,['away-sample-caution']);
const invalid=compareSamples([...home,{shots:2,goals:3,expectedGoals:1}],away);
assert.equal(invalid.comparable,false);assert.equal(invalid.home.invalidPeriods,1);
assert.deepEqual(compareSamples([],[]).reasons,['home-sample-caution','away-sample-caution']);
assert.throws(()=>compareSamples(null,away),TypeError);
console.log('Comparable sample insights deterministic regressions passed');
