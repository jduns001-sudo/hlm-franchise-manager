'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {prepareApprovedCPUTradeBatch}=require('./hlm-phase9-cpu-trade-batch-preview');
const {executeReviewedCPUDecisionTrade}=require('./hlm-phase9-cpu-decision-trade-execution-bridge');
const repo=createMemorySaveRepository();
repo.save('human',createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]}));
const before=serializeGameState(repo.load('human').state);
const prioritization={evaluation:{identification:{problems:[{id:'roster-need',category:'roster',severity:'high'}]},options:[{id:'trade-option',problemId:'roster-need',type:'trades'}]},priorities:[{id:'first',optionId:'trade-option',tier:'high',order:1}]};
const decisionOptions={prioritization,priorityId:'first',authorized:true,execute:true};
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'cpu-e2e-1'};
const steps=[{teamId:'BUF',trade}];
const reviewedPreview=prepareApprovedCPUTradeBatch({repository:repo,sourceSlotId:'human',steps,expectedSourceFingerprint:before});
const run=(overrides={})=>executeReviewedCPUDecisionTrade({repository:repo,sourceSlotId:'human',destinationSlotId:'cpu-approved',teamId:'BUF',steps,reviewedPreview,decisionOptions,confirmExecution:true,...overrides});
assert.throws(()=>run({decisionOptions:{...decisionOptions,authorized:false}}),e=>e.code==='CPU_DECISION_TRADE_PREFLIGHT_FAILED');
assert.throws(()=>run({decisionOptions:{...decisionOptions,execute:false}}),e=>e.code==='CPU_DECISION_TRADE_PREFLIGHT_FAILED');
assert.equal(repo.count(),1);
const result=run();
assert.equal(result.decisionPreflightVerified,true);
assert.equal(result.reviewedTradeExecuted,true);
assert.equal(result.persisted,true);
assert.equal(result.verified,true);
assert.equal(result.autonomousExecutionEnabled,false);
assert.equal(repo.load('cpu-approved').state.universe.players[0].teamId,'NYR');
assert.equal(repo.load('cpu-approved').state.activity.transactions.length,1);
assert.equal(serializeGameState(repo.load('human').state),before);
console.log('Phase 9 CPU decision to persistent trade execution end-to-end tests passed');
