'use strict';
const assert=require('node:assert/strict');
const {assessRealUniverseCareer:assess,previewRealUniverseRollover:roll}=require('./hlm-phase11-real-universe-career-gate');
const teams=[1,2,3,4].map(id=>({id,name:'Club '+id}));
const positions=['C','LW','RW','D','D','G'];
const players=teams.flatMap(t=>Array.from({length:23},(_,i)=>({id:'p'+t.id+'-'+i,teamId:t.id,name:'Player '+t.id+' '+i,position:positions[i%6],ovr:70+i%20,metadata:{source:'roster-v8'}})));
const contracts=players.map((p,i)=>({contractId:'c'+i,playerId:p.id,teamId:p.teamId,status:'active',aav:1000000,years:2}));
const prospects=Array.from({length:8},(_,i)=>({id:'pros'+i,name:'Prospect '+i}));
const draftPicks=Array.from({length:8},(_,i)=>({pickId:'pick'+i,currentOwnerId:i%4+1,status:'available'}));
const finances={teamSnapshots:Object.fromEntries(teams.map(t=>[t.id,{cash:10000000,capLimit:95000000}]))};
const legacy={teams,players,contracts,prospects,draftPicks,finances,leagues:[{id:'premier'}],staff:[{id:'coach1',teamId:1}],injuries:[]};
const games=[[1,2],[3,4]].map(([homeTeamId,awayTeamId],i)=>({id:'g'+i,date:'2026-10-20',homeTeamId,awayTeamId,status:'scheduled'}));
const original=JSON.stringify(legacy);
const assessed=assess(legacy,{controlledTeamId:1,currentDate:'2026-10-19',games});
assert.equal(assessed.ready,true,JSON.stringify(assessed.issues.concat(assessed.readiness.issues)));
assert.equal(assessed.counts.playerCount,92);
assert.equal(assessed.counts.contracts,92);
assert.equal(assessed.counts.draftPicks,8);
assert.equal(assessed.counts.prospects,8);
assert.equal(assessed.readiness.snapshot.financeSnapshotTeams,4);
assert.equal(assessed.candidate.universe.players[0].metadata.source,'roster-v8');
assert.equal(JSON.stringify(legacy),original);
assert.equal(assessed.productionWritePerformed,false);
const {createGameStateEnvelope}=require('./hlm-game-state');
const completed=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2027-06-01'},teams,players,contracts,prospects,draftPicks,finances,leagues:legacy.leagues,staff:legacy.staff,seasons:[{seasonId:'2026-27',championTeamId:1}],extensions:{phase10CurrentSeasonId:'2026-27',phase10Playoffs:{status:'complete',championTeamId:1,rounds:[]}}});
const before=JSON.stringify(completed);
const options={contracts:{expiredContractIds:['c0'],signings:[{contractId:'replacement',playerId:'p1-0',teamId:1,aav:2000000,years:3,season:'2027-28',capLimit:95000000}]},draftSelections:[{pickId:'pick0',prospectId:'pros0',teamId:1}],nextSeason:{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01',cycles:2}};
const result=roll(completed,options);
assert.equal(result.ready,true,JSON.stringify(result.issues));
assert.equal(result.nextState.universe.players.length,92);
assert.equal(result.nextState.universe.players[0].metadata.source,'roster-v8');
assert.equal(result.nextState.history.seasons.length,1);
assert.equal(result.nextState.assets.contracts.find(c=>c.contractId==='c0').status,'expired');
assert.equal(result.nextState.assets.contracts.find(c=>c.contractId==='replacement').status,'active');
assert.equal(result.nextState.assets.draftPicks.find(p=>p.pickId==='pick0').status,'used');
assert.deepEqual(result.nextState.finances,finances);
assert.equal(result.nextState.meta.controlledTeamId,1);
assert.equal(JSON.stringify(completed),before);
assert.throws(()=>roll(completed,{...options,draftSelections:[{pickId:'pick0',prospectId:'pros0',teamId:4}]}),/does not own pick/);
assert.equal(JSON.stringify(completed),before);
assert.equal(assess({...legacy,contracts:[...contracts,contracts[0]]},{controlledTeamId:1,currentDate:'2026-10-19',games}).ready,false);
assert.equal(assess({...legacy,draftPicks:[{...draftPicks[0],currentOwnerId:99}]},{controlledTeamId:1,currentDate:'2026-10-19',games}).ready,false);
assert.throws(()=>assess(legacy,{controlledTeamId:99,currentDate:'2026-10-19',games}),/Controlled team/);
console.log('Real-universe 92-player import, source metadata, finance, draft/contract refs, preview rollover and nonmutation passed');
