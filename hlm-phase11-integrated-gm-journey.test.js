'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {calculateStandings}=require('./hlm-phase10-standings');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {create}=require('./hlm-phase11-isolated-single-game');
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[{id:1},{id:2}],games:[{id:'g1',homeTeamId:1,awayTeamId:2,date:'2026-10-19',status:'scheduled'}],players:[{id:11,teamId:1,position:'G',overall:80},{id:12,teamId:1,position:'C',overall:95},{id:13,teamId:1,position:'LW',overall:95},{id:14,teamId:1,position:'D',overall:95},{id:21,teamId:2,position:'G',overall:80}]});
const data=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};
const engine={applyScheduledGame,calculateStandings,createBrowserFranchiseSaveStore};
const first=create(engine,storage);first.stage(state,true);
assert.deepEqual(first.peek(),first.load());
const second=create(engine,storage);second.load();
first.approveGoalieChoice(11,true);
assert.deepEqual(second.peek().extensions.phase11GmGoaliePlan,{playerId:11,teamId:1});
assert.throws(()=>second.approveSkaterParticipation([12,13,14],true),/changed/,'peek must not accept stale baseline');
assert.throws(()=>second.approveExperimentalRosterAware(true,true),/changed/,'peek must not authorize stale activation');
second.load();second.approveSkaterParticipation([12,13,14],true);
assert.throws(()=>first.approveExperimentalRosterAware(true,true),/changed/);
first.load();assert.throws(()=>first.approveExperimentalRosterAware(true,false),/approval/);
first.approveExperimentalRosterAware(true,true);
assert.throws(()=>second.advance('g1',1375,true),/changed/);
second.load();assert.throws(()=>second.advance('g1',1375,false),/approval/);
const result=second.advance('g1',1375,true);
assert.equal(result.result.experimentalRosterAware,true);assert.equal(result.result.official,false);
assert.equal(result.state.activity.games[0].status,'final');
assert.equal(data.get('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
assert.throws(()=>first.advance('g1',1375,true),/changed/);
console.log('Mission 1375: nonmutating peek, cross-tab stale-write rejection, explicit reload, goalie/skater/activation/game approvals, deterministic result and save isolation pass');
