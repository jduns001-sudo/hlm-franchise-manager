'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),http=require('node:http'),path=require('node:path');
const {chromium}=require('playwright');
const server=http.createServer((req,res)=>{const name=(req.url||'/').split('?')[0].slice(1)||'index.html';if(!/^[\w.-]+$/.test(name))return res.writeHead(404).end();fs.readFile(path.join(__dirname,name),(e,b)=>{if(e)return res.writeHead(404).end();res.setHeader('Content-Type',name.endsWith('.js')?'text/javascript':'text/html');res.end(b)})});
(async()=>{await new Promise(r=>server.listen(0,'127.0.0.1',r));const browser=await chromium.launch();
try{const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});const page=await context.newPage();const base='http://127.0.0.1:'+server.address().port;
await page.goto(base+'/index.html?tools=1');
assert.match(await page.locator('body').innerText(),/Playable Isolated Franchise Season/);
await page.evaluate(()=>localStorage.setItem('hlm_front_office_v8','PRODUCTION_SENTINEL'));
await page.getByRole('link',{name:/Playable Isolated Franchise Season/}).click();
await page.waitForURL(/hlm-phase11-isolated-single-game\.html$/);
assert.match(await page.locator('#season-entry-safety').innerText(),/never imported automatically/);
assert.equal(await page.locator('#import').isDisabled(),true);
assert.equal(await page.evaluate(()=>localStorage.getItem('hlm_front_office_v8')),'PRODUCTION_SENTINEL');
await page.getByRole('link',{name:'Gameplay Bridge'}).click();
await page.waitForURL(/hlm-phase11-gameplay-bridge\.html$/);
assert.match(await page.locator('#playable-season-guidance').innerText(),/No automatic transfer/);
await page.locator('#playable-season-link').click();
await page.waitForURL(/hlm-phase11-isolated-single-game\.html$/);
assert.equal(await page.locator('#import').isDisabled(),true);
assert.equal(await page.evaluate(()=>localStorage.getItem('hlm_front_office_v8')),'PRODUCTION_SENTINEL');
await page.goto(base+'/index.html');
await page.waitForURL(/app\.html$/);
assert.equal(await page.evaluate(()=>localStorage.getItem('hlm_front_office_v8')),'PRODUCTION_SENTINEL');
console.log('Mission 1379 mobile: tools -> playable season -> bridge -> season; default Front Office, explicit import, production isolation passed');
}finally{await browser.close();await new Promise(r=>server.close(r))}})().catch(e=>{console.error(e);process.exitCode=1});
