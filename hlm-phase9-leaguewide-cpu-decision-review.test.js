'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {createLeaguewideCPUDecisionReview}=require('./hlm-phase9-leaguewide-cpu-decision-review');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]});
const before=serializeGameState(state);
const result=createLeaguewideCPUDecisionReview(state);
assert.equal(result.teamCount,2);
assert.deepEqual(result.items.map(x=>x.teamId),['BUF','NYR']);
assert.equal(result.items.every(x=>x.humanReviewRequired&&!x.executionEnabled),true);
assert.equal(result.executionPerformed,false);
assert.equal(result.persistencePerformed,false);
assert.equal(serializeGameState(state),before);
assert.equal(result.sourceFingerprint,before);
assert.ok(Object.isFrozen(result)&&Object.isFrozen(result.items));
assert.throws(()=>createLeaguewideCPUDecisionReview(state,{decisionOptionsByTeam:{PIT:{}}}),e=>e.code==='CPU_LEAGUE_REVIEW_TEAM_OPTIONS_INVALID');
assert.throws(()=>createLeaguewideCPUDecisionReview(state,{decisionOptionsByTeam:{UNKNOWN:{}}}),e=>e.code==='CPU_LEAGUE_REVIEW_TEAM_OPTIONS_INVALID');
const duplicate=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'BUF'}]});
assert.throws(()=>createLeaguewideCPUDecisionReview(duplicate),e=>e.code==='CPU_LEAGUE_REVIEW_DUPLICATE_TEAM');
const missing=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'BUF'}]});
assert.throws(()=>createLeaguewideCPUDecisionReview(missing),e=>e.code==='CPU_LEAGUE_REVIEW_CONTROLLED_TEAM_REQUIRED');
console.log('Phase 9 leaguewide CPU organization decision review tests passed');
