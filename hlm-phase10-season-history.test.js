'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {archiveCompletedSeason}=require('./hlm-phase10-season-history');
const teams=[{id:1,name:'Wolves'},{id:2,name:'Falcons'}];
const games=[{id:'g1',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:3,awayGoals:1,overtime:false}];
const state=createGameStateEnvelope({meta:{saveId:'demo',currentDate:'2027-06-20',controlledTeamId:1},teams,games});
state.extensions.phase10Playoffs={status:'complete',championTeamId:1,rounds:[[{highSeed:{seed:1,teamId:1},lowSeed:{seed:2,teamId:2},status:'complete',winnerTeamId:1,games:[]}]]};
const original=JSON.stringify(state);
const {nextState,record}=archiveCompletedSeason(state,'2026-27');
assert.equal(record.championTeamId,1);
assert.equal(record.regularSeasonGames,1);
assert.equal(record.standings.length,2);
assert.equal(nextState.history.seasons.length,1);
assert.equal(JSON.stringify(state),original);
assert.throws(()=>archiveCompletedSeason(nextState,'2026-27'),/already archived/);
const pending=JSON.parse(original);pending.extensions.phase10Playoffs.status='active';
assert.throws(()=>archiveCompletedSeason(pending,'2026-27'),/not complete/);
assert.throws(()=>archiveCompletedSeason(state,''),/Season ID/);
console.log('Phase 10 season history tests passed');
