'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {project}=require('./hlm-phase11-m1620-cpu-fixture-history');
const teams=[{id:1,name:'GM'},{id:2,name:'CPU North'},{id:3,name:'CPU South'}];
const scheduled={id:'cpu-1',date:'2026-10-19',homeTeamId:2,awayTeamId:3,status:'scheduled'};
const gm={id:'gm-1',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'final',homeGoals:2,awayGoals:1};
const state={meta:{controlledTeamId:1},universe:{teams},activity:{games:[scheduled,gm]}};
const before=JSON.stringify(state),rows=project(state);
assert.equal(rows.length,1);assert.equal(rows[0].status,'scheduled');assert.equal(rows[0].home,'CPU North');assert.equal(rows[0].away,'CPU South');
assert.equal(rows[0].homeGoals,null);assert.equal(JSON.stringify(state),before,'read-only projection');
const final={...scheduled,status:'final',homeGoals:4,awayGoals:3};
const finished={...state,activity:{games:[final,gm]}};
assert.equal(project(finished)[0].homeGoals,4);
assert.equal(project(JSON.parse(JSON.stringify(finished)))[0].awayGoals,3,'reload history');
assert.deepEqual(project({...finished,activity:{games:[final,gm,{id:'cpu-2',date:'2026-10-20',homeTeamId:3,awayTeamId:2,status:'scheduled'}]}}).find(x=>x.id==='cpu-1'),project(finished)[0],'subsequent day cannot rewrite final');
assert.throws(()=>project({...finished,activity:{games:[final,final]}}),/Duplicate/);
assert.throws(()=>project({...finished,activity:{games:[{...final,homeGoals:undefined}]}}),/Invalid authoritative/);
assert.equal(project({...finished,activity:{games:[gm]}}).length,0);
const html=fs.readFileSync('hlm-phase11-isolated-single-game.html','utf8');
assert.match(html,/hlm-phase11-m1620-cpu-fixture-history\.js/);
console.log('Mission 1620 source-backed CPU fixture history Node acceptance PASS');
