'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const lab=require('./hlm-experimental-season-batch');
const positions=['C','LW','RW','D','D','G'];
const players=[...positions.map((position,i)=>({id:10+i,teamId:1,position,ovr:80})),...positions.map((position,i)=>({id:20+i,teamId:2,position,ovr:70}))];
const contracts=players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const state=createGameStateEnvelope({teams:[{id:1,name:'Wolves'},{id:2,name:'Bears'}],players,contracts,injuries});
const original=JSON.stringify(state);
const schedule=lab.createExperimentalSchedule([1,2],2);
assert.equal(schedule.length,2);
assert.deepEqual(schedule.map(g=>g.homeTeamId),[1,2]);
assert.notEqual(lab.deriveGameSeed(123,0),lab.deriveGameSeed(123,1));
const result=lab.runExperimentalSeasonBatch(state,schedule,12345);
assert.equal(result.researchReady,true);
assert.equal(result.games.length,2);
assert.deepEqual(lab.runExperimentalSeasonBatch(state,schedule,12345),result);
assert.equal(JSON.stringify(state),original);
assert.equal(result.standings.reduce((n,row)=>n+row.games,0),4);
assert.equal(result.standings.reduce((n,row)=>n+row.wins,0),2);
assert.equal(result.standings.reduce((n,row)=>n+row.points,0),4);
assert(result.games.every(g=>g.official===false&&g.outcome?.official===false));
for(const key of ['official','gameResultCreated','standingsUpdated','sourceStateMutated','persistencePerformed'])assert.equal(result[key],false);
const tie={gameId:1,homeTeamId:1,awayTeamId:2,seed:2,researchReady:true,hypotheticalScore:{home:2,away:2},blockers:[],official:false};
const ot=lab.applyExperimentalOvertime(tie);
assert.equal(ot.overtime.required,true);
const so=lab.applyExperimentalShootout(ot);
assert.equal(so.shootout.homeWins,true);
assert.equal(lab.createExperimentalGameOutcome(so).outcome.winnerTeamId,1);
const missing=createGameStateEnvelope({teams:state.universe.teams,players,contracts:contracts.filter(c=>c.playerId!==20),injuries});
const blocked=lab.runExperimentalSeasonBatch(missing,schedule,12345);
assert.equal(blocked.researchReady,false);
assert.equal(blocked.standings,null);
assert(blocked.blockers.length>0);
assert(blocked.games.every(g=>g.hypotheticalScore===null&&g.outcome===null));
for(const seed of [-1,2**32,1.5,NaN]) assert.throws(()=>lab.runExperimentalSeasonBatch(state,schedule,seed),RangeError);
for(const invalid of [[],Array.from({length:65},(_,i)=>({id:i+1,homeTeamId:1,awayTeamId:2})),[{id:1,homeTeamId:1,awayTeamId:1}]]) assert.throws(()=>lab.runExperimentalSeasonBatch(state,invalid,123),Error);
assert.throws(()=>lab.createExperimentalSchedule([1,1]),TypeError);
assert.throws(()=>lab.createExperimentalSchedule([1,2],3),RangeError);
console.log('Eight-mission isolated experimental season batch tests passed.');
