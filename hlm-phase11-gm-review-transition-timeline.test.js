'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {buildGMReviewTransitionTimeline:timeline,MAX_CHECKS}=require('./hlm-phase11-gm-review-transition-timeline');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const report=timeline(items,digest,true,1000,[1100,1200,1500,1501],500);
assert.equal(report.status,'review-required');assert.equal(report.transitions.length,3);
assert.equal(report.transitions[0].transition,'remained-current');
assert.equal(report.transitions[1].transition,'remained-current');
assert.equal(report.transitions[2].transition,'became-unavailable');
assert.equal(report.requiresFreshAcknowledgement,true);
assert.equal(timeline(items,digest,true,1000,[1100,1200],500).status,'current');
for(const times of [[],[1],[2,1],[-1,1],[1,NaN],Array.from({length:MAX_CHECKS+1},(_,i)=>i)])assert.equal(timeline(items,digest,true,1000,times,500).status,'unavailable');
assert.equal(timeline(items,'0'.repeat(64),true,1000,[1100,1200],500).status,'review-required');
assert.equal(timeline([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500).status,'review-required');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(report[key],false);
assert.equal(report.requiresGMApproval,true);assert.ok(Object.isFrozen(report));assert.ok(Object.isFrozen(report.transitions));assert.ok(Object.isFrozen(report.transitions[0]));
assert.deepEqual(timeline(items,digest,true,1000,[1100,1200,1500,1501],500),report);
console.log('GM review transition timeline deterministic tests passed');
