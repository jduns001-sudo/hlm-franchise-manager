'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('phase10-roster-lab.html','utf8');
for(const id of ['new','advance','summary','standings','results'])assert(html.includes('id="'+id+'"'));
const sandbox={window:{}};vm.runInNewContext(fs.readFileSync('hlm-phase10-roster-lab.bundle.js','utf8'),sandbox,{timeout:10000});
const api=sandbox.window.HLMRosterLab;
assert.equal(typeof api.createRosterLabFranchise,'function');
const values=new Map();
const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
const store=api.createRosterBrowserStore(storage);
const original=api.createRosterLabFranchise();
assert.equal(original.universe.teams.length,4);
assert.equal(original.activity.games.length,56);
store.save(original);
const advanced=store.advanceAndSave(20261014);
assert.equal(advanced.advanced,true);
assert.equal(advanced.saved,true);
assert.equal(advanced.results.length,2);
assert.equal(store.load().activity.games.filter(g=>g.status==='final').length,2);
assert.equal(api.calculateStandings(store.load().universe.teams,store.load().activity.games).reduce((n,t)=>n+t.gp,0),4);
assert.equal(original.activity.games[0].status,'scheduled');
console.log('Mission 746 browser bundle smoke tests passed.');
