'use strict';
const assert=require('node:assert/strict');
const {summarize,compare,rank}=require('./hlm-player-performance-comparison-insights');
const g=(shots,goals,assists)=>({shots,goals,assists});
const a=[g(3,1,0),g(4,0,1),g(2,0,0),g(5,2,0),g(1,0,1),g(3,1,1),g(2,0,0),g(4,1,0),g(3,1,1),g(2,0,1)];
const original=JSON.stringify(a);
const s=summarize(a);
assert.equal(s.games,10);assert.equal(s.totals.goals,6);assert.equal(s.totals.shots,29);
assert.equal(s.finishingRate,6/29);assert.equal(s.finishingConfidence,'moderate');
assert.equal(s.reliability,'developing');assert.notEqual(s.trendDelta,null);
assert.deepEqual(s,summarize(a));assert.equal(JSON.stringify(a),original);
assert.equal(compare(a,[]).interpretation,'small-sample');
assert.equal(summarize([]).trendDirection,'insufficient-sample');
assert.equal(summarize([]).finishingRate,null);
assert.deepEqual(rank([{id:'b',games:a},{id:'a',games:a}]).map(x=>x.id),['a','b']);
assert.throws(()=>summarize([g(1,2,0)]),/goals exceed shots/);
assert.throws(()=>summarize([g(-1,0,0)]),/invalid box score/);
assert.throws(()=>summarize(a,0),/windowSize/);
console.log('Mission 1147 deterministic performance insight regressions passed');
