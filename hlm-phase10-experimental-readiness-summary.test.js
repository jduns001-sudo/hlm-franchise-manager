'use strict';
const assert = require('node:assert/strict');
const { createGameStateEnvelope } = require('./hlm-game-state');
const { createExperimentalReadinessSummary: summarize } = require('./hlm-phase10-experimental-readiness-summary');
const positions=['C','LW','RW','D','D','G'];
const players=[...positions.map((position,i)=>({id:10+i,teamId:1,position,ovr:80})),...positions.map((position,i)=>({id:20+i,teamId:2,position,ovr:70}))];
const contracts=players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const state=createGameStateEnvelope({teams:[{id:1,name:'Wolves'},{id:2,name:'Bears'}],players,contracts,injuries});
const before=JSON.stringify(state);
const result=summarize(state,1,2);
assert.equal(result.researchEvidenceReady,true);
assert.equal(result.homeExpectedGoals,3.05);
assert.equal(result.awayExpectedGoals,2.15);
assert(result.homeProbabilityTail7Plus>0);
assert(result.awayProbabilityTail7Plus>0);
assert.deepEqual(summarize(state,1,2),result);
for(const flag of ['eligibilityCertified','simulationAuthorized','scoreCalculated','gameResultCreated','sourceStateMutated','persistencePerformed']) assert.equal(result[flag],false);
assert.equal(JSON.stringify(state),before);
const missing=createGameStateEnvelope({teams:state.universe.teams,players,contracts:contracts.filter(c=>c.playerId!==20),injuries});
const blocked=summarize(missing,1,2);
assert.equal(blocked.researchEvidenceReady,false);
assert.equal(blocked.homeExpectedGoals,null);
assert.equal(blocked.awayProbabilityTail7Plus,null);
console.log('Mission 744 experimental readiness summary tests passed.');
