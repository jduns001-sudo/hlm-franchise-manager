'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {commitApprovedCPUTradeSequence}=require('./hlm-phase9-cpu-trade-source-slot-commit');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}]});
const repo=createMemorySaveRepository();repo.save('franchise',state);
const expectedSourceFingerprint=serializeGameState(repo.load('franchise').state);
const trade=(from,to,id)=>({teamIds:[from,to],legs:[{fromTeamId:from,toTeamId:to,assets:[{type:'player',id:'p1',ownerTeamId:from}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:id});
const steps=[{teamId:'BUF',trade:trade('BUF','NYR','t1')},{teamId:'NYR',trade:trade('NYR','BOS','t2')}];
const run=(overrides={})=>commitApprovedCPUTradeSequence({repository:repo,sourceSlotId:'franchise',destinationSlotId:'approved',steps,expectedSourceFingerprint,confirmCommit:true,...overrides});
assert.throws(()=>run({confirmCommit:false}),e=>e.code==='CPU_COMMIT_CONFIRMATION_REQUIRED');
assert.throws(()=>run({expectedSourceFingerprint:'stale'}),e=>e.code==='CPU_COMMIT_SOURCE_STALE');
assert.throws(()=>run({destinationSlotId:'franchise'}),e=>e.code==='CPU_COMMIT_SOURCE_PROTECTED');
assert.equal(repo.has('approved'),false);
const result=run();
assert.equal(result.verified,true);
assert.equal(result.activeFranchiseSlotReplaced,false);
assert.equal(result.productionCPUExecutionEnabled,false);
assert.equal(repo.load('approved').state.universe.players[0].teamId,'BOS');
assert.deepEqual(repo.load('approved').state.activity.transactions.map(t=>t.id),['t1','t2']);
assert.equal(serializeGameState(repo.load('franchise').state),expectedSourceFingerprint);
assert.throws(()=>run(),e=>e.code==='CPU_COMMIT_DESTINATION_OCCUPIED');
assert.throws(()=>run({steps:[{teamId:'PIT',trade:trade('PIT','NYR','bad')}],destinationSlotId:'invalid'}),e=>e.code==='CPU_TRADE_HUMAN_TEAM_PROTECTED');
assert.equal(repo.has('invalid'),false);
console.log('Phase 9 confirmed source-slot CPU trade commit tests passed');
