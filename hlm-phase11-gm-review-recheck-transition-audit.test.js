'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {auditGMReviewRecheckTransition:audit}=require('./hlm-phase11-gm-review-recheck-transition-audit');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const same=audit(items,digest,true,1000,1100,1200,500);
assert.equal(same.transition,'remained-current');assert.equal(same.status,'current');
const expired=audit(items,digest,true,1000,1200,1501,500);
assert.equal(expired.transition,'became-unavailable');assert.equal(expired.status,'expired');
assert.equal(audit(items,digest,true,1000,1501,1502,500).transition,'not-current');
assert.equal(audit(items,digest,true,1000,1200,1199,500).transition,'invalid-order');
assert.equal(audit(items,'0'.repeat(64),true,1000,1100,1200,500).transition,'not-current');
assert.equal(audit([{before:'{',after:items[0].after}],digest,true,1000,1100,1200,500).transition,'not-current');
assert.equal(audit(items,digest,false,1000,1100,1200,500).transition,'not-current');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(same[key],false);
assert.equal(same.requiresGMApproval,true);assert.ok(Object.isFrozen(same));
assert.deepEqual(audit(items,digest,true,1000,1100,1200,500),same);
console.log('GM review recheck transition audit deterministic tests passed');
