'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {selectDraftProspect}=require('./hlm-phase10-draft-selection');
const html=fs.readFileSync('hlm-phase11-isolated-single-game.html','utf8');
assert.match(html,/Draft rights: /);
assert.match(html,/rights only \(not signed to roster\)/);
assert.match(html,/p\.draftedByTeamId/);
const state=createGameStateEnvelope({meta:{controlledTeamId:5},teams:[{id:5,name:'Pittsburgh'},{id:3,name:'New York'}],games:[]});
state.universe.prospects.push({id:'prospect-1395',name:'Draft Prospect'});
state.assets.draftPicks.push({pickId:'pick-1395',currentOwnerId:5,status:'available'});
const original=JSON.stringify(state);
const result=selectDraftProspect(state,{pickId:'pick-1395',prospectId:'prospect-1395',teamId:5});
assert.equal(JSON.stringify(state),original,'draft must not mutate source');
assert.equal(result.nextState.universe.prospects[0].draftedByTeamId,5);
assert.equal(result.nextState.universe.prospects[0].draftPickId,'pick-1395');
assert.equal(result.nextState.universe.players.some(p=>String(p.id)==='prospect-1395'),false,'draft rights do not automatically create signed roster players');
assert.throws(()=>selectDraftProspect(result.nextState,{pickId:'pick-1395',prospectId:'prospect-1395',teamId:5}),/already used/);
console.log('Mission 1395 draft rights ownership and unsigned roster separation passed');
