'use strict';
const assert=require('node:assert/strict');
const {allocateLineupIceTime}=require('./hlm-phase11-lineup-ice-time');
const lineup=[{id:'A',weight:3},{id:'B',weight:2},{id:'C',weight:1},{id:'D',weight:1},{id:'E',weight:1}];
const before=JSON.stringify(lineup),report=allocateLineupIceTime(lineup);
assert.equal(report.totalSkaterSeconds,6000);
assert.deepEqual(report.players.map(x=>x.iceTimeSeconds),[2250,1500,750,750,750]);
assert.equal(report.players.reduce((sum,x)=>sum+x.iceTimeSeconds,0),report.totalSkaterSeconds);
assert.equal(JSON.stringify(lineup),before);
assert.deepEqual(allocateLineupIceTime(JSON.parse(before)),report);
assert.equal(report.productionActivationEnabled,false);
assert.equal(report.automaticallyApplied,false);
assert.equal(report.requiresGMApproval,true);
assert.throws(()=>allocateLineupIceTime([{id:'A',weight:1},{id:'A',weight:2},{id:'C',weight:1},{id:'D',weight:1},{id:'E',weight:1}]),TypeError);
assert.throws(()=>allocateLineupIceTime([{id:'A',weight:0},...lineup.slice(1)]),TypeError);
assert.throws(()=>allocateLineupIceTime(lineup.slice(0,4)),TypeError);
assert.throws(()=>allocateLineupIceTime(lineup,0),TypeError);
console.log('Lineup ice-time allocation, determinism and save isolation passed');
