'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const players=[{id:11,teamId:1,position:'G',overall:90},{id:12,teamId:1,position:'C',overall:95},{id:13,teamId:1,position:'LW',overall:95},{id:14,teamId:1,position:'D',overall:95},{id:21,teamId:2,position:'G',overall:80}];
const base=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams:[{id:1},{id:2}],players,games:[{id:'g1',date:'2026-10-19',homeTeamId:1,awayTeamId:2,status:'scheduled'},{id:'g2',date:'2026-10-19',homeTeamId:2,awayTeamId:1,status:'scheduled'}]});
base.extensions={...base.extensions,phase11GmGoaliePlan:{teamId:1,playerId:11},phase11GmApprovedSkaters:{teamId:1,playerIds:[12,13,14]},phase11ExperimentalRosterAwareScores:true};
const opts={experimentalRosterAware:true};
const first=applyScheduledGame(base,'g1',1376,opts);
const persisted=JSON.parse(JSON.stringify(first.nextState));
assert.equal(persisted.activity.games[0].experimentalRosterAware,true);
assert.equal(persisted.activity.games[0].official,false);
assert.equal(persisted.activity.games[1].status,'scheduled');
const day=simulateNextDay(persisted,1376,opts);
assert.equal(day.results.length,1);
assert.equal(day.nextState.activity.games[1].experimentalRosterAware,true);
assert.equal(day.nextState.activity.games[1].official,false);
assert.equal(day.nextState.activity.games.filter(g=>g.status==='final').length,2);
assert.equal(calculateStandings(day.nextState.universe.teams,day.nextState.activity.games).length,2);
const legacy=applyScheduledGame(base,'g1',1376);
assert.equal(legacy.nextState.activity.games[0].experimentalRosterAware,undefined);
assert.equal(legacy.nextState.activity.games[0].official,undefined);
const html=fs.readFileSync(path.join(__dirname,'hlm-phase11-isolated-single-game.html'),'utf8');
assert.match(html,/EXPERIMENTAL, NONOFFICIAL/);
assert.match(html,/Legacy result/);
console.log('Mission 1376: persisted experimental provenance, regular-season day batch, standings, and default-off legacy pass');
