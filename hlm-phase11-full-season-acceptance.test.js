'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {applyScheduledGame}=require('./hlm-phase10-apply-game');
const {simulateNextDay}=require('./hlm-phase10-simulate-day');
const {calculateStandings}=require('./hlm-phase10-standings');
const {create}=require('./hlm-phase11-isolated-single-game');
const {overview}=require('./hlm-phase11-isolated-season-dashboard');
const memory=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const engine={createBrowserFranchiseSaveStore,applyScheduledGame,simulateNextDay,calculateStandings};
const teams=[{id:1,name:'Owner'},{id:2,name:'CPU A'},{id:3,name:'CPU B'},{id:4,name:'CPU C'}];
const pairs=[[1,2],[3,4],[1,3],[2,4],[1,4],[2,3],[2,1],[4,3],[3,1],[4,2],[4,1],[3,2]];
const games=pairs.map(([homeTeamId,awayTeamId],i)=>({id:'season-'+String(i+1).padStart(2,'0'),date:'2026-10-'+String(19+i).padStart(2,'0'),homeTeamId,awayTeamId,status:'scheduled'})).reverse();
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-18'},teams,games});
const manager=create(engine,storage);
assert.throws(()=>manager.stage(state,false),/approval/);
manager.stage(state,true);
assert.throws(()=>manager.stage(state,true),/overwritten/);
const stale=create(engine,storage);
const results=[];
for(let day=0;day<12;day++){
 const review=manager.reviewNextDay();
 assert.equal(review.games,1);
 assert.throws(()=>manager.advanceNextDay(1341,false),/approval/);
 const before=manager.load();
 assert.equal(before.activity.games.filter(g=>g.status==='final').length,day);
 const advanced=manager.advanceNextDay(1341,true);
 results.push(...advanced.results);
 assert.equal(advanced.state.activity.games.filter(g=>g.status==='final').length,day+1);
 assert.equal(advanced.state.activity.games.filter(g=>g.status==='scheduled').length,11-day);
 assert.equal(advanced.standings.reduce((sum,t)=>sum+t.gp,0),2*(day+1));
 assert.equal(overview(advanced.state,engine).completedCount,day+1);
 assert.equal(storage.getItem('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
 assert.equal(create(engine,storage).load().activity.games.filter(g=>g.status==='final').length,day+1);
}
assert.throws(()=>stale.advanceNextDay(1341,true),/changed/);
assert.equal(new Set(results.map(g=>String(g.gameId))).size,12);
const final=create(engine,storage).load();
assert.equal(final.activity.games.filter(g=>g.status==='final').length,12);
assert.equal(final.activity.games.filter(g=>g.status==='scheduled').length,0);
assert.equal(overview(final,engine).scheduledCount,0);
assert.equal(calculateStandings(final.universe.teams,final.activity.games).reduce((sum,t)=>sum+t.gp,0),24);
assert.throws(()=>manager.advanceNextDay(1341,true),/No scheduled games remain/);
assert.equal(storage.getItem('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
console.log('Twelve-game four-team season: human approval, chronological simulation, unique finals, standings, reload, stale-write rejection and production isolation passed');
