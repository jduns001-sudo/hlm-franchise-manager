'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {buildGMReviewBatchReport}=require('./hlm-phase11-gm-review-batch-report');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const items=[{before:a.text,after:b.text},{before:a.text,after:a.text}];
const report=buildGMReviewBatchReport(items);
assert.equal(report.valid,true);assert.equal(report.lines[0],'GM review batch: 2 comparisons.');
assert.equal(report.lines[1],'1 requires human GM review.');
assert.equal(report.lines[3],'3 total review-state changes.');
assert.match(report.lines[4],/human GM review required/);
assert.equal(report.lines[5],'Comparison 2: unchanged.');
const invalid=buildGMReviewBatchReport([{before:'{',after:b.text}]);
assert.equal(invalid.valid,false);assert.equal(invalid.canPresentToGM,false);assert.equal(invalid.lines.length,1);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(report[key],false);
assert.equal(report.requiresGMApproval,true);
assert.ok(Object.isFrozen(report));assert.ok(Object.isFrozen(report.lines));
assert.deepEqual(buildGMReviewBatchReport(items),report);
console.log('GM review batch report deterministic tests passed');
