'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserSaveAdapter}=require('./hlm-browser-save-adapter');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {createBrowserCPUTradeWorkflow}=require('./hlm-phase9-cpu-browser-approved-workflow');
const memory=new Map(),storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const repository=createBrowserSaveAdapter(storage);
repository.save('human',createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]}));
const before=serializeGameState(repository.load('human').state);
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'browser-approved-1'};
const steps=[{teamId:'BUF',trade}];
const decisionOptions={prioritization:{evaluation:{identification:{problems:[{id:'need-trade',category:'cap',severity:'high'}]},options:[{id:'trade-option',problemId:'need-trade',type:'trades'}]},priorities:[{id:'first',optionId:'trade-option',tier:'high',order:1}]},priorityId:'first',authorized:true,execute:true};
assert.throws(()=>createBrowserCPUTradeWorkflow({storage,sourceSlotId:'human',teamId:'PIT',steps,decisionOptions}),e=>e.code==='CPU_BROWSER_HUMAN_PROTECTED');
const workflow=createBrowserCPUTradeWorkflow({storage,sourceSlotId:'human',teamId:'BUF',steps,decisionOptions});
assert.equal(workflow.preview.stepCount,1);
assert.throws(()=>workflow.execute({destinationSlotId:'reviewed'}),e=>e.code==='CPU_BROWSER_EXECUTION_APPROVAL_REQUIRED');
assert.equal(repository.list().length,1);
const result=workflow.execute({destinationSlotId:'reviewed',confirmExecution:true});
assert.equal(result.verified,true);
assert.equal(repository.load('reviewed').state.universe.players[0].teamId,'NYR');
assert.equal(serializeGameState(repository.load('human').state),before);
assert.throws(()=>workflow.execute({destinationSlotId:'reviewed',confirmExecution:true}),e=>e.code==='CPU_COMMIT_DESTINATION_OCCUPIED');
console.log('Phase 9 browser CPU approved decision-to-trade workflow tests passed');
