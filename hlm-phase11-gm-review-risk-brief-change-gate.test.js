'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {checkGMReviewRiskBriefChange:check}=require('./hlm-phase11-gm-review-risk-brief-change-gate');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const first=check(items,digest,true,1000,[1100,1200],500);
assert.equal(first.status,'unverified');assert.equal(first.requiresFreshGMReview,true);
const same=check(items,digest,true,1000,[1100,1200],500,first.currentSha256);
assert.equal(same.status,'unchanged');assert.equal(same.reviewRequired,false);assert.equal(same.requiresFreshGMReview,false);
assert.equal(check(items,digest,true,1000,[1100,1501],500,first.currentSha256).status,'changed');
const stale=check(items,digest,true,1000,[1100,1501],500);
assert.equal(check(items,digest,true,1000,[1100,1501],500,stale.currentSha256).requiresFreshGMReview,true);
assert.equal(check(items,digest,true,1000,[1100,1200],500,'0'.repeat(64)).status,'changed');
assert.equal(check(items,digest,true,1000,[1100,1200],500,'invalid').status,'unverified');
assert.equal(check(items,'0'.repeat(64),true,1000,[1100,1200],500).reviewRequired,true);
assert.equal(check([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500).reviewRequired,true);
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(same[key],false);
assert.equal(same.requiresGMApproval,true);assert.ok(Object.isFrozen(same));
assert.deepEqual(check(items,digest,true,1000,[1100,1200],500,first.currentSha256),same);
console.log('GM review risk brief change gate deterministic tests passed');
