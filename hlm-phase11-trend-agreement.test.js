'use strict';
const assert=require('node:assert/strict');
const {evaluateTrendAgreement}=require('./hlm-phase11-trend-agreement');
const home=[{shots:10,goals:2,expectedGoals:2},{shots:10,goals:2,expectedGoals:2},{shots:10,goals:4,expectedGoals:2},{shots:10,goals:4,expectedGoals:2}];
const away=[{shots:10,goals:1,expectedGoals:2},{shots:10,goals:1,expectedGoals:2},{shots:10,goals:1,expectedGoals:2},{shots:10,goals:1,expectedGoals:2}];
const supported=evaluateTrendAgreement(home,away,[5,10]);
assert.equal(supported.agreement,'consistent');assert.equal(supported.direction,'increased');
assert.equal(supported.coveredThresholds,2);assert.equal(supported.totalThresholds,2);
assert.equal(supported.productionActivationEnabled,false);assert.equal(supported.automaticallyApplied,false);
assert.equal(supported.requiresGMApproval,true);assert.equal(Object.isFrozen(supported),true);
assert.deepEqual(supported,evaluateTrendAgreement(home,away,[5,10]));
const partial=evaluateTrendAgreement(home,away,[5,10,25]);
assert.equal(partial.agreement,'partial-coverage');assert.equal(partial.direction,null);
assert.equal(partial.coveredThresholds,2);assert.equal(partial.thresholdSensitivity,'threshold-sensitive');
const unsupported=evaluateTrendAgreement(home,away,[50,100]);
assert.equal(unsupported.agreement,'insufficient-evidence');assert.equal(unsupported.direction,null);
assert.throws(()=>evaluateTrendAgreement(home,away,[0]),RangeError);
assert.throws(()=>evaluateTrendAgreement(null,away),TypeError);
console.log('Trend agreement deterministic regressions passed');
