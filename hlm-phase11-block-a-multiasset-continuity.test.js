'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {join}=require('node:path');
const {teams,build}=require('./hlm-phase11-new-franchise');
const engine={...require('./hlm-game-state'),...require('./hlm-phase10-season-schedule')};
const {createIsolatedTransactionLab}=require('./hlm-phase11-block-a-isolated-transaction-lab');
test('two source-backed picks commit together and preserve multiseason archive',()=>{
 const source=JSON.parse(readFileSync(join(__dirname,'hlm-universe.json'),'utf8'));
 const state=build(source,teams(source)[0].id,engine);
 state.history.seasons.push({season:'lab-prior-season',champion:'test-only'});
 const picks=state.assets.draftPicks.filter(p=>p.status==='AVAILABLE').slice(0,2);
 assert.equal(picks.length,2);
 const transfers=picks.map(p=>({id:p.pickId,from:p.currentOwnerId,to:teams(source).find(t=>String(t.id)!==String(p.currentOwnerId)).id}));
 const lab=createIsolatedTransactionLab(state);
 const request={experimentalEnabled:true,gmApproved:true,expectedRevision:'revision-1',decisionId:'multi-pick-lab',changes:{players:[],contracts:[],picks:transfers,prospects:[]}};
 const before=lab.snapshot();
 assert.equal(lab.simulate({...request,injectFailure:true}).committed,false);
 assert.deepEqual(lab.snapshot(),before);
 const result=lab.simulate(request);
 assert.equal(result.committed,true);
 const after=lab.snapshot();
 for(const t of transfers)assert.equal(String(after.state.assets.draftPicks.find(p=>p.pickId===t.id).currentOwnerId),String(t.to));
 assert.deepEqual(after.state.history.seasons,before.state.history.seasons);
 assert.equal(after.state.activity.transactions.length,before.state.activity.transactions.length+1);
 assert.equal(after.consumedDecisionIds.length,1);
 assert.equal(lab.simulate({...request,expectedRevision:after.revision}).committed,false);
 assert.equal(lab.simulate({...request,decisionId:'different-id'}).committed,false);
});
test('one stale pick rejects all valid companion changes without history or replay consumption',()=>{
 const source=JSON.parse(readFileSync(join(__dirname,'hlm-universe.json'),'utf8'));
 const state=build(source,teams(source)[0].id,engine);
 const pick=state.assets.draftPicks.find(p=>p.status==='AVAILABLE');
 const to=teams(source).find(t=>String(t.id)!==String(pick.currentOwnerId)).id;
 const lab=createIsolatedTransactionLab(state),before=lab.snapshot();
 const result=lab.simulate({experimentalEnabled:true,gmApproved:true,expectedRevision:'revision-1',decisionId:'rollback-all',changes:{players:[],contracts:[],picks:[{id:pick.pickId,from:pick.currentOwnerId,to},{id:'nonexistent',from:pick.currentOwnerId,to}],prospects:[]}});
 assert.equal(result.committed,false);
 assert.deepEqual(lab.snapshot(),before);
});
