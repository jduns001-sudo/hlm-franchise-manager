'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {describeGMReviewBatch}=require('./hlm-phase11-gm-review-batch-details');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const items=[{before:a.text,after:b.text},{before:a.text,after:a.text}];
const x=describeGMReviewBatch(items);
assert.equal(x.valid,true);assert.equal(x.reviewCount,1);assert.equal(x.unchangedCount,1);assert.equal(x.totalChanges,3);
assert.deepEqual(x.details.map(d=>[d.index,d.reason,d.totalChanges]),[[0,'human-review-required',3],[1,'no-change',0]]);
assert.equal(describeGMReviewBatch([{before:'{',after:b.text}]).valid,false);
assert.equal(describeGMReviewBatch([{before:'{',after:b.text}]).details.length,0);
assert.equal(describeGMReviewBatch([]).valid,false);
assert.equal(describeGMReviewBatch(Array.from({length:51},()=>items[0])).valid,false);
assert.equal(x.productionActivationEnabled,false);assert.equal(x.gameplayActionAuthorized,false);assert.equal(x.saveWriteAllowed,false);
assert.equal(x.requiresGMApproval,true);assert.ok(Object.isFrozen(x));assert.ok(Object.isFrozen(x.details));assert.ok(Object.isFrozen(x.details[0]));
assert.deepEqual(describeGMReviewBatch(items),x);
console.log('GM review batch details deterministic tests passed');
