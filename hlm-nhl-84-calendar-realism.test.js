'use strict';
const assert=require('node:assert/strict');
const {generateNhl84Schedule}=require('./hlm-nhl-84-schedule-generator');
const {validateNhl84Schedule}=require('./hlm-nhl-schedule-validator');
const {scheduleNhl84CalendarRealism,auditNhl84CalendarRealism}=require('./hlm-nhl-84-calendar-realism');
let count=0;
const ok=(v,m)=>{assert.ok(v,m);count++;};
const rejects=(fn,p)=>{assert.throws(fn,p);count++;};
const teams=[];
for(let c=0;c<2;c++)for(let d=0;d<2;d++)for(let i=0;i<8;i++)teams.push({id:`${c}-${d}-${i}`,conferenceId:`C${c}`,divisionId:`C${c}D${d}`});
const games=generateNhl84Schedule(teams),before=JSON.stringify({teams,games});
const opts={startDate:'2026-10-01',endDate:'2027-04-15'};
const result=scheduleNhl84CalendarRealism(teams,games,opts);
ok(teams.length===32,'32 teams');
ok(result.length===1344,'1344 games');
ok(new Set(result.map(g=>g.id)).size===1344,'unique ids');
ok(result.every((g,i)=>g.id===games[i].id&&g.status==='scheduled'),'identity and status preserved');
ok(validateNhl84Schedule(teams,result).valid,'84/team, 42 home/away, opponent quotas preserved');
ok(result.every(g=>g.date>=opts.startDate&&g.date<=opts.endDate),'date bounds');
const audit=auditNhl84CalendarRealism(result);
const daily=new Map();
for(const g of result){
  if(!daily.has(g.date))daily.set(g.date,new Set());
  const used=daily.get(g.date);
  ok(!used.has(String(g.homeTeamId))&&!used.has(String(g.awayTeamId)),'no double booking');
  used.add(String(g.homeTeamId));used.add(String(g.awayTeamId));
}
ok(Object.keys(audit.months).join()==='2026-10,2026-11,2026-12,2027-01,2027-02,2027-03,2027-04','October-April coverage');
ok(audit.months['2027-04']>=60,'April coverage substantial');
ok(Object.entries(audit.months).every(([m,n])=>m==='2027-04'||n>=150),'full months evenly filled');
ok(audit.maxBackToBacks<=10&&audit.maxBackToBacks>=1,'back-to-backs controlled and present');
ok(audit.tripleRuns===0,'no three consecutive days');
ok(audit.maxInactiveGap<=7,'maximum inactivity respected');
ok(audit.distinctRestGaps.length>=3,'varied rest');
ok(audit.maxGamesInDay<=12,'daily cap');
const tight=scheduleNhl84CalendarRealism(teams,games,{...opts,maxBackToBacksPerTeam:1});
ok(auditNhl84CalendarRealism(tight).maxBackToBacks<=1,'tighter back-to-back option honored');
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,maxBackToBacksPerTeam:0}),/infeasible/);
ok(JSON.stringify({teams,games})===before,'no input mutation');
ok(JSON.stringify(result)===JSON.stringify(scheduleNhl84CalendarRealism(teams,games,opts)),'deterministic');
ok(JSON.stringify(result)===JSON.stringify(scheduleNhl84CalendarRealism(teams,[...games].reverse(),opts)),'order independent');
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,endDate:'2027-03-30'}),/October through April/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,startDate:'2026-02-30'}),/Invalid calendar date/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,maxGamesPerDay:3}),/maxGamesPerDay/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,maxBackToBacksPerTeam:-1}),/maxBackToBacksPerTeam/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,maxInactiveDays:2}),/maxInactiveDays/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,blockedDates:'x'}),/blockedDates/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games.slice(1),opts),/Invalid NHL84/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,blockedDates:['2026-10-05','2026-10-06','2026-10-07','2026-10-08','2026-10-09','2026-10-10','2026-10-11','2026-10-12','2026-10-13']}),/infeasible/);
rejects(()=>scheduleNhl84CalendarRealism(teams,games,{...opts,blockedDates:Array.from({length:150},(_,i)=>new Date(Date.parse(opts.startDate)+i*86400000).toISOString().slice(0,10))}),/infeasible/);
ok(JSON.stringify({teams,games})===before,'no mutation after failures');
console.log('PASS '+count+' assertions; games='+result.length+'; activeDays='+daily.size+'; b2bMax='+audit.maxBackToBacks+'; maxGap='+audit.maxInactiveGap);
