'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {create}=require('./hlm-phase11-isolated-single-game');
const memory=new Map();
const storage={getItem:k=>memory.has(k)?memory.get(k):null,setItem:(k,v)=>memory.set(k,String(v))};
const engine={applyScheduledGame(){},calculateStandings(){},createBrowserFranchiseSaveStore(s,k){return {load(){const raw=s.getItem(k);return raw?JSON.parse(raw):null},save(v){s.setItem(k,JSON.stringify(v))}}}};
const gm=create(engine,storage);
const players=[{id:'signed',name:'Signed Prospect',teamId:5,position:'C',overall:70},{id:'veteran1',teamId:5,position:'D',overall:75},{id:'veteran2',teamId:5,position:'LW',overall:78},{id:'opponent',teamId:3,position:'C',overall:80}];
const state=createGameStateEnvelope({meta:{controlledTeamId:5},teams:[{id:5},{id:3}],players,contracts:[{contractId:'rookie',playerId:'signed',teamId:5,status:'active',aav:1}],transactions:[{id:'drafted-prospect-signing:rookie',type:'drafted-prospect-signing',playerId:'signed',teamId:5,contractId:'rookie'}],extensions:{phase11ExperimentalRosterAwareScores:false}});
gm.stage(state,true);
const before=storage.getItem(gm.key);
assert.throws(()=>gm.approveSkaterParticipation(['signed','veteran1','veteran2'],false),/approval required/);
assert.equal(storage.getItem(gm.key),before,'unapproved lineup never saves');
assert.throws(()=>gm.approveSkaterParticipation(['signed','veteran1','opponent'],true),/controlled-team roster/);
assert.equal(storage.getItem(gm.key),before,'foreign player blocked');
const approved=gm.approveSkaterParticipation(['signed','veteran1','veteran2'],true);
assert.deepEqual(approved.playerIds,['signed','veteran1','veteran2']);
const after=gm.load();
assert.ok(after.extensions.phase11GmApprovedSkaters.playerIds.includes('signed'));
assert.equal(after.extensions.phase11ExperimentalRosterAwareScores,false);
assert.equal(after.activity.transactions.length,1,'signing history unchanged');
assert.equal(after.assets.contracts.length,1,'contract unchanged');
assert.equal(after.universe.players.length,4,'roster unchanged');
const stale=storage.getItem(gm.key);
storage.setItem(gm.key,JSON.stringify({...after,extensions:{...after.extensions,externalEdit:true}}));
assert.throws(()=>gm.approveSkaterParticipation(['signed','veteran1','veteran2'],true),/changed/);
assert.notEqual(storage.getItem(gm.key),stale);
assert.equal(JSON.parse(storage.getItem(gm.key)).extensions.externalEdit,true,'stale approval cannot overwrite');
assert.equal(storage.getItem('hlm_front_office_v8'),null,'production untouched');
console.log('Mission 1399 existing GM skater approval safely includes signed prospect');
