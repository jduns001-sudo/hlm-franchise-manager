'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {prepareApprovedCPUTradeBatch}=require('./hlm-phase9-cpu-trade-batch-preview');
const {executeApprovedCPUTradeBatch}=require('./hlm-phase9-cpu-approved-trade-persistent-executor');
const repo=createMemorySaveRepository();
repo.save('human',createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]}));
const original=serializeGameState(repo.load('human').state);
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'cpu-approved-1'};
const steps=[{teamId:'BUF',trade}];
const reviewedPreview=prepareApprovedCPUTradeBatch({repository:repo,sourceSlotId:'human',steps,expectedSourceFingerprint:original});
const run=(changes={})=>executeApprovedCPUTradeBatch({repository:repo,sourceSlotId:'human',destinationSlotId:'cpu-approved',steps,reviewedPreview,confirmExecution:true,...changes});
assert.throws(()=>run({confirmExecution:false}),e=>e.code==='CPU_EXECUTOR_APPROVAL_REQUIRED');
assert.throws(()=>run({reviewedPreview:null}),e=>e.code==='CPU_EXECUTOR_REVIEW_REQUIRED');
assert.throws(()=>run({sourceSlotId:'different'}),e=>e.code==='CPU_EXECUTOR_SOURCE_MISMATCH');
assert.equal(repo.count(),1);
const result=run();
assert.equal(result.executed,true);
assert.equal(result.persisted,true);
assert.equal(result.verified,true);
assert.equal(result.autonomousExecutionEnabled,false);
assert.equal(repo.load('cpu-approved').state.universe.players[0].teamId,'NYR');
assert.equal(serializeGameState(repo.load('human').state),original);
assert.throws(()=>run(),e=>e.code==='CPU_COMMIT_DESTINATION_OCCUPIED');
console.log('Phase 9 explicitly approved persistent CPU trade execution tests passed');
