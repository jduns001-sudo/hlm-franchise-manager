'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {checkGMReviewAcknowledgementExpiry:check}=require('./hlm-phase11-gm-review-acknowledgement-expiry');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const now=1000000,age=86400000;
const current=check(items,digest,true,now,now,age);
assert.equal(current.status,'current');assert.equal(current.acknowledgementCurrent,true);
assert.equal(check(items,digest,true,now,now+age,age).status,'current');
assert.equal(check(items,digest,true,now,now+age+1,age).status,'expired');
assert.equal(check(items,digest,true,now+1,now,age).status,'future-acknowledgement');
assert.equal(check(items,digest,true,-1,now,age).status,'invalid-clock');
assert.equal(check(items,digest,true,now,now,0).status,'invalid-clock');
assert.equal(check(items,digest,false,now,now,age).status,'blocked');
assert.equal(check(items,'0'.repeat(64),true,now,now,age).status,'blocked');
assert.equal(check([{before:'{',after:items[0].after}],digest,true,now,now,age).status,'blocked');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.equal(current.requiresGMApproval,true);assert.ok(Object.isFrozen(current));
assert.deepEqual(check(items,digest,true,now,now,age),current);
console.log('GM review acknowledgement expiry deterministic tests passed');
