'use strict';
const assert=require('node:assert/strict');
const {evaluateGMEvidenceActionBoundary}=require('./hlm-phase11-gm-evidence-action-boundary');
const home=Array.from({length:4},(_,i)=>({shots:10,goals:i+1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const before=JSON.stringify([home,away]);
const partial=evaluateGMEvidenceActionBoundary(home,away,[5,10,25],[5]);
assert.equal(partial.gameplayActionAuthorized,false);
assert.equal(partial.productionActivationEnabled,false);
assert.equal(partial.requiresGMApproval,true);
assert.ok(partial.blockers.includes('historical-evidence-incomplete'));
assert.ok(partial.blockers.includes('review-incomplete'));
assert.ok(partial.deniedAutomaticActions.includes('save-write'));
const reviewed=evaluateGMEvidenceActionBoundary(home,away,[5,10,25],[5,10,25]);
assert.equal(reviewed.gmReviewComplete,true);
assert.equal(reviewed.gameplayActionAuthorized,false);
assert.ok(reviewed.blockers.includes('production-activation-disabled'));
assert.deepEqual(evaluateGMEvidenceActionBoundary(home,away,[5,10,25],[5]),partial);
assert.ok(Object.isFrozen(partial.blockers));
assert.equal(JSON.stringify([home,away]),before);
console.log('GM evidence action boundary deterministic tests passed');
