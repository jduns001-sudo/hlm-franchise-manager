'use strict';
const assert=require('node:assert/strict');
const {project}=require('./hlm-phase11-office-summary.js');
const source={meta:{controlledTeamId:1},universe:{teams:[{id:1,name:'Pittsburgh'},{id:2,name:'Edmonton'}]},activity:{games:[{id:'past',date:'2026-10-20',homeTeamId:1,awayTeamId:2,status:'final',homeGoals:3,awayGoals:1},{id:'next',date:'2026-10-21',homeTeamId:2,awayTeamId:1,status:'scheduled'}]},extensions:{}};
const before=JSON.stringify(source);
const manager={peek:()=>source};
const a=project(manager);
assert.equal(a.teamName,'Pittsburgh');
assert.deepEqual(a.record,{wins:1,losses:0,ties:0,finalGames:1});
assert.deepEqual(a.nextGame,{gameId:'next',date:'2026-10-21',opponent:'Edmonton',home:false});
assert.equal(a.readiness.requiresHumanGMReview,true);
assert.equal(a.readiness.goalieApproved,false);
assert.equal(a.readOnly,true);
assert.equal(JSON.stringify(source),before,'projection never mutates authoritative state');
source.extensions.phase11GmGoaliePlan={teamId:1,playerId:99};
source.extensions.phase11GmGameDaySkaterApproval={teamId:1,gameId:'next',playerIds:[7]};
assert.equal(project(manager).readiness.requiresHumanGMReview,false);
assert.equal(project({peek:()=>null}).status,'no-franchise');
assert.throws(()=>project({peek:()=>({})}),/Authoritative/);
assert.throws(()=>project({peek:()=>({...source,activity:{games:[{...source.activity.games[0],homeGoals:null}]}})}),/score missing/);
