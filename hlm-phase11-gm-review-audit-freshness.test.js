'use strict';
const assert=require('node:assert/strict');
const {assessGMReviewAuditFreshness:assess}=require('./hlm-phase11-gm-review-audit-freshness');
const record={schemaVersion:1,status:'unchanged',checkedAtMs:1000,sha256:'a'.repeat(64),requiresFreshGMReview:false,requiresGMApproval:true,productionActivationEnabled:false,gameplayActionAuthorized:false,saveWriteAllowed:false};
const payload=JSON.stringify(record);
const current=assess(payload,1100,100);assert.equal(current.status,'current-read-only');assert.equal(current.auditCurrent,true);
assert.equal(assess(payload,1101,100).status,'expired');
assert.equal(assess(payload,999,100).status,'future-audit');
assert.equal(assess(payload,-1,100).status,'invalid-clock');
assert.equal(assess(payload,1100,0).status,'invalid-clock');
assert.equal(assess(payload,1100,604800001).status,'invalid-clock');
assert.equal(assess(JSON.stringify({...record,status:'changed',requiresFreshGMReview:true}),1100,100).status,'review-required');
assert.equal(assess(JSON.stringify({...record,status:'unverified',requiresFreshGMReview:true}),1100,100).status,'review-required');
assert.equal(assess(JSON.stringify({...record,status:'invalid-audit-time',checkedAtMs:null,requiresFreshGMReview:true}),1100,100).status,'invalid-clock');
assert.equal(assess(JSON.stringify({...record,gameplayActionAuthorized:true}),1100,100).status,'invalid-audit');
assert.equal(assess('{',1100,100).status,'invalid-audit');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.equal(current.requiresGMApproval,true);assert.ok(Object.isFrozen(current));
assert.deepEqual(assess(payload,1100,100),current);
console.log('GM review audit freshness deterministic tests passed');
