'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {recheckGMReviewExpiry:recheck}=require('./hlm-phase11-gm-review-expiry-recheck');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const current=recheck(items,digest,true,1000,1100,1400,500);
assert.equal(current.status,'current');assert.equal(current.stillCurrent,true);
const expired=recheck(items,digest,true,1000,1100,1501,500);
assert.equal(expired.status,'expired');assert.equal(expired.firstStatus,'current');assert.equal(expired.stillCurrent,false);
assert.equal(recheck(items,digest,true,1000,1400,1300,500).status,'invalid-recheck-order');
assert.equal(recheck(items,digest,false,1000,1100,1400,500).status,'blocked');
assert.equal(recheck(items,'0'.repeat(64),true,1000,1100,1400,500).status,'blocked');
assert.equal(recheck([{before:'{',after:items[0].after}],digest,true,1000,1100,1400,500).status,'blocked');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(current[key],false);
assert.equal(current.requiresGMApproval,true);assert.ok(Object.isFrozen(current));
assert.deepEqual(recheck(items,digest,true,1000,1100,1400,500),current);
console.log('GM review expiry recheck deterministic tests passed');
