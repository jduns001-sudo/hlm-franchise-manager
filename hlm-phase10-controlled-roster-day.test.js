'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {simulateControlledRosterDay:simulate}=require('./hlm-phase10-controlled-roster-day');
const positions=['C','LW','RW','D','D','G'];
const teams=[1,2,3,4].map(id=>({id,name:'Team '+id}));
const players=teams.flatMap(t=>positions.map((position,i)=>({id:t.id*100+i,teamId:t.id,position,ovr:70+t.id})));
const contracts=players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const games=[{id:'G1',date:'2026-10-14',status:'scheduled',homeTeamId:1,awayTeamId:2},
 {id:'G2',date:'2026-10-14',status:'scheduled',homeTeamId:3,awayTeamId:4}];
const input={meta:{currentDate:'2026-10-13'},teams,players,contracts,injuries,games};
const state=createGameStateEnvelope(input),before=JSON.stringify(state);
assert.throws(()=>simulate(state,9),{code:'CONTROLLED_ROSTER_DAY_NOT_ENABLED'});
const result=simulate(state,9,{experimental:true});
assert.equal(result.advanced,true);
assert.equal(result.results.length,2);
assert.equal(result.nextState.meta.currentDate,'2026-10-14');
assert.equal(result.nextState.activity.games.filter(g=>g.status==='final').length,2);
assert.equal(result.standings.reduce((sum,t)=>sum+t.gp,0),4);
assert.equal(JSON.stringify(state),before);
assert.deepEqual(result,simulate(state,9,{experimental:true}));
const missing=createGameStateEnvelope({...input,contracts:contracts.filter(c=>c.teamId!==4)});
const blocked=simulate(missing,9,{experimental:true});
assert.equal(blocked.advanced,false);
assert.equal(blocked.nextState,null);
assert.equal(blocked.results.length,0);
assert.equal(blocked.blocked[0].gameId,'G2');
const duplicate=createGameStateEnvelope({...input,games:[games[0],{...games[1],id:'G1'}]});
assert.throws(()=>simulate(duplicate,9,{experimental:true}),{code:'INVALID_ROSTER_DAY_SCHEDULE'});
console.log('Mission 743 roster-backed daily simulation tests passed.');
