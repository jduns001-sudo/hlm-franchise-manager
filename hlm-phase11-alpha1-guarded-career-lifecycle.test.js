'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createGuardedCareerLifecycle}=require('./hlm-phase11-alpha1-guarded-career-lifecycle');
const KEY='hlm-phase11-alpha1-career-test';
const teams=[1,2].map(id=>({id,name:'Club '+id}));
const state=createGameStateEnvelope({meta:{saveId:'career-test',currentDate:'2027-06-20',controlledTeamId:1},teams,games:[{id:'regular-1',date:'2027-06-19',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:4,awayGoals:2,overtime:false}],contracts:[{id:'contract-1'}]});
const data=new Map([[KEY,JSON.stringify(state)],['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:k=>data.has(k)?data.get(k):null,setItem:(k,v)=>data.set(k,String(v))};
assert.throws(()=>createGuardedCareerLifecycle(storage,'hlm_front_office_v8'),/isolated/);
const guard=createGuardedCareerLifecycle(storage,KEY);
let review=guard.review('start-playoffs',{spots:2});
assert.equal(review.requiresHumanApproval,true);
assert.equal(guard.decide('cancel',review.reviewSequence).saved,false);
assert.equal(guard.decide('approve',review.reviewSequence).saved,false);
review=guard.review('start-playoffs',{spots:2});
assert.equal(guard.decide('approve',review.reviewSequence).saved,true);
assert.equal(JSON.parse(storage.getItem(KEY)).extensions.phase10Playoffs.status,'active');
let count=0;
while(JSON.parse(storage.getItem(KEY)).extensions.phase10Playoffs.status==='active'){
 assert.ok(++count<=7,'best of seven must complete');
 review=guard.review('play-playoff-game',{seed:count});
 assert.equal(review.requiresHumanApproval,true);
 assert.equal(guard.decide('approve',review.reviewSequence).saved,true);
}
const champion=JSON.parse(storage.getItem(KEY)).extensions.phase10Playoffs.championTeamId;
assert.ok([1,2].includes(champion));
review=guard.review('archive-championship',{seasonId:'2026-27'});
assert.equal(guard.decide('decline',review.reviewSequence).saved,false);
assert.equal(JSON.parse(storage.getItem(KEY)).history.seasons.length,0);
review=guard.review('archive-championship',{seasonId:'2026-27'});
assert.equal(guard.decide('approve',review.reviewSequence).saved,true);
assert.equal(JSON.parse(storage.getItem(KEY)).history.seasons[0].championTeamId,champion);
const before=storage.getItem(KEY);
review=guard.review('begin-next-season',{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'});
assert.equal(guard.decide('cancel',review.reviewSequence).saved,false);
assert.equal(storage.getItem(KEY),before);
review=guard.review('begin-next-season',{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'});
assert.equal(guard.decide('approve',review.reviewSequence).saved,true);
const next=JSON.parse(storage.getItem(KEY));
assert.equal(next.extensions.phase10CurrentSeasonId,'2027-28');
assert.equal(next.meta.controlledTeamId,1);
assert.equal(next.history.seasons[0].championTeamId,champion);
assert.equal(next.assets.contracts.length,1);
assert.ok(next.activity.games.every(g=>g.status==='scheduled'));
assert.equal(storage.getItem('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
review=guard.review('begin-next-season',{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'});
assert.equal(review.saved,false);
const stale=guard.review('unknown');
assert.equal(stale.saved,false);
const pending=guard.review('start-playoffs',{spots:2});
assert.equal(pending.saved,false);
const guard2=createGuardedCareerLifecycle(storage,KEY);
const beforeConflict=storage.getItem(KEY);
storage.setItem(KEY,beforeConflict+' ');
assert.equal(guard2.review('archive-championship',{seasonId:'2026-27'}).saved,false);
guard.reload();
assert.equal(guard.decide('approve',999).saved,false);
console.log('Alpha 1 guarded playoff, champion archive, next-season and GM no-save safety passed');
