'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createIsolatedCPUTradeCandidate}=require('./hlm-phase9-cpu-isolated-trade-candidate');
const base=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'},{id:'p2',teamId:'NYR'}],contracts:[{playerId:'p1',teamId:'BUF',aav:3000000},{playerId:'p2',teamId:'NYR',aav:5000000}],finances:{buf:{teamId:'BUF',seasonId:2030,payroll:18000000,capLimit:20000000},nyr:{teamId:'NYR',seasonId:2030,payroll:19000000,capLimit:20000000}}});
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]},{fromTeamId:'NYR',toTeamId:'BUF',assets:[{type:'player',id:'p2',ownerTeamId:'NYR'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'net-2030'};
const original=JSON.stringify(base);
const result=createIsolatedCPUTradeCandidate(base,'BUF',trade);
assert.equal(result.candidateState.finances.buf.payroll,20000000);
assert.equal(result.candidateState.finances.nyr.payroll,17000000);
assert.equal(result.candidateState.assets.contracts[0].teamId,'NYR');
assert.equal(result.candidateState.assets.contracts[1].teamId,'BUF');
assert.equal(result.candidateState.activity.transactions.length,1);
assert.equal(JSON.stringify(base),original);
const over=JSON.parse(JSON.stringify(base));over.finances.buf.payroll=19000000;
assert.throws(()=>createIsolatedCPUTradeCandidate(over,'BUF',trade),e=>e.code==='CPU_TRADE_CAP_LIMIT_EXCEEDED');
const missing=JSON.parse(JSON.stringify(base));missing.assets.contracts.pop();
assert.throws(()=>createIsolatedCPUTradeCandidate(missing,'BUF',trade),e=>e.code==='CPU_TRADE_CAP_RECONCILIATION_UNSUPPORTED');
const season=JSON.parse(JSON.stringify(base));season.finances.nyr.seasonId=2031;
assert.throws(()=>createIsolatedCPUTradeCandidate(season,'BUF',trade),e=>e.code==='CPU_TRADE_CAP_RECONCILIATION_UNSUPPORTED');
assert.equal(JSON.stringify(base),original);
console.log('Phase 9 multi-player net cap reconciliation tests passed');
