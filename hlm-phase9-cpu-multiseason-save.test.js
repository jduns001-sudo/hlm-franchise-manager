'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {persistApprovedCPUMultiSeasonCandidate}=require('./hlm-phase9-cpu-multiseason-save');
const repository=createMemorySaveRepository();
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT',currentDate:'2030-06-30'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]});
state.history.seasons.push({id:'2029-30',status:'completed',champion:'PIT'});
repository.save('original',state);
const expectedSourceFingerprint=serializeGameState(repository.load('original').state);
const transitions=[{fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01'},{fromSeasonId:'2030-31',toSeasonId:'2031-32',nextDate:'2031-07-01',completedSeason:{seasonId:'2030-31',championTeamId:'NYR'}}];
const run=(changes={})=>persistApprovedCPUMultiSeasonCandidate({repository,sourceSlotId:'original',destinationSlotId:'future',expectedSourceFingerprint,transitions,confirmCommit:true,...changes});
assert.throws(()=>run({confirmCommit:false}),e=>e.code==='CPU_MULTI_SEASON_SAVE_CONFIRMATION_REQUIRED');
assert.throws(()=>run({destinationSlotId:'original'}),e=>e.code==='CPU_MULTI_SEASON_SAVE_SOURCE_PROTECTED');
assert.throws(()=>run({expectedSourceFingerprint:'stale'}),e=>e.code==='CPU_MULTI_SEASON_SAVE_SOURCE_STALE');
assert.throws(()=>run({transitions:[transitions[0],{...transitions[1],completedSeason:undefined}]}),e=>e.code==='CPU_MULTI_SEASON_COMPLETION_REQUIRED');
assert.equal(repository.count(),1);
const result=run();
assert.equal(result.verified,true);
assert.equal(result.transitionCount,2);
assert.equal(result.productionCPUExecutionEnabled,false);
const future=repository.load('future').state;
assert.equal(future.history.seasons.length,3);
assert.equal(future.history.seasons[1].champion,'NYR');
assert.equal(future.history.seasons[2].status,'active');
assert.equal(future.meta.currentDate,'2031-07-01');
assert.equal(future.meta.controlledTeamId,'PIT');
assert.equal(serializeGameState(repository.load('original').state),expectedSourceFingerprint);
assert.throws(()=>run(),e=>e.code==='CPU_MULTI_SEASON_SAVE_DESTINATION_OCCUPIED');
console.log('Phase 9 approved CPU multi-season save tests passed');
