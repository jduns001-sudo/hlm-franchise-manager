'use strict';
const assert=require('node:assert/strict');
const {build}=require('./hlm-phase11-season-gm-brief');
const {checkpoint}=require('./hlm-phase11-season-checkpoint');
const {createBridge,KEY}=require('./hlm-phase11-gameplay-bridge');
let writes=0;
const state={meta:{controlledTeamId:1,currentDate:'2026-10-17'},universe:{teams:[{id:1,name:'Home'},{id:2,name:'Away'}],players:[]},activity:{games:[{id:'g1',date:'2026-10-18',homeTeamId:1,awayTeamId:2,status:'scheduled'}]},privateNotes:'DO_NOT_LEAK_SECRET'};
const bridge=createBridge({createBrowserFranchiseSaveStore:()=>({load:()=>state}),calculateStandings:()=>[]},{getItem:k=>k===KEY?JSON.stringify(state):null,setItem(){writes++}});
const before=build(checkpoint(bridge));
assert.equal(before.actions[0].topic,'baseline');
assert.equal(before.actions.some(a=>a.topic==='next-game'),true);
assert.equal(before.actions.some(a=>a.topic==='evidence-gaps'),true);
assert.equal(before.finalDecisionMaker,'human-gm');
assert.equal(before.productionActivationAllowed,false);
assert.equal(before.automaticTransactionsAllowed,false);
assert.equal(before.privateNotesIncluded,false);
assert.equal(JSON.stringify(before).includes('DO_NOT_LEAK_SECRET'),false);
assert.deepEqual(before,build(checkpoint(bridge)));
state.activity.games[0]={...state.activity.games[0],status:'final',homeGoals:1,awayGoals:3};
const after=build(checkpoint(bridge));
assert.equal(after.goalDifferential,-2);
assert.equal(after.actions.some(a=>a.topic==='goal-balance'&&a.priority==='review'),true);
assert.equal(after.controlledGamesRemaining,0);
assert.equal(writes,0);
assert.throws(()=>build({...checkpoint(bridge),productionActivationAllowed:true}),/Verified isolated/);
assert.throws(()=>build({...checkpoint(bridge),record:{wins:4,losses:0,ties:0}}),/Invalid controlled team record/);
console.log('Mission 1313 human GM season brief deterministic regressions passed');
