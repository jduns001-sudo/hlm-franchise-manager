'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('phase10-roster-lab.html','utf8');
const ids=['new','advance','fast','playoffs','playoffgame','summary','standings','results','leaders','bracket','status'];
for(const id of ids)assert(html.includes('id="'+id+'"'),'Missing UI element: '+id);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(Boolean);
assert.equal(scripts.length,1,'Expected one inline UI controller');
const elements=new Map();
function element(id){if(!elements.has(id))elements.set(id,{id,textContent:'',disabled:false,children:[],replaceChildren(...children){this.children=children},append(...children){this.children.push(...children)}});return elements.get(id)}
const storageMap=new Map([['hlm-phase10-demo-v1','DO_NOT_TOUCH']]);
const storage={getItem:k=>storageMap.get(k)??null,setItem:(k,v)=>storageMap.set(k,v)};
const sandbox={window:{localStorage:storage},document:{getElementById:element,createElement:tag=>element('dynamic-'+Math.random())},confirm:()=>true,console};
vm.runInNewContext(fs.readFileSync('hlm-phase10-roster-lab.bundle.js','utf8'),sandbox,{timeout:10000});
vm.runInNewContext(scripts[0],sandbox,{timeout:10000});
assert.match(element('summary').textContent,/No experimental roster season/);
element('new').onclick();
assert.match(element('summary').textContent,/Games complete: 0 \/ 56/);
assert.equal(element('advance').disabled,false);
element('advance').onclick();
assert.match(element('summary').textContent,/Games complete: 2 \/ 56/);
assert(element('leaders').children.length>0,'Goal leaders should be visible');
element('fast').onclick();
assert.match(element('summary').textContent,/Games complete: 56 \/ 56/);
assert.equal(element('playoffs').disabled,false);
element('playoffs').onclick();
assert.match(element('bracket').textContent,/Round 1/);
let attempts=0;
while(!element('bracket').textContent.includes('Champion')&&attempts++<25)element('playoffgame').onclick();
assert.match(element('bracket').textContent,/Champion team:/);
assert.equal(element('playoffgame').disabled,true);
assert.equal(storageMap.get('hlm-phase10-demo-v1'),'DO_NOT_TOUCH');
const reload={window:{localStorage:storage},document:{getElementById:element,createElement:tag=>element('reloaded-'+Math.random())},confirm:()=>true,console};
vm.runInNewContext(fs.readFileSync('hlm-phase10-roster-lab.bundle.js','utf8'),reload,{timeout:10000});
vm.runInNewContext(scripts[0],reload,{timeout:10000});
assert.match(element('bracket').textContent,/Champion team:/);
console.log('Mission 752 UI controller and save reload regression passed.');
