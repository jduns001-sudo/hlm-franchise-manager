'use strict';
const assert=require('node:assert/strict');
const {METRICS,summarize,compare}=require('./hlm-player-performance-multimetric-insights');
const game=(goals,assists,shots=4)=>({goals,assists,shots});
const data=[{season:2029,games:Array.from({length:20},()=>game(1,0))},{season:2027,games:[game(0,1)]},{season:2028,games:Array.from({length:5},()=>game(0,1))}];
const original=JSON.stringify(data);
const options={years:[2029,2027,2028,2029],metrics:['finishing','pointsPerGame','goalsPerGame']};
const result=summarize(data,options);
assert.deepEqual(result.rows.map(r=>r.season),[2027,2028,2029]);
assert.deepEqual(Object.keys(result.rows[0].values),options.metrics);
assert.equal(result.rows[0].confidence,'limited');
assert.equal(result.rows[1].confidence,'developing');
assert.equal(result.rows[2].confidence,'established');
assert.equal(result.rows[2].values.finishing,.25);
assert.equal(result.changes.length,6);
assert.equal(result.changes[0].confidence,'insufficient-sample');
assert.equal(result.changes[3].confidence,'directional');
assert.equal(result.changes[3].delta,.25);
assert.deepEqual(result,summarize(data,options));
assert.deepEqual(compare(data,data,options).player,compare(data,data,options).team);
assert.equal(summarize(data,{years:[]}).rows.length,0);
assert.equal(summarize([{season:2027,games:[]}],{years:[2027]}).rows[0].values.finishing,null);
assert.throws(()=>summarize([{season:2027,games:[game(5,0,4)]}],{years:[2027]}),/invalid game/);
assert.throws(()=>summarize(data,{years:[2027],metrics:['unknown']}),/invalid selection/);
assert.throws(()=>summarize([{season:2027,games:[]},{season:2027,games:[]}],{years:[2027]}),/duplicate/);
assert.equal(JSON.stringify(data),original);
assert.equal(Object.isFrozen(result.rows[0].values),true);
assert.equal(METRICS.length,5);
console.log('Mission 1154 deterministic multi-metric insights passed');
