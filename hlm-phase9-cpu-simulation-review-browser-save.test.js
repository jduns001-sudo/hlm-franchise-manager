'use strict';
const assert=require('node:assert/strict');
const {createMasterCalendar}=require('./hlm-master-calendar');
const {createSeasonPhaseTimeline}=require('./hlm-season-phase-timeline');
const {createCalendarEventIndex}=require('./hlm-calendar-event');
const {createSimulationStopRules}=require('./hlm-simulation-stop-rules');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {createBrowserSaveAdapter}=require('./hlm-browser-save-adapter');
const {createSimulationCommand,planSimulationCommand}=require('./hlm-simulation-command');
const {authorizeSimulationCommand,executeSimulationCommandCalendar,verifySimulationCommandCalendar}=require('./hlm-simulation-command-execution');
const {createSimulationGameStateCandidate,verifySimulationGameStateCandidate,authorizeSimulationGameStateActivation,activateSimulationGameState,verifySimulationGameStateActivation}=require('./hlm-simulation-gamestate-integration');
const {persistReviewedCPUSimulationCandidate}=require('./hlm-phase9-cpu-simulation-review-browser-save');
const memory=new Map(),storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const repository=createBrowserSaveAdapter(storage);
const state=createGameStateEnvelope({meta:{currentDate:'2027-04-17',controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}]});
repository.save('active',state);
const before=serializeGameState(repository.load('active').state);
const calendar=createMasterCalendar({currentDate:'2027-04-17'});
const timeline=createSeasonPhaseTimeline({windows:[{phaseId:'regular-season',startDate:'2027-04-01',endDate:'2027-04-30'}]});
const eventIndex=createCalendarEventIndex({events:[]});
const stopRules=createSimulationStopRules({});
const plan=planSimulationCommand({calendar,timeline,eventIndex,stopRules,command:createSimulationCommand({command:'day'})});
const authorization=authorizeSimulationCommand({plan,approved:true});
const execution=executeSimulationCommandCalendar({calendar,plan,authorization});
const verification=verifySimulationCommandCalendar({execution});
const candidate=createSimulationGameStateCandidate({state,verification});
const candidateVerification=verifySimulationGameStateCandidate({sourceState:state,candidate});
const activationAuthorization=authorizeSimulationGameStateActivation({verification:candidateVerification,approved:true});
const activation=activateSimulationGameState({verification:candidateVerification,authorization:activationAuthorization});
const simulationVerification=verifySimulationGameStateActivation({activation});
const args={storage,sourceSlotId:'active',destinationSlotId:'next',sourceState:state,simulationVerification};
assert.throws(()=>persistReviewedCPUSimulationCandidate(args),e=>e.code==='CPU_SIMULATION_SAVE_APPROVAL_REQUIRED');
assert.equal(repository.list().length,1);
const result=persistReviewedCPUSimulationCandidate({...args,confirmCommit:true});
assert.equal(result.verified,true);
assert.equal(result.teamCount,2);
assert.equal(result.gamesSimulated,false);
assert.equal(repository.load('next').state.meta.currentDate,'2027-04-18');
assert.equal(serializeGameState(repository.load('active').state),before);
assert.throws(()=>persistReviewedCPUSimulationCandidate({...args,confirmCommit:true}),e=>e.code==='CPU_SIMULATION_SAVE_DESTINATION_UNAVAILABLE');
assert.throws(()=>persistReviewedCPUSimulationCandidate({...args,destinationSlotId:'active',confirmCommit:true}),e=>e.code==='CPU_SIMULATION_SAVE_DESTINATION_UNAVAILABLE');
console.log('Phase 9 simulation CPU review browser persistence integration tests passed');
