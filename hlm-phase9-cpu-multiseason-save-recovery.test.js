'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {persistApprovedCPUMultiSeasonCandidate}=require('./hlm-phase9-cpu-multiseason-save');
const underlying=createMemorySaveRepository();
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT',currentDate:'2030-06-30'},teams:[{id:'PIT'},{id:'NYR'}]});
state.history.seasons.push({id:'2029-30',status:'completed',champion:'PIT'});
underlying.save('source',state);
const fingerprint=serializeGameState(underlying.load('source').state);
const transitions=[{fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01'}];
const repository={...underlying,load(id){if(id==='candidate')throw Error('transient reload outage');return underlying.load(id);}};
assert.throws(()=>persistApprovedCPUMultiSeasonCandidate({repository,sourceSlotId:'source',destinationSlotId:'candidate',expectedSourceFingerprint:fingerprint,transitions,confirmCommit:true}),e=>e.code==='CPU_MULTI_SEASON_SAVE_RELOAD_FAILED');
assert.equal(underlying.has('candidate'),true);
assert.equal(underlying.has('source'),true);
assert.equal(serializeGameState(underlying.load('source').state),fingerprint);
assert.equal(underlying.load('candidate').state.history.seasons.length,2);
console.log('Phase 9 multi-season save reload recovery tests passed');
