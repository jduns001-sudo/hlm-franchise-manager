'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {verifySequentialCPUTradeSaveRoundTrip}=require('./hlm-phase9-cpu-trade-sequence-save');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}]});
const trade=(from,to,id)=>({teamIds:[from,to],legs:[{fromTeamId:from,toTeamId:to,assets:[{type:'player',id:'p1',ownerTeamId:from}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:id});
const steps=[{teamId:'BUF',trade:trade('BUF','NYR','t1')},{teamId:'NYR',trade:trade('NYR','BOS','t2')}];
const repo=createMemorySaveRepository();
repo.save('original',state);
const result=verifySequentialCPUTradeSaveRoundTrip({state,steps,repository:repo,slotId:'sequence'});
assert.equal(result.verified,true);
assert.equal(result.stepCount,2);
assert.equal(result.productionCPUExecutionEnabled,false);
assert.equal(repo.load('sequence').state.universe.players[0].teamId,'BOS');
assert.deepEqual(repo.load('sequence').state.activity.transactions.map(t=>t.id),['t1','t2']);
assert.deepEqual(repo.load('original').state,state);
assert.throws(()=>verifySequentialCPUTradeSaveRoundTrip({state,steps,repository:repo,slotId:'sequence'}),e=>e.code==='CPU_TRADE_SEQUENCE_SAVE_SLOT_OCCUPIED');
assert.throws(()=>verifySequentialCPUTradeSaveRoundTrip({state,steps:[steps[0],{teamId:'NYR',trade:trade('NYR','BOS','t1')}],repository:repo,slotId:'invalid'}),e=>e.code==='CPU_TRADE_TRANSACTION_ID_DUPLICATE');
assert.equal(repo.has('invalid'),false);
const corrupt=createMemorySaveRepository();
const unreliable={has:corrupt.has,save:corrupt.save,load:()=>({state})};
assert.throws(()=>verifySequentialCPUTradeSaveRoundTrip({state,steps,repository:unreliable,slotId:'uncertain'}),e=>e.code==='CPU_TRADE_SEQUENCE_SAVE_MISMATCH');
assert.equal(corrupt.has('uncertain'),true);
assert.deepEqual(repo.load('original').state,state);
const mutated=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'},{id:'BOS'}],players:[{id:'p1',teamId:'BUF'}]});
const originalHas=repo.has.bind(repo);
let checks=0;
const hostile={has:id=>{checks++;if(checks===2)mutated.universe.players[0].teamId='BOS';return originalHas(id);},save:repo.save,load:repo.load};
assert.throws(()=>verifySequentialCPUTradeSaveRoundTrip({state:mutated,steps,repository:hostile,slotId:'hostile'}),e=>e.code==='CPU_TRADE_SEQUENCE_SOURCE_CHANGED');
assert.equal(repo.has('hostile'),false);
console.log('Phase 9 sequential CPU trade isolated save tests passed');
