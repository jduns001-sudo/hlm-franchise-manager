'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {previewRosterCareer}=require('./hlm-phase11-real-roster-season-preview');
const positions=['C','LW','RW','D','D','G'];
const teams=[1,2,3,4].map(id=>({id,name:'Club '+id}));
const players=teams.flatMap(t=>Array.from({length:23},(_,i)=>({id:t.id*100+i,teamId:t.id,position:positions[i%6],ovr:65+t.id*4+i%10,metadata:{source:'import'}})));
const contracts=players.map((p,i)=>({contractId:'c'+i,playerId:p.id,teamId:p.teamId,status:'Active',aav:1000000,years:2}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const games=[[1,2],[3,4],[1,3],[2,4],[1,4],[2,3]].map(([homeTeamId,awayTeamId],i)=>({id:'g'+i,homeTeamId,awayTeamId,date:'2026-10-'+(20+i),status:'scheduled'}));
const finances={teamSnapshots:Object.fromEntries(teams.map(t=>[t.id,{balance:10000000}]))};
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-19'},teams,players,contracts,injuries,games,finances,prospects:[{id:'pros1'}],draftPicks:[{pickId:'pick1',currentOwnerId:1,status:'available'}]});
const before=JSON.stringify(state);
const options={seasonId:'2026-27',nextSeasonId:'2027-28',nextStartDate:'2027-10-01',offseason:{contracts:{expiredContractIds:[],signings:[]},draftSelections:[]}};
const first=previewRosterCareer(state,options);
assert.equal(first.official,false);
assert.equal(first.assistsShotsGoalieStatisticsCertified,false);
const firstEvents=first.nextState.extensions.phase11ExperimentalCareerGoalEvents;
assert.equal(firstEvents.length,first.experimentalGoals.regular+first.experimentalGoals.playoffs);
assert.equal(firstEvents.filter(e=>e.stage==='regular').length,first.experimentalGoals.regular);
assert.equal(firstEvents.filter(e=>e.stage==='playoff').length,first.experimentalGoals.playoffs);
assert.equal(first.experimentalGoals.leaders.reduce((n,p)=>n+p.goals,0),firstEvents.length);
assert(firstEvents.every(e=>e.seasonId==='2026-27'&&e.experimental===true));
assert.equal(first.playerStatisticsCertified,false);
assert.equal(first.persistencePerformed,false);
assert.equal(first.regularGames,6);
assert(first.playoffGames>=6&&first.playoffGames<=21);
assert.equal(first.archivedSeasons,1);
assert.equal(first.nextState.extensions.phase10CurrentSeasonId,'2027-28');
assert.equal(first.nextState.activity.games.length,12);
assert.equal(first.nextState.universe.players.length,92);
assert.equal(first.nextState.assets.contracts.length,92);
assert.deepEqual(first.nextState.finances,finances);
assert.equal(first.nextState.meta.controlledTeamId,1);
assert.equal(first.nextState.universe.players[0].metadata.source,'import');
assert.equal(JSON.stringify(state),before);
assert.deepEqual(first,previewRosterCareer(state,options));
const invalid=JSON.parse(before);invalid.assets.contracts=[];
assert.throws(()=>previewRosterCareer(invalid,options),/Roster blocked/);
assert.equal(JSON.stringify(state),before);
const second=previewRosterCareer(first.nextState,{...options,seasonId:'2027-28',nextSeasonId:'2028-29',nextStartDate:'2028-10-01'});
assert.equal(second.archivedSeasons,2);
const careerEvents=second.nextState.extensions.phase11ExperimentalCareerGoalEvents;
assert.equal(careerEvents.length,firstEvents.length+second.experimentalGoals.regular+second.experimentalGoals.playoffs);
assert.equal(careerEvents.filter(e=>e.seasonId==='2026-27').length,firstEvents.length);
assert.equal(new Set(careerEvents.map(e=>[e.seasonId,e.stage,e.gameId,e.teamId,e.sequence].join('|'))).size,careerEvents.length);
assert.equal(second.nextState.extensions.phase10CurrentSeasonId,'2028-29');
assert.equal(second.nextState.universe.players.length,92);
assert.equal(second.nextState.history.seasons[0].championTeamId,first.championTeamId);
assert.equal(second.nextState.meta.controlledTeamId,1);
assert.deepEqual(second.nextState.finances,finances);
assert.equal(second.official,false);
console.log('Two-season 92-player roster-weighted experimental games, standings, playoffs, offseason and finance continuity passed');
