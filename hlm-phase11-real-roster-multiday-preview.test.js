'use strict';
const assert=require('node:assert/strict');
const {previewImportedRosterSeason:preview}=require('./hlm-phase11-real-roster-multiday-preview');
const positions=['C','LW','RW','D','D','G'];
const players=[1,2].flatMap(teamId=>positions.map((position,i)=>({id:teamId*100+i,name:'Player '+teamId+'-'+i,teamId,position,ovr:teamId===1?85:75})));
const legacy={teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],players,contracts:players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'})),injuries:players.map(p=>({playerId:p.id,status:'Recovered'}))};
const options={controlledTeamId:1,currentDate:'2026-10-12',games:[{id:'G1',date:'2026-10-13',status:'scheduled',homeTeamId:1,awayTeamId:2},{id:'G2',date:'2026-10-14',status:'scheduled',homeTeamId:2,awayTeamId:1}],days:2,seed:11,experimental:true};
const original=JSON.stringify(legacy),optionsBefore=JSON.stringify(options);
const result=preview(legacy,options);
assert.equal(result.advancedDays,2);
assert.equal(result.blocked.length,0);
assert.equal(result.nextState.meta.currentDate,'2026-10-14');
assert.equal(result.nextState.activity.games.filter(g=>g.status!=='scheduled').length,2);
assert.equal(result.days.length,2);
assert.equal(result.official,false);
assert.equal(result.persistencePerformed,false);
assert.deepEqual(result,preview(legacy,options));
assert.equal(JSON.stringify(legacy),original);
assert.equal(JSON.stringify(options),optionsBefore);
assert.throws(()=>preview(legacy,{...options,experimental:false}),/opt-in/);
assert.throws(()=>preview(legacy,{...options,days:32}),/1 through 31/);
assert.throws(()=>preview(legacy,{...options,seed:-1}),/seed/);
const invalid=preview(legacy,{...options,games:[{...options.games[0],awayTeamId:99}]});
assert.equal(invalid.advancedDays,0);
assert.equal(invalid.nextState,null);
assert(invalid.blocked[0].issues.some(i=>i.code==='INVALID_GAME_TEAMS'));
const blocked=preview({...legacy,contracts:[]},options);
assert.equal(blocked.advancedDays,0);
assert.equal(blocked.nextState,null);
assert.equal(JSON.stringify(legacy),original);
console.log('Phase 11 real-roster multiday preview, isolation, deterministic outcomes and atomic block passed');
