'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {verifyIsolatedCPUTradeSaveRoundTrip}=require('./hlm-phase9-cpu-trade-isolated-save-roundtrip');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}],draftPicks:[{pickId:'d1',ownerTeamId:'NYR',currentOwnerId:'NYR'}]});
const before=JSON.stringify(state);
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]},{fromTeamId:'NYR',toTeamId:'BUF',assets:[{type:'draft-pick',id:'d1',ownerTeamId:'NYR'}]}],playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,humanGMApproved:true};
const repo=createMemorySaveRepository();
repo.save('original',state);
const result=verifyIsolatedCPUTradeSaveRoundTrip({state,teamId:'BUF',trade,repository:repo,slotId:'candidate'});
assert.equal(result.verified,true);
assert.equal(result.liveFranchiseSaveChanged,false);
assert.equal(repo.load('candidate').state.universe.players[0].teamId,'NYR');
assert.equal(repo.load('candidate').state.assets.draftPicks[0].currentOwnerId,'BUF');
assert.deepEqual(repo.load('original').state,state);
assert.equal(JSON.stringify(state),before);
assert.throws(()=>verifyIsolatedCPUTradeSaveRoundTrip({state,teamId:'BUF',trade,repository:repo,slotId:'candidate'}),e=>e.code==='CPU_TRADE_SAVE_SLOT_OCCUPIED');
assert.throws(()=>verifyIsolatedCPUTradeSaveRoundTrip({state,teamId:'PIT',trade,repository:repo,slotId:'bad'}),e=>e.code==='CPU_TRADE_HUMAN_TEAM_PROTECTED');
assert.equal(repo.has('bad'),false);
const corrupt=createMemorySaveRepository();
const sabotaged={has:corrupt.has,save:corrupt.save,remove:corrupt.remove,load:()=>({state})};
assert.throws(()=>verifyIsolatedCPUTradeSaveRoundTrip({state,teamId:'BUF',trade,repository:sabotaged,slotId:'rollback'}),e=>e.code==='CPU_TRADE_SAVE_ROUNDTRIP_MISMATCH');
assert.equal(corrupt.has('rollback'),false);
console.log('Phase 9 isolated CPU trade save round-trip tests passed');
