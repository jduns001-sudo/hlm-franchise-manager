'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createBrowserFranchiseSaveStore}=require('./hlm-phase10-browser-storage');
const {finalizeChampionshipSeason}=require('./hlm-phase10-season-finalization');
const {rolloverBrowserFranchise}=require('./hlm-phase10-browser-offseason');
const map=new Map(),storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v)};
const store=createBrowserFranchiseSaveStore(storage,'browser');
const state=createGameStateEnvelope({meta:{saveId:'browser',currentDate:'2027-06-20',controlledTeamId:1},teams:[{id:1,name:'Wolves'},{id:2,name:'Falcons'}],games:[{id:'g',status:'final',homeTeamId:1,awayTeamId:2,homeGoals:2,awayGoals:1,overtime:false}]});
state.extensions.phase10Playoffs={status:'complete',championTeamId:1,rounds:[[]]};
store.save(finalizeChampionshipSeason(state,'2026-27').nextState);
const before=map.get('browser');
const options={nextSeason:{completedSeasonId:'2026-27',nextSeasonId:'2027-28',startDate:'2027-10-01'}};
assert.throws(()=>rolloverBrowserFranchise(storage,{nextSeason:{...options.nextSeason,startDate:'2027-01-01'}},'browser'),/after championship/);
assert.equal(map.get('browser'),before);
const result=rolloverBrowserFranchise(storage,options,'browser');
assert.equal(result.summary.season.scheduledGames,2);
assert.deepEqual(store.load(),result.nextState);
assert.throws(()=>rolloverBrowserFranchise(storage,options,'browser'),/already initialized|unfinished/);
assert.throws(()=>rolloverBrowserFranchise(null,options,'browser'),/Storage/);
console.log('Phase 10 browser offseason adapter tests passed');
