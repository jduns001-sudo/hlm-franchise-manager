'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {executeReviewedCPUDecisionTrade}=require('./hlm-phase9-cpu-decision-trade-execution-bridge');
const repo=createMemorySaveRepository();
repo.save('human',createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]}));
const before=serializeGameState(repo.load('human').state);
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'cpu-bridge-1'};
const steps=[{teamId:'BUF',trade}];
const run=(changes={})=>executeReviewedCPUDecisionTrade({repository:repo,sourceSlotId:'human',destinationSlotId:'candidate',teamId:'BUF',steps,decisionOptions:{},confirmExecution:true,...changes});
assert.throws(()=>run({confirmExecution:false}),e=>e.code==='CPU_DECISION_TRADE_APPROVAL_REQUIRED');
assert.throws(()=>run({teamId:'PIT'}),e=>e.code==='CPU_DECISION_TRADE_HUMAN_PROTECTED');
assert.throws(()=>run({teamId:'NYR'}),e=>e.code==='CPU_DECISION_TRADE_TEAM_MISMATCH');
assert.throws(()=>run(),e=>e.code==='CPU_DECISION_TRADE_PREFLIGHT_FAILED');
assert.equal(repo.count(),1);
assert.equal(serializeGameState(repo.load('human').state),before);
console.log('Phase 9 CPU decision trade execution bridge fail-closed tests passed');
