'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {prepareGMReviewIntegrity}=require('./hlm-phase11-gm-review-presentation-integrity');
const {summarizeGMReviewTransitions:summary}=require('./hlm-phase11-gm-review-transition-summary');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const items=[{before:exportGMReviewEvidence(home,away,[5,10],[5]).text,after:exportGMReviewEvidence(home,away,[5,10,25],[10]).text}];
const digest=prepareGMReviewIntegrity(items).sha256;
const report=summary(items,digest,true,1000,[1100,1200,1500,1501],500);
assert.equal(report.status,'review-required');assert.equal(report.checkCount,4);assert.equal(report.transitionCount,3);
assert.equal(report.counts['remained-current'],2);assert.equal(report.counts['became-unavailable'],1);assert.equal(report.firstFailureIndex,3);
assert.equal(summary(items,digest,true,1000,[1100,1200],500).status,'current');
assert.equal(summary(items,digest,true,1000,[1200,1100],500).status,'unavailable');
assert.equal(summary(items,digest,true,1000,[],500).status,'unavailable');
assert.equal(summary(items,'0'.repeat(64),true,1000,[1100,1200],500).status,'review-required');
assert.equal(summary([{before:'{',after:items[0].after}],digest,true,1000,[1100,1200],500).status,'review-required');
for(const key of ['productionActivationEnabled','gameplayActionAuthorized','saveWriteAllowed'])assert.equal(report[key],false);
assert.equal(report.requiresGMApproval,true);assert.ok(Object.isFrozen(report));assert.ok(Object.isFrozen(report.counts));
assert.deepEqual(summary(items,digest,true,1000,[1100,1200,1500,1501],500),report);
console.log('GM review transition summary deterministic tests passed');
