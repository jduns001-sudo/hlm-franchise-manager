'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createExperimentalSchedule,runExperimentalSeasonBatch}=require('./hlm-experimental-season-batch');
const p=require('./hlm-experimental-playoff-series');
const positions=['C','LW','RW','D','D','G'];
const players=[...positions.map((position,i)=>({id:10+i,teamId:1,position,ovr:80})),...positions.map((position,i)=>({id:20+i,teamId:2,position,ovr:70}))];
const contracts=players.map(q=>({playerId:q.id,teamId:q.teamId,status:'Active'}));
const injuries=players.map(q=>({playerId:q.id,status:'Recovered'}));
const state=createGameStateEnvelope({teams:[{id:1,name:'Wolves'},{id:2,name:'Bears'}],players,contracts,injuries});
const before=JSON.stringify(state);
const bracket=p.buildExperimentalBracket([{teamId:1},{teamId:2}]);
assert.deepEqual(bracket,[{seriesId:1,higherSeedTeamId:1,lowerSeedTeamId:2}]);
assert.equal(p.playoffHomeTeam(0,1,2),1);
assert.equal(p.playoffHomeTeam(2,1,2),2);
const series=p.simulateExperimentalPlayoffSeries(state,1,2,12345,7);
assert.equal(series.researchReady,true);
assert(series.games.length>=4&&series.games.length<=7);
assert.equal(series.wins[String(series.winnerTeamId)],4);
assert.equal(p.playoffSeriesAudit(series).consistent,true);
assert.equal(p.playoffSeriesSummary(series).official,false);
assert.deepEqual(p.simulateExperimentalPlayoffSeries(state,1,2,12345,7),series);
const season=runExperimentalSeasonBatch(state,createExperimentalSchedule([1,2],2),12345);
assert.equal(p.createExperimentalPlayoffPreview(season,2).firstRound.length,1);
const round=p.runExperimentalPlayoffRound(state,bracket,12345,7);
assert.equal(round.researchReady,true);
assert.equal(round.winners.length,1);
assert.equal(JSON.stringify(state),before);
const blockedState=createGameStateEnvelope({teams:state.universe.teams,players,contracts:contracts.filter(c=>c.playerId!==20),injuries});
const blocked=p.simulateExperimentalPlayoffSeries(blockedState,1,2,12345,7);
assert.equal(blocked.researchReady,false);
assert.equal(blocked.winnerTeamId,null);
assert(blocked.blockers.length>0);
assert.equal(p.runExperimentalPlayoffRound(blockedState,bracket,12345,7).winners,null);
assert.throws(()=>p.validateSeriesTeams(1,1,7),TypeError);
assert.throws(()=>p.validateSeriesTeams(1,2,6),RangeError);
assert.throws(()=>p.buildExperimentalBracket([{teamId:1},{teamId:1}]),TypeError);
assert.throws(()=>p.buildExperimentalBracket([{teamId:1},{teamId:2},{teamId:3}]),RangeError);
assert.throws(()=>p.playoffHomeTeam(7,1,2),RangeError);
assert.throws(()=>p.simulateExperimentalPlayoffSeries(state,1,2,-1,7),RangeError);
const corrupted={...series,wins:{...series.wins,[String(series.winnerTeamId)]:0}};
assert.equal(p.playoffSeriesAudit(corrupted).consistent,false);
assert.throws(()=>p.playoffSeriesSummary(corrupted),/Inconsistent/);
console.log('Batch 773-780 experimental playoff series tests passed.');
