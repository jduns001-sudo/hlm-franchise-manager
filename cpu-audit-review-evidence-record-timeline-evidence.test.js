'use strict';
const assert=require('node:assert/strict');
const records=require('./cpu-audit-review-evidence-timeline-record');
const presentation=require('./cpu-audit-review-evidence-timeline-presentation');
const bundles=require('./cpu-audit-review-evidence-record-timeline-bundle');
const api=require('./cpu-audit-review-evidence-record-timeline-evidence');
const summary={kind:'cpu-audit-public-review-evidence-timeline-summary',readOnly:true,count:2,reviewCount:0,reviewStateChanges:0,transitionCount:1};
const record=records.create({kind:'cpu-audit-public-review-evidence-timeline-bundle',readOnly:true,summary,text:presentation.describe(summary)});
const clean=api.create(bundles.build([record,record]));
assert.equal(clean.requiresHumanReview,false);
assert.equal(clean.summary.count,2);
assert.ok(Object.isFrozen(clean)&&Object.isFrozen(clean.reasons));
assert.deepEqual(api.parse(api.stringify(clean)),clean);
const empty=api.create(bundles.build([]));
assert.equal(empty.requiresHumanReview,true);
assert.equal(empty.reasons.length,1);
assert.throws(()=>api.validate({...clean,requiresHumanReview:true}),TypeError);
assert.throws(()=>api.validate({...clean,reasons:['forged']}),TypeError);
assert.throws(()=>api.validate({...clean,summary:{...clean.summary,reviewCount:3}}),TypeError);
assert.throws(()=>api.parse('x'.repeat(1025)),TypeError);
console.log('Aggregate review evidence record timeline evidence tests passed');
