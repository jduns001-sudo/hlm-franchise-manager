'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createIsolatedCPUTradeCandidate}=require('./hlm-phase9-cpu-isolated-trade-candidate');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}],draftPicks:[{pickId:'d1',ownerTeamId:'NYR'}]});
const before=JSON.stringify(state);
const input={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]},{fromTeamId:'NYR',toTeamId:'BUF',assets:[{type:'draft-pick',id:'d1',ownerTeamId:'NYR'}]}],playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,humanGMApproved:true,transactionId:'cpu-trade-001'};
const result=createIsolatedCPUTradeCandidate(state,'BUF',input);
assert.equal(result.assetCount,2);
assert.equal(result.candidateState.universe.players[0].teamId,'NYR');
assert.equal(result.candidateState.assets.draftPicks[0].ownerTeamId,'BUF');
assert.equal(result.liveExecutionPerformed,false);
assert.equal(result.persistencePerformed,false);
assert.equal(result.readyForLiveExecution,false);
assert.equal(JSON.stringify(state),before);
assert.throws(()=>createIsolatedCPUTradeCandidate(state,'PIT',input),/human franchise/);
assert.throws(()=>createIsolatedCPUTradeCandidate(state,'BUF',{...input,humanGMApproved:false}),/approval/);
assert.throws(()=>createIsolatedCPUTradeCandidate(state,'BUF',{...input,teamIds:['BUF','NYR','PIT']}),/Human-controlled/);
assert.throws(()=>createIsolatedCPUTradeCandidate(state,'BUF',{...input,legs:[...input.legs,input.legs[0]]}),/Same asset/);
const wrong={...input,legs:[{...input.legs[0],assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]},{...input.legs[1],assets:[{type:'draft-pick',id:'d1',ownerTeamId:'NYR'}]}]};
assert.equal(createIsolatedCPUTradeCandidate(state,'BUF',wrong).candidateOnly,true);
console.log('Phase 9 isolated CPU trade candidate integration tests passed');
