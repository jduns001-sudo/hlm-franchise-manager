'use strict';
const assert=require('node:assert/strict');
const {exportGMReviewEvidence}=require('./hlm-phase11-gm-review-evidence-export');
const {describeGMReviewDigest}=require('./hlm-phase11-gm-review-digest-accessibility');
const home=Array.from({length:4},()=>({shots:10,goals:1,expectedGoals:2}));
const away=Array.from({length:4},()=>({shots:8,goals:0,expectedGoals:1}));
const a=exportGMReviewEvidence(home,away,[5,10],[5]);
const b=exportGMReviewEvidence(home,away,[5,10,25],[10]);
const result=describeGMReviewDigest(a.text,b.text);
assert.equal(result.valid,true);
assert.equal(result.text,'3 review-state changes. 1 completed review. 1 reopened review. 1 scope change.');
assert.equal(result.saveWriteAllowed,false);
assert.equal(result.gameplayActionAuthorized,false);
assert.equal(result.productionActivationEnabled,false);
assert.equal(result.requiresGMApproval,true);
assert.equal(describeGMReviewDigest(a.text,a.text).text,'No review-state changes.');
assert.equal(describeGMReviewDigest('{',b.text).valid,false);
assert.deepEqual(describeGMReviewDigest(a.text,b.text),result);
assert.ok(Object.isFrozen(result));
console.log('GM review digest accessibility deterministic tests passed');
