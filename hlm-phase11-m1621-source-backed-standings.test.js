'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {calculateStandings}=require('./hlm-phase10-standings');
const {project}=require('./hlm-phase11-m1621-source-backed-standings');
const teams=[{id:1,name:'GM'},{id:2,name:'CPU North'},{id:3,name:'CPU South'}];
const finalA={id:'a',date:'2026-10-19',homeTeamId:2,awayTeamId:3,status:'final',homeGoals:4,awayGoals:2,overtime:false};
const finalB={id:'b',date:'2026-10-20',homeTeamId:1,awayTeamId:2,status:'final',homeGoals:2,awayGoals:3,overtime:true};
const scheduled={id:'c',date:'2026-10-21',homeTeamId:3,awayTeamId:1,status:'scheduled'};
const state=createGameStateEnvelope({meta:{controlledTeamId:1,currentDate:'2026-10-20'},teams,games:[finalA,finalB,scheduled]});
const before=JSON.stringify(state),view=project(state);
assert.deepEqual(view.standings,calculateStandings(teams,state.activity.games),'reuse authoritative scoring');
assert.equal(view.results.length,2,'scheduled games do not become results');
assert.equal(view.results[0].id,'b','latest final first');
assert.equal(view.results[0].overtime,true);
assert.equal(view.standings.find(t=>t.teamId===2).points,4);
assert.equal(view.standings.find(t=>t.teamId===1).otl,1);
assert.equal(JSON.stringify(state),before,'projection never mutates source');
assert.ok(Object.isFrozen(view)&&Object.isFrozen(view.standings)&&Object.isFrozen(view.results));
assert.deepEqual(project(JSON.parse(JSON.stringify(state))),view,'reload reproduces same projection');
const withGames=games=>({...state,activity:{...state.activity,games}});
assert.throws(()=>project(withGames([finalA,finalA])),/Duplicate authoritative game id/);
assert.throws(()=>project(withGames([{...finalA,homeGoals:2,awayGoals:2}])),/Invalid authoritative final score/);
assert.throws(()=>project(withGames([{...finalA,homeGoals:undefined}])),/Invalid authoritative final score/);
assert.throws(()=>project(withGames([{...finalA,overtime:'yes'}])),/Invalid authoritative overtime flag/);
assert.throws(()=>project(withGames([{...finalA,awayTeamId:999}])),/Invalid authoritative game teams/);
assert.throws(()=>project(withGames([{...finalA,status:'unknown'}])),/Unsupported authoritative game status/);
assert.throws(()=>project({...state,universe:{...state.universe,teams:[...teams,teams[0]]}}),/Duplicate authoritative team id/);
assert.equal(project(withGames([scheduled])).results.length,0);
assert.equal(project(withGames([scheduled])).standings.every(t=>t.gp===0),true);
console.log('Mission 1621 pure source-backed standings and results Node acceptance PASS');
