'use strict';
const assert=require('node:assert/strict');
const universe=require('./hlm-universe.json');
const {build}=require('./hlm-phase11-new-franchise');
const {create:season}=require('./hlm-phase11-isolated-single-game');
const {create}=require('./hlm-phase11-m1573-season-trade-source');
const engine={...require('./hlm-game-state'),...require('./hlm-phase10-season-schedule'),...require('./hlm-phase10-browser-storage'),
 ...require('./hlm-phase10-apply-game'),...require('./hlm-phase10-standings'),...require('./hlm-phase10-simulate-day')};
const memory=new Map([['hlm_front_office_v8','PRODUCTION_SENTINEL']]);
const storage={getItem:key=>memory.get(key)??null,setItem:(key,value)=>memory.set(key,value)};
const manager=season(engine,storage),panel=create(()=>manager.peek());
assert.equal(panel.choices().ready,false);assert.equal(memory.size,1);
const initial=build(universe,5,engine);manager.stage(initial,true);
const before=storage.getItem(manager.key),choices=panel.choices();
assert.equal(choices.controlledTeamId,'5');assert.equal(choices.teamName,'Pittsburgh');
assert.equal(choices.outgoing.length,initial.universe.players.filter(p=>p.teamId===5).length);
assert.ok(choices.incoming.length>100);
assert.ok(choices.outgoing.every(p=>p.teamId==='5'));assert.ok(choices.incoming.every(p=>p.teamId!=='5'));
const input={outgoingPlayerId:choices.outgoing[0].id,incomingPlayerId:choices.incoming[0].id};
const reviewed=panel.review(input);
assert.equal(reviewed.source,'current-saved-isolated-season');
assert.equal(reviewed.saved,false);assert.equal(reviewed.settlementAuthorized,false);assert.equal(reviewed.cpuConsentAuthenticated,false);
assert.ok(reviewed.players.every(p=>p.contractStatus==='active-contract-unavailable'&&p.aav===null),'real starter roster must not become invented contracts');
reviewed.players[0].name='Altered view';choices.outgoing[0].name='Altered choice';
assert.equal(storage.getItem(manager.key),before,'selection and source review never save');
assert.throws(()=>panel.review({...input,outgoingPlayerId:input.incomingPlayerId}),/different/);
manager.advanceNextDay(1573,true);
assert.throws(()=>panel.review(input),/Saved season changed/,'actual game-day advancement invalidates old trade view');
assert.ok(panel.choices().ready);assert.equal(panel.review(input).saved,false);
assert.equal(storage.getItem('hlm_front_office_v8'),'PRODUCTION_SENTINEL');
assert.deepEqual(initial.assets.contracts,[]);
// Contract evidence is read only if uniquely present and matches saved ownership.
let state=structuredClone(manager.peek());const direct=create(()=>state);direct.choices();
state.assets.contracts=[{playerId:input.outgoingPlayerId,teamId:5,status:'active',aav:4}];direct.choices();
assert.equal(direct.review(input).players[0].aav,4);
state.assets.contracts.push({...state.assets.contracts[0]});direct.choices();
assert.equal(direct.review(input).players[0].contractStatus,'ambiguous-active-contract');
assert.equal(direct.review(input).players[0].aav,null);
state.assets.contracts=[{playerId:input.outgoingPlayerId,teamId:3,status:'active',aav:4}];direct.choices();
assert.equal(direct.review(input).players[0].contractStatus,'active-contract-unavailable');
state.universe.players.push({...state.universe.players[0]});assert.throws(()=>direct.choices(),/ambiguous/);
console.log('M1573 actual real-universe season: saved roster selection, honest missing contracts, read-only review, game-day stale rejection and production isolation passed');
