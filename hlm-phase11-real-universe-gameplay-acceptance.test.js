'use strict';
const assert=require('node:assert/strict');
const {previewImportedFranchiseGame:preview}=require('./hlm-phase11-real-universe-gameplay-acceptance');
const positions=['C','LW','RW','D','D','G'];
const players=[1,2].flatMap(teamId=>positions.map((position,i)=>({id:teamId*100+i,name:'Player '+teamId+'-'+i,teamId,position,ovr:teamId===1?85:75})));
const legacy={teams:[{id:1,name:'Owner'},{id:2,name:'CPU'}],players,contracts:players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'})),injuries:players.map(p=>({playerId:p.id,status:'Recovered'})),draftPicks:[{pickId:'pick1',currentOwnerId:1}],prospects:[]};
const options={controlledTeamId:1,currentDate:'2026-10-12',games:[{id:'G1',status:'scheduled',homeTeamId:1,awayTeamId:2}],gameId:'G1',seed:11};
const before=JSON.stringify(legacy),opts=JSON.stringify(options);
const result=preview(legacy,options);
assert.equal(result.summary.teamCount,2);
assert.equal(result.summary.playerCount,12);
assert.equal(result.readiness.snapshot.scheduledGames,1);
assert.equal(result.game.gameId,'G1');
assert.equal(result.game.canApplyOfficialResult,false);
assert.equal(result.game.persistencePerformed,false);
assert.equal(result.persistencePerformed,false);
assert.equal(result.game.exhibition.rosterRating.home,85);
assert.equal(result.game.exhibition.rosterRating.away,75);
assert.deepEqual(result,preview(legacy,options));
assert.equal(JSON.stringify(legacy),before);
assert.equal(JSON.stringify(options),opts);
const badGame={...options,games:[{...options.games[0],awayTeamId:99}]};
const invalid=preview(legacy,badGame);
assert.equal(invalid.ready,false);
assert(invalid.readiness.issues.some(i=>i.code==='INVALID_GAME_TEAMS'));
assert.equal(invalid.game,null);
assert.throws(()=>preview(legacy,{...options,controlledTeamId:99}),/Controlled team not found/);
assert.throws(()=>preview(legacy,{...options,games:[]}),/Scheduled games required/);
console.log('Phase 11 real-universe Front Office roster preview integration passed');
