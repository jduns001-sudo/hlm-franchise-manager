'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {createMemorySaveRepository}=require('./hlm-save-repository');
const {serializeGameState}=require('./hlm-game-state-serialization');
const {persistApprovedCPUSeasonTransition}=require('./hlm-phase9-cpu-season-transition-save');
const repository=createMemorySaveRepository();
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT',currentDate:'2030-06-30'},teams:[{id:'PIT'},{id:'BUF'},{id:'NYR'}],players:[{id:'p1',teamId:'BUF'}]});
state.history.seasons.push({id:'2029-30',status:'completed',champion:'PIT'});
repository.save('original',state);
const expectedSourceFingerprint=serializeGameState(repository.load('original').state);
const trade={teamIds:['BUF','NYR'],legs:[{fromTeamId:'BUF',toTeamId:'NYR',assets:[{type:'player',id:'p1',ownerTeamId:'BUF'}]}],humanGMApproved:true,playerProtectionVerified:true,leagueRulesVerified:true,capRulesVerified:true,transactionId:'season-t1'};
const transition={fromSeasonId:'2029-30',toSeasonId:'2030-31',nextDate:'2030-07-01',steps:[{teamId:'BUF',trade}]};
const run=(changes={})=>persistApprovedCPUSeasonTransition({repository,sourceSlotId:'original',destinationSlotId:'next',expectedSourceFingerprint,transition,confirmCommit:true,...changes});
assert.throws(()=>run({confirmCommit:false}),e=>e.code==='CPU_SEASON_SAVE_APPROVAL_REQUIRED');
assert.throws(()=>run({expectedSourceFingerprint:'stale'}),e=>e.code==='CPU_SEASON_SAVE_SOURCE_STALE');
assert.throws(()=>run({destinationSlotId:'original'}),e=>e.code==='CPU_SEASON_SAVE_SOURCE_PROTECTED');
assert.throws(()=>run({transition:{...transition,nextDate:'2030-06-29'}}),e=>e.code==='CPU_SEASON_TRANSITION_DATE_ORDER');
assert.equal(repository.count(),1);
const result=run();
assert.equal(result.verified,true);
assert.equal(result.activeFranchiseSlotReplaced,false);
assert.equal(result.productionCPUExecutionEnabled,false);
const next=repository.load('next').state;
assert.equal(next.history.seasons.length,2);
assert.equal(next.history.seasons[1].id,'2030-31');
assert.equal(next.meta.currentDate,'2030-07-01');
assert.equal(next.meta.controlledTeamId,'PIT');
assert.equal(next.universe.players[0].teamId,'NYR');
assert.equal(next.activity.transactions[0].id,'season-t1');
assert.equal(serializeGameState(repository.load('original').state),expectedSourceFingerprint);
assert.throws(()=>run(),e=>e.code==='CPU_SEASON_SAVE_DESTINATION_OCCUPIED');
console.log('Phase 9 CPU season transition save tests passed');
