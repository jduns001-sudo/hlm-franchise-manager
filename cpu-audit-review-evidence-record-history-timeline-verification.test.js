'use strict';
const assert=require('node:assert/strict');
const evidence=require('./cpu-audit-review-evidence-record-history-evidence');
const presentation=require('./cpu-audit-review-evidence-record-history-presentation');
const bundles=require('./cpu-audit-review-evidence-record-history-timeline-bundle');
const gates=require('./cpu-audit-review-evidence-record-history-timeline-gate');
const api=require('./cpu-audit-review-evidence-record-history-timeline-verification');
const summary={kind:'cpu-audit-public-review-evidence-record-history-summary',readOnly:true,count:2,reviewCount:0,reviewStateChanges:0,transitionCount:1};
const record=evidence.create({kind:'cpu-audit-public-review-evidence-record-history-bundle',readOnly:true,summary,text:presentation.describe(summary)});
const bundle=bundles.build([record,record]),gate=gates.assess(bundle);
const result=api.verify(bundle,gate);
assert.equal(result.verified,true);
assert.equal(result.requiresHumanReview,false);
assert.equal(result.snapshotCount,2);
assert.ok(Object.isFrozen(result));
assert.equal(api.verify(bundles.build([]),gates.assess(bundles.build([]))).requiresHumanReview,true);
assert.throws(()=>api.verify(bundle,{...gate,requiresHumanReview:true}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,snapshotCount:1}),TypeError);
assert.throws(()=>api.verify(bundle,{...gate,reasons:['forged']}),TypeError);
assert.throws(()=>api.verify({...bundle,text:'forged'},gate),TypeError);
console.log('Aggregate review evidence record history timeline verification tests passed');
