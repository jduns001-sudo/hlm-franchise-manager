'use strict';
const assert=require('node:assert/strict');
const {createGameStateEnvelope}=require('./hlm-game-state');
const {inspectCPUExecutionBoundary}=require('./hlm-phase9-cpu-execution-boundary');
const state=createGameStateEnvelope({meta:{controlledTeamId:'PIT'},teams:[{id:'PIT',name:'Pittsburgh'},{id:'NYR',name:'New York'}],players:[],contracts:[],draftPicks:[]});
const before=JSON.stringify(state);
const priority={evaluation:{identification:{problems:[{id:'cap',category:'cap',severity:'high'}]},options:[{id:'trade',problemId:'cap',type:'trades'}]},priorities:[{id:'first',optionId:'trade',tier:'high',order:1}]};
const decision={prioritization:priority,priorityId:'first',authorized:true,execute:true};
const cpu=inspectCPUExecutionBoundary(state,'NYR',{decision});
assert.equal(cpu.cpuVerified,true);
assert.equal(cpu.canExecute,false);
assert.ok(cpu.blockers.includes('cpu-executor-not-implemented'));
const human=inspectCPUExecutionBoundary(state,'PIT',{decision});
assert.equal(human.humanControlled,true);
assert.ok(human.blockers.includes('human-controlled-team-protected'));
const denied=inspectCPUExecutionBoundary(state,'NYR',{decision:{...decision,authorized:false}});
assert.equal(denied.cpuVerified,false);
assert.ok(denied.blockers.includes('cpu-advisory-preflight-not-verified'));
assert.equal(JSON.stringify(state),before);
assert.ok(Object.isFrozen(cpu)&&Object.isFrozen(cpu.blockers));
assert.throws(()=>inspectCPUExecutionBoundary({},'NYR'),TypeError);
assert.throws(()=>inspectCPUExecutionBoundary(state,'UNKNOWN'),/Team not found/);
console.log('Phase 9 CPU execution boundary integration tests passed');
