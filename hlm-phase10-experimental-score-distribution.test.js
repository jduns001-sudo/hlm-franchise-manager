'use strict';
const assert = require('node:assert/strict');
const { createGameStateEnvelope } = require('./hlm-game-state');
const { createExperimentalScoreDistribution: distribution, MAX_SAMPLES } = require('./hlm-phase10-experimental-score-distribution');
const positions=['C','LW','RW','D','D','G'];
const players=[...positions.map((position,i)=>({id:10+i,teamId:1,position,ovr:80})),...positions.map((position,i)=>({id:20+i,teamId:2,position,ovr:70}))];
const contracts=players.map(p=>({playerId:p.id,teamId:p.teamId,status:'Active'}));
const injuries=players.map(p=>({playerId:p.id,status:'Recovered'}));
const state=createGameStateEnvelope({teams:[{id:1,name:'Wolves'},{id:2,name:'Bears'}],players,contracts,injuries});
const before=JSON.stringify(state);
const a=distribution(state,1,2,12345,12);
assert.equal(a.researchReady,true);
assert.equal(a.samples.length,12);
assert.deepEqual(distribution(state,1,2,12345,12),a);
assert.notDeepEqual(distribution(state,1,2,98765,12).samples,a.samples);
assert.equal(JSON.stringify(state),before);
assert(a.samples.every(s=>Number.isInteger(s.home)&&s.home>=0&&Number.isInteger(s.away)&&s.away>=0));
assert(Number.isFinite(a.meanHypotheticalGoals.home));
for(const flag of ['simulationAuthorized','gameResultCreated','standingsUpdated','sourceStateMutated','persistencePerformed']) assert.equal(a[flag],false);
const missing=createGameStateEnvelope({teams:state.universe.teams,players,contracts:contracts.filter(c=>c.playerId!==20),injuries});
const blocked=distribution(missing,1,2,12345,12);
assert.equal(blocked.researchReady,false);
assert.deepEqual(blocked.samples,[]);
assert.equal(blocked.meanHypotheticalGoals,null);
assert(blocked.blockers.length>0);
for(const count of [0,-1,1.5,MAX_SAMPLES+1,NaN]) assert.throws(()=>distribution(state,1,2,12345,count),RangeError);
for(const seed of [-1,2**32,1.5]) assert.throws(()=>distribution(state,1,2,seed,1),RangeError);
console.log('Mission 752 seeded hypothetical distribution tests passed.');
