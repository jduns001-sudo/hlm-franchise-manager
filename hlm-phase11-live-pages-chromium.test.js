'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {createGameStateEnvelope}=require('./hlm-game-state');
const base='https://jduns001-sudo.github.io/hlm-franchise-manager/';
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage();
  const failures=[];
  page.on('pageerror',e=>failures.push(e.message));
  const bundle=await page.request.get(base+'hlm-phase11-browser-simulation.bundle.js',{timeout:30000});
  assert.equal(bundle.status(),200,'GitHub Pages must serve real browser bundle');
  const source=await bundle.text();
  assert.match(source,/HLMPhase11SimBundle/);
  assert.ok(source.length>20000,'Expected full compiled Phase 10 bundle');
  const response=await page.goto(base+'hlm-phase11-real-finance.html',{waitUntil:'load',timeout:30000});
  assert.equal(response.status(),200);
  assert.equal(await page.locator('#enable').isChecked(),false);
  assert.equal(await page.locator('#previewDay').isDisabled(),true);
  assert.equal(await page.locator('#commitDay').isDisabled(),true);
  const state=createGameStateEnvelope({meta:{saveId:'live-ci',currentDate:'2026-10-12',controlledTeamId:1},teams:[{id:1,name:'Home'},{id:2,name:'Away'}],contracts:[{id:1,teamId:1,annualSalary:80000000}],games:[{id:'g1',date:'2026-10-13',homeTeamId:1,awayTeamId:2,status:'scheduled'}]});
  await page.evaluate(()=>localStorage.setItem('hlm-phase10-save','LIVE_CI_SENTINEL'));
  await page.locator('#enable').check();
  assert.equal(await page.locator('#previewDay').isEnabled(),true,'real browser bundle loaded');
  page.on('dialog',d=>d.accept());
  await page.locator('#file').setInputFiles({name:'ci-franchise.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(state))});
  await page.locator('#import').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Imported'));
  await page.locator('#calculate').click();
  const finance=JSON.parse(await page.locator('#output').textContent());
  assert.ok(finance.financialDashboard,'owner financial dashboard must render');
  assert.ok(finance.cpuRecommendation,'CPU recommendation must render');
  await page.locator('#previewDay').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('preview generated'));
  const preview=JSON.parse(await page.locator('#output').textContent());
  assert.equal(preview.fromDate,'2026-10-12');
  assert.equal(preview.toDate,'2026-10-13');
  assert.ok(preview.finances && preview.finances.teamSnapshots,'owner and CPU snapshots present');
  assert.ok(Object.keys(preview.finances.teamSnapshots).length>=2,'all teams receive financial snapshots');
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('hlm-phase11-finance-browser-preview-v1')).meta.currentDate),'2026-10-12');
  await page.locator('#commitDay').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Isolated simulation saved'));
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('hlm-phase11-finance-browser-preview-v1')).meta.currentDate),'2026-10-13');
  assert.equal(await page.evaluate(()=>localStorage.getItem('hlm-phase10-save')),'LIVE_CI_SENTINEL');
  assert.deepEqual(failures,[],'no uncaught browser errors');
  const front=await page.request.get(base+'app.html');
  assert.equal(front.status(),200,'default Front Office still served');
  console.log('PASS: live GitHub Pages bundle, opt-in, actual Phase 10 day, finance CPU/owner snapshots, explicit isolated confirmation, production save and Front Office intact');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
